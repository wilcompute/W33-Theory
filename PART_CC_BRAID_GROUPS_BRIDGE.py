# ---------------------------------------------------------------------------
# Audit function
# ---------------------------------------------------------------------------

def braid_groups_bridge_audit() -> Dict[str, Any]:
    categories = {
        "atom_checks": _make_atom_checks(),
        "generator_checks": _make_generator_checks(),
        "burau_checks": _make_burau_checks(),
        "catalan_checks": _make_catalan_checks(),
        "garside_checks": _make_garside_checks(),
        "structural_checks": _make_structural_checks(),
    }

    all_checks = [c for checks in categories.values() for c in checks]
    failed = [c.name for c in all_checks if not c.passes]
    passing = len(all_checks) - len(failed)

    return {
        "status": "PASS" if not failed else "FAIL",
        "all_checks_pass": not bool(failed),
        "check_count": len(all_checks),
        "checks_passing": passing,
        "failed_checks": failed,
        "category_counts": {k: len(v) for k, v in categories.items()},
        "garside_lengths": {
            "B3": GARSIDE_B3,
            "B5": GARSIDE_B5,
            "B8": GARSIDE_B8,
            "B12": GARSIDE_B12,
        },
        "tl_dimensions": {
            "TL2": TL_DIM_2,
            "TL3": TL_DIM_3,
            "TL4": TL_DIM_4,
            "TL5": TL_DIM_5,
        },
        "w33_atoms": {
            "Q": Q, "LAM": LAM, "V": V, "K": K,
            "PHI3": PHI3, "PHI4": PHI4, "PHI6": PHI6,
            "J_INV": J_INV, "EDGES": EDGES, "EIG_MAX": EIG_MAX,
        },
        "theorem_cc": (
            "Every key parameter of braid groups B_n for n ∈ {Q, LAM², PHI3, PHI4, "
            "PHI6, J_INV, K, EIG_MAX} — generator count, Garside element length, "
            "Temperley-Lieb dimension, reduced Burau dimension, and permutation count — "
            "is an integer expression in the W(3,3) atoms with zero free parameters: "
            "gen(B_5)=LAM², Δ_3 length=Q, Δ_5 length=PHI4, TL_3 dim=EIG_MAX, "
            "TL_2 dim=LAM, Q!=MULT_K2, gen(B_8)=PHI6, gen(B_{13})=K."
        ),
    }


def main() -> None:
    result = braid_groups_bridge_audit()
    out_path = os.path.join(os.path.dirname(__file__),
                            "PART_CC_braid_groups_results.json")
    with open(out_path, "w") as fh:
        json.dump(result, fh, indent=2)

    n = result["check_count"]
    p = result["checks_passing"]
    status = result["status"]
    print(f"PART_CC Braid Groups Bridge: {status} ({p}/{n} checks pass)")
    if result["failed_checks"]:
        print(f"  FAILED: {result['failed_checks']}")


if __name__ == "__main__":
    main()
