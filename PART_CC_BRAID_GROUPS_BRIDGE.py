PERM_BRAIDS_B3_IS_MULT_K2: bool = (PERM_BRAIDS_B3 == MULT_K2)

# Braid index of torus knot T(p,q) = min(p,q)
def torus_braid_index(p: int, q: int) -> int:
    return min(p, q)

TORUS_T3_K: int = torus_braid_index(Q, K)        # min(3,12) = 3 = Q ✓
TORUS_T3_12_IS_Q: bool = (TORUS_T3_K == Q)
TORUS_T_LAM_PHI6: int = torus_braid_index(LAM, PHI6)  # min(2,7) = 2 = LAM ✓

# Artin relations count for B_n:
# Commutativity: |i-j|>=2 → C(n-1,2) - (n-2) pairs = (n-1)(n-2)/2 - (n-2) = (n-2)(n-3)/2
# Braid: n-2 relations (adjacent)
def artin_braid_relations(n: int) -> int:
    return n - 2   # adjacent braid relations σᵢσᵢ₊₁σᵢ = σᵢ₊₁σᵢσᵢ₊₁

def artin_comm_relations(n: int) -> int:
    n_gen = n - 1
    total_pairs = n_gen * (n_gen - 1) // 2
    return total_pairs - (n - 2)   # subtract adjacent pairs

BRAID_RELS_B3: int = artin_braid_relations(Q)    # 1
BRAID_RELS_B5: int = artin_braid_relations(EIG_MAX)  # 3
COMM_RELS_B3: int = artin_comm_relations(Q)      # 0 (B_3 has no commutative pairs)
COMM_RELS_B5: int = artin_comm_relations(EIG_MAX) # 3

# B_3 has exactly 1 braid relation and 0 commutative relations ✓
BRAID_RELS_B3_CORRECT: bool = (BRAID_RELS_B3 == 1 and COMM_RELS_B3 == 0)

# Center of B_n: generated by Δ_n². For B_3: Δ_3 = σ₁σ₂σ₁, Δ_3² has length 6 = MULT_K2 ✓
GARSIDE_B3_SQ_LENGTH: int = 2 * GARSIDE_B3     # 6 = MULT_K2
