# B_Q = B_3: first infinite non-abelian braid group
BRAID_FIRST_NONABELIAN: int = Q         # 3 strands

# Generator count for B_n = n-1
def gen_count(n: int) -> int:
    return n - 1

GEN_COUNT_B3: int = gen_count(Q)       # 2 = LAM ✓
GEN_COUNT_B5: int = gen_count(EIG_MAX) # 4 = LAM²
GEN_COUNT_B8: int = gen_count(J_INV)   # 7 = PHI6
GEN_COUNT_B12: int = gen_count(K)      # 11 = PHI3 - LAM
GEN_COUNT_B13: int = gen_count(PHI3)   # 12 = K

# Reduced Burau representation dimension for B_n = n-1
BURAU_DIM_B3: int = Q - 1        # 2 = LAM
BURAU_DIM_B5: int = EIG_MAX - 1  # 4 = LAM²
BURAU_DIM_B8: int = J_INV - 1    # 7 = PHI6

# Full Burau representation dimension = n × n
BURAU_FULL_DIM_B3: int = Q**2    # 9
BURAU_FULL_DIM_B12: int = K**2   # 144

# Catalan number C_n (dimension of Temperley-Lieb algebra TL_n)
def catalan(n: int) -> int:
    return math.comb(2 * n, n) // (n + 1)

TL_DIM_2: int = catalan(LAM)       # C_2 = 2 = LAM
TL_DIM_3: int = catalan(Q)         # C_3 = 5 = EIG_MAX ✓
TL_DIM_4: int = catalan(LAM**2)    # C_4 = 14
TL_DIM_5: int = catalan(EIG_MAX)   # C_5 = 42

# TL_Q dimension = C_Q = C_3 = 5 = EIG_MAX ✓
TL_Q_DIM_IS_EIG_MAX: bool = (TL_DIM_3 == EIG_MAX)
# TL_LAM dimension = C_2 = 2 = LAM ✓
TL_LAM_DIM_IS_LAM: bool = (TL_DIM_2 == LAM)

# Garside element: Δ_n has word length n(n-1)/2
def garside_length(n: int) -> int:
    return n * (n - 1) // 2

GARSIDE_B3: int = garside_length(Q)       # 3·2/2 = 3 = Q ✓
GARSIDE_B5: int = garside_length(EIG_MAX) # 5·4/2 = 10 = PHI4 ✓
GARSIDE_B8: int = garside_length(J_INV)   # 8·7/2 = 28
