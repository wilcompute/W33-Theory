PHI4: int = Q**2 + 1            # 10
PHI6: int = Q**2 - Q + 1        # 7
PHI12: int = Q**4 - Q**2 + 1    # 73
J_INV: int = 2 * LAM**2         # 8
EDGES: int = V * K // 2         # 240
EIG_MAX: int = 5
MULT_K2: int = K // 2           # 6

# ---------------------------------------------------------------------------
# Braid group constants expressible via W(3,3) atoms
