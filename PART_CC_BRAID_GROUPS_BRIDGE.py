# For completeness: Markov moves relate B_n traces to knot invariants
# The HOMFLY polynomial has variables a, z (ring Z[a±1, z±1])

# ---------------------------------------------------------------------------
# BraidCheck dataclass
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class BraidCheck:
    name: str
    description: str
    computed: Any
    expected: Any
    exact: bool = True

    @property
    def passes(self) -> bool:
        if self.exact:
            return self.computed == self.expected
        return abs(self.computed - self.expected) < 1e-10


