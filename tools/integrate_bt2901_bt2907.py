def replace_literal(text: str, old: str, new: str, label: str, required: bool = True) -> tuple[str, bool]:
    if new in text:
        return text, False
    if old not in text:
        if required:
            raise RuntimeError(f"missing blueprint anchor: {label}")
        return text, False
    return text.replace(old, new, 1), True


def replace_regex(text: str, pattern: str, replacement: str, label: str, required: bool = True) -> tuple[str, bool]:
    if re.search(pattern, text, flags=re.S) is None:
        if required:
            raise RuntimeError(f"missing blueprint regex anchor: {label}")
        return text, False
    new_text, count = re.subn(pattern, replacement, text, count=1, flags=re.S)
    return new_text, bool(count)


