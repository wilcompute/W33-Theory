def patch_index(path: Path) -> bool:
    text = path.read_text(encoding="utf-8")
    ident = 'id="pass-2901-2907-selector-butterfly-observer"'
    if ident in text:
        return False
    section = '''
<section id="pass-2901-2907-selector-butterfly-observer" class="section theorem-section">
  <div class="section-number">Passes 2901--2907</div>
  <h2>Intrinsic selector channels and nonlinear support diagnosis</h2>
  <p>The three residual selector channels are an affine line with C3 translations and S3 transition functions; no global geometry-equivariant numbering exists.</p>
  <p>A literal q=3 butterfly engine evaluates the fifteen-state quotient in 47 modeled cycles rather than 225 dense serial cycles. The full micro-ISA still requires all 81 frame states for exact execution.</p>
  <p>The 96 typed selector--tomotope tokens carry a regular determinant-twisted group action. The optimal fifteen-mask passage schedule costs 315 and is provably nonlinear: every GL(4,2) Singer cycle costs more.</p>
  <p>The first forty observer classes are not W(3,3); the matching count is explicitly recorded as a falsified identification.</p>
</section>
'''
    marker = "</body>"
    if marker in text:
        text = text.replace(marker, section + marker, 1)
    else:
        text += section
    path.write_text(text, encoding="utf-8")
    return True


def close_registry(path: Path) -> bool:
    data = json.loads(path.read_text(encoding="utf-8"))
    completion = {
        "verifier": "analysis/bt2901_2907_seven_frontiers.py",
        "aggregate_certificate": "data/PART_BT2901_BT2907_SEVEN_FRONTIERS_results.json",
        "tests": "tests/test_bt2901_2907_seven_frontiers.py",
        "rtl": [
            "rtl/w33_pass2902_q3_hadamard_engine.sv",
            "rtl/w33_pass2902_q3_dense_reference.sv",
            "rtl/tb_w33_pass2902_q3_hadamard_engine.sv",
        ],
        "insert": "analysis/BT2901_BT2907_seven_frontiers_insert.tex",
        "blueprint_rewrite": "tools/integrate_bt2901_bt2907.py",
    }
    if data.get("status") == "complete" and data.get("completion") == completion:
        return False
    data["status"] = "complete"
    data["completion"] = completion
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return True


def main() -> None:
    changed: list[str] = []
    for name in ("w33_paper.tex", "photonic_holonet.tex"):
        if patch_wrapper(ROOT / name):
            changed.append(name)
    if patch_blueprint(ROOT / "holonet_machine_blueprint.tex"):
        changed.append("holonet_machine_blueprint.tex")
    if patch_index(ROOT / "docs" / "index.html"):
        changed.append("docs/index.html")
    registry = ROOT / "data" / "w33_pass_namespace_registry_v2.d" / "2901-2907.json"
    if close_registry(registry):
        changed.append(str(registry.relative_to(ROOT)))
    print("changed:", ", ".join(changed) if changed else "none")


if __name__ == "__main__":
    main()
