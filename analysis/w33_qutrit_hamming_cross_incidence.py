OUT = ROOT / "data" / "w33_qutrit_hamming_cross_incidence.json"


def points(q: int):
    return list(itertools.product(range(q), repeat=2))


def cross_matrix(q: int) -> sp.Matrix:
    pts = points(q)
    return sp.Matrix(
        [[1 if (x == a or y == b) else 0 for x, y in pts] for a, b in pts]
    )


def adjacency(q: int) -> sp.Matrix:
    B = cross_matrix(q)
    return B - sp.eye(q * q)


def rank_mod(M: sp.Matrix, p: int) -> int:
    A = [[int(M[i, j]) % p for j in range(M.cols)] for i in range(M.rows)]
    m, n = len(A), len(A[0])
    r = 0
    for c in range(n):
        pivot = next((i for i in range(r, m) if A[i][c] % p), None)
        if pivot is None:
            continue
        A[r], A[pivot] = A[pivot], A[r]
        inv = pow(A[r][c], -1, p)
        A[r] = [(x * inv) % p for x in A[r]]
        for i in range(m):
            if i != r and A[i][c] % p:
                f = A[i][c] % p
                A[i] = [(A[i][j] - f * A[r][j]) % p for j in range(n)]
        r += 1
    return r


def rref_basis_mod2(M: sp.Matrix):
    A = [[int(M[i, j]) & 1 for j in range(M.cols)] for i in range(M.rows)]
    m, n = len(A), len(A[0])
    r = 0
    for c in range(n):
        pivot = next((i for i in range(r, m) if A[i][c]), None)
        if pivot is None:
            continue
        A[r], A[pivot] = A[pivot], A[r]
        for i in range(m):
            if i != r and A[i][c]:
                A[i] = [x ^ y for x, y in zip(A[i], A[r])]
        r += 1
    return A[:r]


def binary_weight_enumerator(M: sp.Matrix):
    basis = rref_basis_mod2(M)
    out = Counter()
    for coeff in itertools.product((0, 1), repeat=len(basis)):
        v = [0] * M.cols
        for c, row in zip(coeff, basis):
            if c:
                v = [x ^ y for x, y in zip(v, row)]
        out[sum(v)] += 1
    return len(basis), dict(sorted(out.items()))


def det_formula(q: int) -> int:
    return ((-1) ** ((q - 1) ** 2)) * (2 * q - 1) * (q - 1) ** (2 * (q - 1))


def inverse_formula(q: int) -> sp.Matrix:
    n = q * q
    A = adjacency(q)
    J = sp.ones(n)
    return (
        sp.Rational(3 - q, q - 1) * sp.eye(n)
        + sp.Rational(1, q - 1) * A
        - sp.Rational(2, (q - 1) * (2 * q - 1)) * J
    )


def control(q: int):
    B = cross_matrix(q)
    A = B - sp.eye(q * q)
    formula = det_formula(q)
    direct = int(B.det())
    assert direct == formula
    assert B * inverse_formula(q) == sp.eye(q * q)

    # intersection census between translated crosses
    pts = points(q)
    inter = Counter()
    for i, (a, b) in enumerate(pts):
        for j, (c, d) in enumerate(pts):
            if i == j:
                kind = "same"
            elif a == c or b == d:
                kind = "hamming_adjacent"
            else:
                kind = "hamming_distance_2"
            inter[(kind, int((B.row(i) * B.row(j).T)[0]))] += 1

    expected = {
        ("same", 2 * q - 1),
        ("hamming_adjacent", q),
        ("hamming_distance_2", 2),
    }
    assert {x for x in inter} == expected

    return {
        "q": q,
        "size": q * q,
        "cross_size": 2 * q - 1,
        "det_direct": direct,
        "det_formula": formula,
        "abs_det": abs(formula),
        "pauli_nonzero_q4_minus_1": q**4 - 1,
        "det_equals_q4_minus_1": abs(formula) == q**4 - 1,
        "inverse_I_coefficient": str(Fraction(3 - q, q - 1)),
        "intersection_types": {
            "same": 2 * q - 1,
            "hamming_adjacent": q,
            "hamming_distance_2": 2,
        },
    }


