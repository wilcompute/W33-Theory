"""Pass 12661: exhaustive decision for q = 8 -- is there a Lagrangian M of F_2^12 with |M cap {Q = 0}| = 1 (resp. exactly the
points of a prescribed small set)?  Symmetry-reduced, de-duplicated level-by-level enumeration.
Coordinates: m = [[x1, x2], [z2, z1]] in M_2(F_q), Q = det m = x1 z1 + x2 z2, omega = Tr of the polar form of det.
G = SL(2,q) x SL(2,q) acts by m -> g m h^T, preserves Q and omega, and is transitive on the covered points (rank-one matrices).
Fix the covered point c = E_11.  Level j = isotropic j-spaces containing c whose only covered point is c.  Level 2 is reduced modulo
Stab_G(c) (Schreier generators); higher levels are generated by adding one admissible vector and de-duplicated by the sorted span.
If level 6 (Lagrangians) is empty for every level-2 orbit representative, no such Lagrangian exists: m*(8) >= 2; the same run with the
'one extra covered point allowed' variant is not attempted (|M cap C| = 2 is excluded separately: see note).
Control: q = 4 must find Lagrangians at level 4.   usage: py -3 analysis/w33_regulus_stabiliser_exhaustive2.py"""
import itertools, json, os, time
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
src = open(os.path.join(HERE, "w33_regulus_constants_q16_q32.py"), encoding="utf-8").read()
g = {"__name__": "x", "__file__": os.path.join(HERE, "w33_regulus_constants_q16_q32.py")}
exec(src[: src.index("def model(")], g)


def run(k, two=False):
    q, mul, trace = g["field"](k); n = 2 * k; N = 4 * k; msk = q - 1; V = 1 << N; t0 = time.time()
    MUL = np.array([[mul(a, b) for b in range(q)] for a in range(q)]); TR = np.array([trace(a) for a in range(q)])
    inv = [0] + [next(b for b in range(1, q) if mul(a, b) == 1) for a in range(1, q)]
    vs = np.arange(V); x1, x2, z1, z2 = vs & msk, (vs >> k) & msk, (vs >> 2 * k) & msk, (vs >> 3 * k) & msk
    pack = lambda a, b, c_, d_: a | (b << k) | (c_ << 2 * k) | (d_ << 3 * k)
    Qv = MUL[x1, z1] ^ MUL[x2, z2]; unc = Qv != 0
    def orth(v):
        a = (v & msk, (v >> k) & msk, (v >> 2 * k) & msk, (v >> 3 * k) & msk)
        return TR[MUL[a[0], z1] ^ MUL[a[1], z2] ^ MUL[a[2], x1] ^ MUL[a[3], x2]] == 0
    # group generators as permutations: m = [[x1, x2], [z2, z1]];  left g: rows; right h: columns
    def perm_left(gm):   # m -> g m
        a, b, c_, d_ = gm
        n11 = MUL[a, x1] ^ MUL[b, z2]; n12 = MUL[a, x2] ^ MUL[b, z1]; n21 = MUL[c_, x1] ^ MUL[d_, z2]; n22 = MUL[c_, x2] ^ MUL[d_, z1]
        return pack(n11, n12, n22, n21)
    def perm_right(hm):  # m -> m h^T
        a, b, c_, d_ = hm
        n11 = MUL[x1, a] ^ MUL[x2, b]; n12 = MUL[x1, c_] ^ MUL[x2, d_]; n21 = MUL[z2, a] ^ MUL[z1, b]; n22 = MUL[z2, c_] ^ MUL[z1, d_]
        return pack(n11, n12, n22, n21)
    lam = 2
    sl2 = [(1, 1, 0, 1), (1, 0, 1, 1), (lam, 0, 0, inv[lam])]
    gens = [perm_left(m_) for m_ in sl2] + [perm_right(m_) for m_ in sl2]
    for p in gens:
        assert sorted(p.tolist()) == list(range(V)) and (Qv[p] == Qv).all()
        u, w = 37 % V, 1234 % V
        assert orth(int(p[u]))[p[w]] == orth(u)[w] and p[u ^ w] == p[u] ^ p[w]
    c = 1; assert not unc[c]
    # Schreier generators of Stab(c)
    trans = {c: np.arange(V)}; fr = [c]; sch = []
    invp = lambda p: np.argsort(p)
    while fr:
        nx = []
        for pt in fr:
            for p in gens:
                img = int(p[pt]); tp = p[trans[pt]]  # tp maps c -> img
                if img not in trans: trans[img] = tp; nx.append(img)
                else:
                    s = invp(trans[img])[tp]
                    if not (s == np.arange(V)).all(): sch.append(s)
        fr = nx
    orbit_size = len(trans)
    # dedupe Schreier generators
    seen = set(); S = []
    for s in sch:
        key = s.tobytes()
        if key not in seen: seen.add(key); S.append(s)
    # level 2: v with omega(c, v) = 0, v and v + c uncovered
    cand = orth(c) & (~unc if two else unc) & unc[vs ^ c]; cand[[0, c]] = False  # two=True: second basis vector is a second covered point
    L2 = np.flatnonzero(cand); parent = {int(v): int(v) for v in L2}
    def find(a):
        while parent[a] != a: parent[a] = parent[parent[a]]; a = parent[a]
        return a
    for v in L2:
        v = int(v)
        if not two: parent[find(v)] = find(v ^ c)
        for s in S[:400]:
            parent[find(v)] = find(int(s[v]))
    reps = sorted({find(int(v)) for v in L2})
    # enumerate upward from each level-2 orbit representative
    def admissible(span):
        m = np.ones(V, bool)
        for s in span: m &= orth(int(s)) if s else m
        for s in span: m &= unc[vs ^ s]
        m &= unc
        m[span] = False
        return m
    total = {j: 0 for j in range(2, n + 1)}; found = None
    for r in reps:
        level = {tuple(sorted({0, c, r, r ^ c}))}
        for j in range(2, n):
            total[j] += len(level); nxt = set()
            for sp in level:
                spa = np.array(sp); m = admissible(spa)
                for v in np.flatnonzero(m):
                    new = tuple(sorted(set(sp) | {int(s ^ v) for s in sp}))
                    nxt.add(new)
            level = nxt
            if not level: break
        if level and len(next(iter(level))) == (1 << n):
            total[n] += len(level); found = found or list(next(iter(level)))
    return dict(q=q, covered_orbit=orbit_size, n_schreier=len(S), level2_candidates=int(len(L2)), level2_orbit_reps=len(reps),
                subspaces_by_dim={str(j): v for j, v in total.items()}, lagrangians_found=total[n],
                status="exists" if total[n] else "none", example=found, seconds=round(time.time() - t0, 1))


out = {}
for k in (2, 3):
    out[f"q{1 << k}"] = run(k); print({a: b for a, b in out[f"q{1 << k}"].items() if a != "example"}, flush=True)
    out[f"q{1 << k}_exactly_two"] = run(k, two=True); print("exactly two:", {a: b for a, b in out[f"q{1 << k}_exactly_two"].items() if a != "example"}, flush=True)
    json.dump(out, open(os.path.join(ROOT, "data", "w33_regulus_stabiliser_exhaustive2.json"), "w"), indent=1)
