def rank(rows):
    piv={}
    for x in rows:
        while x:
            p=x.bit_length()-1
            if p in piv:x^=piv[p]
            else:piv[p]=x;break
    return len(piv)

def points(q):
    P=[]
    for a,b,c in itertools.product(range(q),repeat=3):P.append((1,a,b,c))
    for b,c in itertools.product(range(q),repeat=2):P.append((0,1,b,c))
    for c in range(q):P.append((0,0,1,c))
    P.append((0,0,0,1));return P

def line_bases(q):
    for a,b,c,d in itertools.product(range(q),repeat=4):yield (1,0,a,b),(0,1,c,d)
    for a,b,c in itertools.product(range(q),repeat=3):yield (1,a,0,b),(0,0,1,c)
    for a,b in itertools.product(range(q),repeat=2):yield (1,a,b,0),(0,0,0,1)
    for a,b in itertools.product(range(q),repeat=2):yield (0,1,0,a),(0,0,1,b)
    for a in range(q):yield (0,1,a,0),(0,0,0,1)
    yield (0,0,1,0),(0,0,0,1)

def norm(v,q):
    for x in v:
        if x:
            s=pow(x,-1,q);return tuple(s*y%q for y in v)
    raise ValueError

def sp(u,v,q):return (u[0]*v[2]-u[2]*v[0]+u[1]*v[3]-u[3]*v[1])%q

def null2(rows,q):
    A=[[x%q for x in r] for r in rows];piv=[];rr=0
    for c in range(4):
        k=next((i for i in range(rr,len(A)) if A[i][c]),None)
        if k is None:continue
        A[rr],A[k]=A[k],A[rr];iv=pow(A[rr][c],-1,q);A[rr]=[(x*iv)%q for x in A[rr]]
        for i in range(len(A)):
            if i!=rr and A[i][c]:
                f=A[i][c];A[i]=[(A[i][j]-f*A[rr][j])%q for j in range(4)]
        piv.append(c);rr+=1
    free=[c for c in range(4) if c not in piv];B=[]
    for f in free:
        x=[0]*4;x[f]=1
        for i,p in enumerate(piv):x[p]=(-A[i][f])%q
        B.append(tuple(x))
    assert len(B)==2;return B

def linepts(u,v,q,pi):
    S={pi[norm(v,q)]}
    for a in range(q):S.add(pi[norm(tuple((u[k]+a*v[k])%q for k in range(4)),q)])
    return tuple(sorted(S))

def anchor(q):
    P=points(q);pi={p:i for i,p in enumerate(P)};carriers={};noniso=0
    for u,v in line_bases(q):
        if sp(u,v,q)==0:continue
        noniso+=1;H=linepts(u,v,q,pi)
        rows=[(u[2],u[3],-u[0],-u[1]),(v[2],v[3],-v[0],-v[1])]
        a,b=null2(rows,q);Hp=linepts(a,b,q,pi);C=tuple(sorted(set(H)|set(Hp)));carriers[C]=1
    C=sorted(carriers);rows=[0]*len(P)
    for j,B in enumerate(C):
        for p in B:rows[p]|=1<<j
    return {'q':q,'W_points':len(P),'P_components':len(C),'nonisotropic_lines':noniso,
      'carrier_size':len(C[0]),'point_footprint_weight':next(iter({x.bit_count() for x in rows})),
      'rank_F2':rank(rows),'target_g':q*(q*q+1)//2}

