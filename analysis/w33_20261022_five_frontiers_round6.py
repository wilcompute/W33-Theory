def sparse_point_equivalence():
    """Rank-one spectral duality: dense B model == sparse A model off constants."""
    cases=[]
    for q,c in ((3,1),(9,1),(9,3),(9,4)):
        g=make_geometry(q)
        n=g["n"];b=g["B"].astype(np.int64)
        ones=np.ones((n,n),dtype=np.int64)
        ident=np.eye(n,dtype=np.int64)
        adj=ones-ident-b
        assert np.array_equal(adj,adj.T)
        assert np.all(adj.sum(axis=1)==q*(q+1))
        w=np.array([1,0,0,0],dtype=np.int16)
        v=np.array([0,1,0,0],dtype=np.int16)
        p1=g["trans"](w,1);p2=g["trans"](v,c)
        d=4*ident.copy()
        for perm in (p1,p2):
            t=np.zeros((n,n),dtype=np.int64)
            t[np.arange(n),perm]=1
            d-=t+t.T
            # Every moved T-link connects noncollinear points, i.e. A=0.
            assert all(adj[i,int(perm[i])]==0 for i in range(n) if perm[i]!=i)
        dense=(q**3)*ident-b+d
        sparse=(q**3+1)*ident+adj+d
        assert np.array_equal(sparse-dense,ones)
        assert np.all(d@np.ones(n,dtype=np.int64)==0)
        assert np.all(dense@np.ones(n,dtype=np.int64)==0)
        assert np.all(sparse@np.ones(n,dtype=np.int64)==n*np.ones(n,dtype=np.int64))
        # A strongly regular W(3,q) adjacency has nontrivial eigenvalues q-1,-q-1.
        # Each order-3 transvection defect has PSD spectrum {0,3}; sum <=6.
