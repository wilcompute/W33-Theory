def field(q):
    if q in (4,8):
        def add(a,b):return a^b
        polynomial=0b111 if q==4 else 0b1011
        degree=2 if q==4 else 3
        def mul(a,b):
            out=0
            while b:
                if b&1:out^=a
                b>>=1
                a<<=1
                if a & (1<<degree):a^=polynomial
            return out
        return 2,add,mul
    if q in (3,9,27):
        add,neg,mul=field_ops(q)
        return 3,add,mul
    raise ValueError(q)


def make_geometry(q, full_matrix=True):
    p,add,mul=field(q)
    table=np.asarray([[mul(a,b) for b in range(q)] for a in range(q)], dtype=np.int16)
    plus=np.asarray([[add(a,b) for b in range(q)] for a in range(q)], dtype=np.int16)
    minus=np.asarray([[next(c for c in range(q) if add(b,c)==a) for b in range(q)] for a in range(q)], dtype=np.int16)
    inv=np.asarray([0]+[next(b for b in range(1,q) if mul(a,b)==1) for a in range(1,q)],dtype=np.int16)
    points=[]
    for pivot in range(4):
        for trail in product(range(q), repeat=3-pivot):
            points.append((0,)*pivot+(1,)+trail)
    pts=np.array(points,dtype=np.int16)
    n=len(pts)
    assert n==(q+1)*(q*q+1)
    lookup={tuple(row):i for i,row in enumerate(pts)}
    u=pts[:,0];v=pts[:,1];s=pts[:,2];t=pts[:,3]
    def pairing(w):
        z=np.full(n,0,dtype=np.int16)
        for ai,bi,sgn in [(v,w[0],-1),(u,w[1],+1),(t,w[2],-1),(s,w[3],+1)]:
            term=table[ai,bi]
            z=plus[z,term] if sgn==1 else minus[z,term]
        return z
    def trans(w, coeff=1):
        z=pairing(w)
        new=pts.copy()
        for j in range(4):
            new[:,j]=plus[new[:,j],table[table[z,coeff],w[j]]]
        for i in range(n):
            nonzero=next(j for j in range(4) if new[i,j]!=0)
            new[i]=table[new[i],inv[new[i,nonzero]]]
        ans=np.array([lookup[tuple(x)] for x in new],dtype=np.int32)
        assert len(set(ans.tolist()))==n
        return ans
    if not full_matrix:return {"p":p,"q":q,"pts":pts,"pairing":pairing,"trans":trans}
    omega=np.zeros((n,n),dtype=np.int16)
    for j,w in enumerate(pts):omega[:,j]=pairing(w)
    mat=(omega!=0).astype(np.int16)
    assert np.all(mat.sum(axis=1)==q**3)
    perm=trans(np.asarray([1,0,0,0],dtype=np.int16))
    return {"p":p,"q":q,"n":n,"pts":pts,"B":mat,"perm":perm,"pairing":pairing,"trans":trans}


def modular_basis(rows,p):
    pivots={}
    for row in rows:
        v=np.asarray(row,dtype=np.int64).copy()%p
        while True:
            inds=np.flatnonzero(v)
            if not len(inds):break
            i=int(inds[0])
            if i in pivots:
                v=(v-int(v[i])*pivots[i])%p
            else:
                v=v*pow(int(v[i]),-1,p)%p
                pivots[i]=v
                break
    return pivots


def kernel_from_pivots(pivots,n,p):
    cols=sorted(pivots)
    free=[i for i in range(n) if i not in pivots]
    ker=np.zeros((len(free),n),dtype=np.int16)
    for k,f in enumerate(free):
        x=np.zeros(n,dtype=np.int64);x[f]=1
        for pivot in reversed(cols):
            row=pivots[pivot]
            x[pivot]=(-int(np.dot(row[pivot+1:],x[pivot+1:])))%p
        ker[k]=x
    return ker


def jordan_from_ranks(ranks):
    p=len(ranks)-1
    blocks={str(j):int(ranks[j-1]-2*ranks[j]+ranks[j+1]) for j in range(1,p)}
    blocks[str(p)]=int(ranks[p-1])
    assert sum(int(j)*m for j,m in blocks.items())==ranks[0]
    return blocks


def primepower_module(q):
    g=make_geometry(q);p,n=g["p"],g["n"];Bq=g["B"];perm=g["perm"]
    cb=modular_basis(Bq,p)
    r=len(cb);basis=np.array(list(cb.values()),dtype=np.int16)
    assert not np.any(basis.astype(np.int64)@basis.T%p)
    assert len(modular_basis(list(basis)+list(basis[:,perm]),p))==r
    # D acts by pullback perm: D f = f(perm[i])-f(i).
    def delta(mat):
        return (mat[:,perm]-mat)%p
    # Rank of C and of powers on C.
    c_r=[r];w=basis.copy()
    for k in range(1,p+1):
        w=delta(w)
        c_r.append(len(modular_basis(w,p)))
    # The duality K=(M/C)^* computes K ranks through ambient images.
    # D^k M is generated by p-k vectors for each p-cycle on the affine chart.
    seen=set();cyc=[]
    for start in range(n):
        if start in seen:continue
        cur=[];i=start
        while i not in seen:
            seen.add(i);cur.append(i);i=int(perm[i])
        if len(cur)>1:assert len(cur)==p;cyc.append(cur)
    kr=[n-r]
    for k in range(1,p+1):
        im=[]
        for orbit in cyc:
            for a in range(p-k):
                temp=np.zeros(n,dtype=np.int16)
                # kth finite difference on orbit
                for j in range(k+1):
                    temp[orbit[(a+j)%p]]=(temp[orbit[(a+j)%p]]+math.comb(k,j)*((-1)**(k-j)))%p
                im.append(temp)
        rr=len(modular_basis(list(basis)+im,p))-r
        kr.append(rr)
    # K = ker(C) follows from C=row(B), and is invariant.
    ker=kernel_from_pivots(cb,n,p)
    assert len(ker)==n-r and not np.any((ker.astype(np.int64)@basis.T)%p)
    assert not np.any((delta(ker).astype(np.int64)@basis.T)%p)
    qr=[n-2*r];w=ker.copy()
    for k in range(1,p+1):
        w=delta(w)
        qr.append(len(modular_basis(list(basis)+list(w),p))-r)
    assert qr[-1]==0 and kr[-1]==0 and c_r[-1]==0
    assert all(kr[k]>=c_r[k]+qr[k] for k in range(p+1))
    # C, K and Q Jordan blocks are independent exact modular certificates.
    return {"q":q,"p":p,"n":n,"Cdim":r,"Kdim":n-r,"Qdim":n-2*r,
            "moving_p_cycles":len(cyc),
            "ranks_C":c_r,"ranks_K":kr,"ranks_Q":qr,
            "Jordan_C":jordan_from_ranks(c_r),"Jordan_K":jordan_from_ranks(kr),
            "Jordan_Q":jordan_from_ranks(qr),
            "delta_higher_rank":[kr[k]-c_r[k]-qr[k] for k in range(1,p+1)]}


