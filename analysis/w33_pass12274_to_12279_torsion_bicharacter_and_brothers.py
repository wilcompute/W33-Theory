import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "w33_pass12274_to_12279_torsion_bicharacter_and_brothers.json"
A = ROOT / "analysis"


def main():
    checks, res = {}, {}
    c = json.loads((A / "search_drivers_12274" / "correlate.json").read_text())["table"]
    res["12274"] = c
    get = lambda *k: c.get(str(k), 0)
    b0_same = sum(get(t, "B=0", "identical") for t in ("even", "ctrl", "odd", "oddc"))
    b0_changed = sum(get(t, "B=0", "changed") for t in ("even", "ctrl", "odd", "oddc"))
    changed = sum(get(t, b, "changed") for t in ("even", "ctrl", "odd", "oddc") for b in ("B=0", "B!=0"))
    checks["12274: B = 0 => unchanged 232/232; changed => B != 0 61/61; consistent Z2xZ2 B != 0 => changed 41/44"] = (
        b0_same == 232 and b0_changed == 0 and changed == 61 and get("ctrl", "B!=0", "changed") == 41
        and get("ctrl", "B!=0", "identical") == 3)
    checks["12275: on T6/Z3 B vanishes for all 160 relabellings"] = get("odd", "B=0", "identical") == 80 and get("oddc", "B=0", "identical") == 80
    ex = json.loads((A / "search_drivers_12274" / "exceptions.json").read_text())
    res["12274_exceptions"] = ex["rows"]
    checks["12274: the 3 exceptions carry massless fields in their torsion sectors (necessary, not sufficient)"] = (
        sum(1 for v in ex["rows"].values() if v["spectrum"] == "identical") == 3
        and all(v["massless_fields_in_torsion_sectors"] > 0 for v in ex["rows"].values()))
    z = json.loads((A / "search_drivers_12274" / "z3_theorem_check.json").read_text())
    res["12275"] = z
    checks["12275: consistent shifts B = 0 (37/37), Ploger-violating shifts B != 0 (360/360)"] = (
        z.get("('shift consistent', 'B=0')") == 37 and z.get("('shift violates Ploger', 'B!=0')") == 360
        and "('shift consistent', 'B!=0')" not in z and "('shift violates Ploger', 'B=0')" not in z)
    bc = A / "search_drivers_12276" / "bro_cmp.json"
    if bc.exists():
        b = json.loads(bc.read_text())
        res["12276"] = b["table"]
        res["12276_new_SM_brothers"] = len(b["new_SM_brothers"])
        checks["12276: every control (unshifted) is an SM under the strict engine"] = (
            b["table"].get("('control', 0)", 0) > 0 and not any(k.startswith("('control', ") and not k.endswith(" 0)") for k in b["table"]))
    b2 = json.loads((A / "search_drivers_12277" / "b2496_cmp.json").read_text())
    res["12277"] = b2["summary"]
    vs = {k: v["verdict"] for k, v in b2["per"].items()}
    cl = {k: v["cls"] for k, v in b2["per"].items()}
    checks["12277: SM_2496 W5 brothers -- spectrum changes iff V0.lam odd (8 identical / 8 changed, 790 -> 804 fields)"] = (
        len(vs) == 16 and all((vs[k] == "identical") == (cl[k][0] == 0) for k in vs)
        and all(v["fields"] == 804 for k, v in b2["per"].items() if cl[k][0]) and b2["control"]["fields"] == 790)
    bug = (A / "search_drivers_12268" / "BUG_REPORT_nonSUSYorbifolder.md").read_text(encoding="utf-8")
    checks["12278: bug report names the verbose-only flag and the fix"] = "if(verbose)" in bug and "IsModularInvariant = false;" in bug
    checks = {k: bool(v) for k, v in checks.items()}
    res["checks"] = checks
    res["all_checks_pass"] = all(checks.values())
    OUT.write_text(json.dumps(res, indent=2, default=str))
    print(json.dumps(checks, indent=1), res["all_checks_pass"])
    return res


if __name__ == "__main__":
    main()
