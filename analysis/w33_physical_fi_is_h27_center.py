    assert qpsi["residue_dimensions"]["mod3_CE2_and_physical_FI"]==[86,81,81]
    p=split["physical_FI_center_Z3"]
    assert p["adjoint_eigendimensions"]==[86,81,81]
    assert p["fixed_reductive_algebra"]=="E6+A2"

