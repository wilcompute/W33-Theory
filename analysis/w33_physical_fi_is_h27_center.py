# H27 normal form: Z^a X^b omega^c, (a,b,c) in F3^3.
# ZX=omega XZ gives
#   (a,b,c)(a',b',c')=(a+a',b+b',c+c' - b*a') mod3
# for this ordering convention.
def mul(g,h):
    a,b,c=g; A,B,C=h
    return ((a+A)%3,(b+B)%3,(c+C-b*A)%3)

def inv(g):
    for h in H:
        if mul(g,h)==I and mul(h,g)==I:return h
    raise AssertionError(g)

I=(0,0,0)
H=[(a,b,c) for a in range(3) for b in range(3) for c in range(3)]

def comm(g,h):
    return mul(mul(mul(g,h),inv(g)),inv(h))

