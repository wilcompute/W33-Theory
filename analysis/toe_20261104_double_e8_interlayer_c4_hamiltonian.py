#!/usr/bin/env python3
"""Full-H4-invariant two-sheet E8 root Hamiltonian with 120 C4 interlayer sectors.

The two index-five E8 completions of 25x60 packet kernel are distinct
integral lattices interchanged by row/column swap C. A simple single
coordinate flip F:(u,v)->(u,-v) maps roots of plus to minus and
intertwines the A5xA5 base but NOT the swap C. Symmetry completion
requires both flip maps F1 and F2. This makes the minimal natural
intersheet incidence a union of exactly 120 squares C4, with adjacency
spectrum +-2 (120 each), zero (240). It cannot transport all
root-mode information (half the states are dark) alone.

Adding the E8 root inner-product=1 adjacency within each sheet
makes a 480-node connected regular graph. We certify full A5xA5:C2
symmetry under explicit permutation generators and derive its
numerical spectral census. This is a mathematical tight-binding
toy, not a physical 600-cell waveguide or a TOE.
"""
from __future__ import annotations
import itertools,collections,json,sys
from pathlib import Path
import numpy as np
import networkx as nx
ROOT=Path(__file__).resolve().parents[1]
if str(ROOT/"analysis") not in sys.path:sys.path.insert(0,str(ROOT/"analysis"))
from toe_20261104_reye_kernel_a4a4_e8_glue import roots_scaled5
OUT=ROOT/"data"/"toe_20261104_double_e8_interlayer_c4_hamiltonian.json"
def flip1(v):return tuple(-x for x in v[:5])+v[5:]
def flip2(v):return v[:5]+tuple(-x for x in v[5:])
def swap(v):return v[5:]+v[:5]
def change(v,p,side):
    out=list(v)
    for i in range(5):out[5*side+p[i]]=v[5*side+i]
    return tuple(out)
def main():
    plus=sorted(set(roots_scaled5(2)))
    minus=sorted(set(roots_scaled5(3)))
    assert len(plus)==len(minus)==240
    assert {flip1(v) for v in plus}==set(minus)
    assert {flip2(v) for v in plus}==set(minus)
    assert {swap(v) for v in plus}==set(minus)
    idxplus={v:i for i,v in enumerate(plus)}
    idxminus={v:240+i for i,v in enumerate(minus)}
    axes=plus+minus
    index=[idxplus,idxminus]
    graph=nx.Graph()
    graph.add_nodes_from(range(480))
    inter=set()
    for i,v in enumerate(plus):
        a=idxminus[flip1(v)];b=idxminus[flip2(v)]
        assert a!=b
        graph.add_edge(i,a);graph.add_edge(i,b)
        inter.add(tuple(sorted((i,a))))
        inter.add(tuple(sorted((i,b))))
    assert len(inter)==480
    assert nx.is_regular(graph) and set(dict(graph.degree()).values())=={2}
    components=list(nx.connected_components(graph))
    assert len(components)==120
    assert all(len(c)==4 and graph.subgraph(c).number_of_edges()==4 for c in components)
    Ainter=nx.to_numpy_array(graph,nodelist=list(range(480)),dtype=np.int16)
    eye=np.eye(480,dtype=np.int16)
    assert np.all((Ainter@Ainter@Ainter)==4*Ainter)
    assert np.trace(Ainter@Ainter)==960
    # Full effective H4 packet symmetry generated by A5 on each factor
    # and sheet/coordinate interchange. The base generators separately
    # preserve each integral E8 glue, while the swap exchanges sheets.
    c5=(1,2,3,4,0);c3=(1,2,0,3,4)
    generators=[]
    for side in (0,1):
        for p in (c5,c3):
            mapped=tuple(index[s][change(v,p,side)] for s,roots in enumerate((plus,minus)) for v in roots)
            generators.append(mapped)
    swapped=tuple(index[1-s][swap(v)] for s,roots in enumerate((plus,minus)) for v in roots)
    generators.append(swapped)
    assert len(generators)==5
    assert all(len(set(g))==480 for g in generators)
    def image_edge(u,v,g):
        return tuple(sorted((g[u],g[v])))
    assert all({image_edge(u,v,g) for u,v in inter}==inter for g in generators)
    # A single chosen F1 matching breaks full swap symmetry.
    only_f1={tuple(sorted((i,idxminus[flip1(v)]))) for i,v in enumerate(plus)}
    assert any({image_edge(u,v,g) for u,v in only_f1}!=only_f1 for g in generators)
    assert all({image_edge(u,v,g) for u,v in only_f1}==only_f1 for g in generators[:-1])
    # Add standard E8 240-root adjacency (inner product +1)
    A=np.array(axes,dtype=np.int16)
    # v coordinates represent actual vectors scaled by5. Inner product=1
    # iff dot of scaled-fifths integer vectors =25.
    Aintra=np.zeros((480,480),dtype=np.int16)
    for i in range(2):
        B=A[240*i:240*(i+1)]
        xx=B@B.T
        Aintra[240*i:240*(i+1),240*i:240*(i+1)]=(xx==25)
    assert np.all(np.diag(Aintra)==0)
    assert set(np.sum(Aintra,axis=0))=={56}
    assert int(Aintra.sum()//2)==13440
    intr_edges={tuple(map(int,p)) for p in zip(*np.where(np.triu(Aintra,1)))}
    assert all({image_edge(u,v,g) for u,v in intr_edges}==intr_edges for g in generators)
    # Exact block conjugacy, in F2 coordinate-flip labels:
    # A_combined ~ [[T, I+N],[I+N,T]], with N the antipodal
    # root-inversion operator, N^2=I and [T,N]=0.
    T=Aintra[:240,:240].astype(np.int64)
    N=np.zeros((240,240),dtype=np.int64)
    for i,v in enumerate(plus):
        N[i,idxplus[tuple(-x for x in v)]]=1
    assert np.array_equal(N@N,np.eye(240,dtype=np.int64))
    assert np.array_equal(T@N,N@T)
    P=np.zeros((240,240),dtype=np.int64)
    for i,v in enumerate(plus):P[idxminus[flip2(v)]-240,i]=1
    assert np.array_equal(P.T@P,np.eye(240,dtype=np.int64))
    assert np.array_equal(P.T@Aintra[240:,240:]@P,T)
    assert np.array_equal(Ainter[:240,240:]@P,np.eye(240,dtype=np.int64)+N)
    # Restriction to inversion-even space has T-eigenvalues 56,8,-4.
    # Restriction to inversion-odd space has T-eigenvalues 28,-2.
    I=np.eye(240,dtype=np.int64)
    assert not np.any((T-56*I)@(T-8*I)@(T+4*I)@(I+N))
    assert not np.any((T-28*I)@(T+2*I)@(I-N))
    assert np.trace(N)==0
    # The nonzero inter-sheet coupler B=I+N annihilates the
    # entire 120D odd subspace PER SHEET (240D total).
    assert not np.any((I+N)@(I-N))
    combined=Aintra+Ainter
    assert set(combined.ravel())<={0,1}
    assert set(np.sum(combined,axis=0))=={58}
    G=nx.from_numpy_array(combined)
    assert nx.is_connected(G)
    assert G.number_of_edges()==13920
    eig=np.linalg.eigvalsh(combined.astype(float))
    maxval=float(eig[-1])
    assert abs(maxval-58)<1e-8
    assert len(eig)==480
    assert eig[0]>=-58-1e-8
    sorted_eigs=collections.Counter(str(round(float(x),8)) for x in eig)
    assert sorted_eigs=={'-6.0':84,'-2.0':308,'6.0':35,'10.0':35,'28.0':16,'54.0':1,'58.0':1}
    # Intra-layer E8 adjacency spectrum, verify with direct numerical data.
    a240=Aintra[:240,:240].astype(float)
    eig_e8=np.linalg.eigvalsh(a240)
    spectrum_e8=collections.Counter(str(round(float(v),8)) for v in eig_e8)
    assert abs(eig_e8[-1]-56)<1e-8
    result=dict(status="PASS_FULL_H4_INVARIANT_TWO_E8_SHEET_C4_COUPLER_AND_CONNECTED_ROOT_GRAPH",
        e8_sheet_root_modes=240,number_of_sheets=2,
        shared_40_roots_in_lattices_not_identified_as_same_state=True,
        intersheet_matched_hopping_F1_vs_F2_requires_symmetry_completion=True,
        intersheet_root_coordinate_flips=2,
        intersheet_bipartite_edge_count=len(inter),
        intersheet_degree_per_root=2,
        intersheet_disconnected_components=120,
        intersheet_each_component_is_four_cycle=True,
        intersheet_exact_minimal_polynomial="A^3=4A",
        intersheet_adjacency_spectrum={"-2":120,"0":240,"2":120},
        intersheet_only_has_240_zero_modes=True,
        one_flip_matching_preserves_base_A5xA5_but_breaks_full_swap=True,
        two_flip_completed_matching_preserves_all_five_group_generators=True,
        e8_single_sheet_innerproduct1_degree=56,
        e8_both_sheets_intralayer_edges=13440,
        e8_single_sheet_root_graph_eigenvalues=dict(sorted(spectrum_e8.items(),key=lambda a:float(a[0]))),
        combined_graph_vertices=480,
        combined_graph_regular_degree=58,
        combined_graph_edges=G.number_of_edges(),
        combined_graph_connected=True,
        combined_graph_eigenvalues=dict(sorted(sorted_eigs.items(),key=lambda a:float(a[0]))),
        combined_graph_all_full_H4_generators_preserve_adjacency=True,
        exact_conjugated_block_matrix="[[T,I+N],[I+N,T]], T=E8 root adjacency, N=root inversion",
        block_conjugacy_verified_integer=True,
        root_inversion_commutes_with_E8_adj_exact=True,
        inversion_even_subspace_T_eigenvalues={"56":1,"8":35,"-4":84},
        inversion_odd_subspace_T_eigenvalues={"28":8,"-2":112},
        inversion_even_T_minimal_polynomial="(T-56I)(T-8I)(T+4I)(I+N)=0",
        inversion_odd_T_minimal_polynomial="(T-28I)(T+2I)(I-N)=0",
        full_H4_symmetric_interlayer_dark_subspace_dimension=240,
        exact_two_sheet_spectrum_from_inversion_parity=True,
        root_sheet_flip_laws="F1(u,v)=(-u,v), F2(u,v)=(u,-v), F1=negative_global*F2; swap conjugates F1 to F2.",
        unbroken_symmetry_protection="Rootwise F1-only matching respects A5×A5 but breaks sheet swap. Adding swap-conjugate F2 restores full group at the cost of 120 uncoupled four-cycles and 240 null interlayer modes.",
        prior_art="The E8 240 root shell/56-neighbor graph is classical. Here the explicit 25-packet A4+A4 gluing is transported to a concrete 480-mode H4-invariant interlayer graph and checked against all generators; no novelty priority claim for classical root geometry.",
        physics_limit="Graph hopping is not an actual single photon optical compiler, neither tomotope face rank nor Lorentzian dynamics; physical root-mode labels and signed coupling phases remain unspecified."
    )
    OUT.write_text(json.dumps(result,indent=2,sort_keys=True)+"\n",encoding="utf8")
    print(result["status"],"E8spec",result["e8_single_sheet_root_graph_eigenvalues"],
         "combined",result["combined_graph_eigenvalues"],flush=True)
    return result
if __name__=="__main__":main()
