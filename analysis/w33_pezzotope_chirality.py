"""Prior art check and chirality test for Pass 12634 addendum 3.
BT844/BT845 (corpus): 'pentads' = 5 pairwise-disjoint W(3,3) lines covering 20 points, maximal partial spreads (in no spread);
432 of them in TWO chiral PSp(4,3)-orbits of 216; each core pairs one LEFT and one RIGHT pentad.  P12523: 216 codewords = synthematic
totals of the 36 double-sixes; S5 orbits 12 + 15 on the 27 lines.
Tests: (1) the 432 pezzotope pentads (Pass 12634) = exactly the maximal 5-line partial spreads of W(3,3);
(2) PSp(4,3) (generated by symplectic transvections of F_3^4) has two orbits of 216 on them;
(3) the two pezzotopes over each (double-six, total) lie in different PSp(4,3)-orbits (the factor 2 = chirality).
usage: py -3 analysis/w33_pezzotope_chirality.py"""
import itertools
import json
import os
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ns = {"__name__": "x", "__file__": os.path.join(HERE, "w33_split_bridge.py")}
exec(open(os.path.join(HERE, "w33_split_bridge.py"), encoding="utf-8").read().split("# (ii) roots -> spreads")[0], ns)
phi, lines, roots_of, P, w = ns["phi"], ns["lines"], ns["roots_of"], ns["P"], ns["w"]
gz = {"__name__": "x", "__file__": os.path.join(HERE, "w33_pezzotope_gosset.py")}
src = open(os.path.join(HERE, "w33_pezzotope_gosset.py"), encoding="utf-8").read()
exec(src.split("# candidate canonical line sets")[0], gz)
pents = gz["pents"]
G_, v_meet, v_skew, RL = gz["G"], gz["v_meet"], gz["v_skew"], gz["RL"]
np = gz["np"]

pent_lines = [frozenset(phi[t] for t in C) for C, r in pents]
# (1) maximal 5-line partial spreads
disj = lambda a, b: not (lines[a] & lines[b])
five = []
def ext(c, cand):
    if len(c) == 5:
        five.append(frozenset(c)); return
    for i, v in enumerate(cand):
        ext(c + [v], [u for u in cand[i + 1:] if disj(v, u)])
ext([], list(range(40)))
maximal = [S for S in five if not any(all(disj(x, s) for s in S) for x in range(40) if x not in S)]
res = dict(n_disjoint_5=len(five), n_maximal_5=len(maximal), pezzotopes_equal_maximal=set(maximal) == set(pent_lines))
print("disjoint 5-line sets", len(five), "| maximal (in no larger partial spread):", len(maximal), "| = pezzotope pentads:", res["pezzotopes_equal_maximal"])

# (2) PSp(4,3) orbits via transvections x -> x + c w(x, v) v
idx = {p: i for i, p in enumerate(P)}
norm = lambda v: next(tuple((x * pow(c, -1, 3)) % 3 for x in v) for c in v if c)
def transvection(v, c):
    return [idx[norm(tuple((x + c * w(p, v) * vi) % 3 for x, vi in zip(p, v)))] for p in P]
gens_pts = [transvection(v, 1) for v in P]
line_index = {L: i for i, L in enumerate(lines)}
def act_line(gp, L):
    return line_index[frozenset(gp[p] for p in lines[L])]
gens = [[act_line(gp, L) for L in range(40)] for gp in gens_pts]
pset = set(pent_lines)
orbit_of = {}
k = 0
for S in pent_lines:
    if S in orbit_of:
        continue
    orbit_of[S] = k
    todo = [S]
    while todo:
        X = todo.pop()
        for gL in gens:
            Y = frozenset(gL[x] for x in X)
            if Y not in orbit_of:
                orbit_of[Y] = k
                todo.append(Y)
    k += 1
sizes = Counter(orbit_of[S] for S in pent_lines)
res["psp_orbits_on_pezzotopes"] = sorted(sizes.values())
res["orbits_closed_on_pentads"] = all(S in pset for S in orbit_of)
print("PSp(4,3) orbits on the 432:", res["psp_orbits_on_pezzotopes"], "| orbits stay inside the 432:", res["orbits_closed_on_pentads"])

# (3) the two pezzotopes over each (double-six, total): different orbits?
skew = lambda i, j: abs(G_[i, j] - v_skew) < 1e-6
key_of = {}
for (C, r), S in zip(pents, pent_lines):
    keys = sorted(r); R = [r[k_] for k_ in keys]
    nz = {l: [keys[x] for x in range(10) if abs(RL[R[x], l]) > 1e-6] for l in range(27)}
    twelve = frozenset(l for l in range(27) if len(nz[l]) == 5)
    fifteen = [l for l in range(27) if len(nz[l]) == 4]
    tot = frozenset(frozenset(l for l in fifteen if (set(range(5)) - {x for e in nz[l] for x in e}).pop() == m) for m in range(5))
    key_of.setdefault((twelve, tot), []).append(orbit_of[S])
pairs = Counter(tuple(sorted(v)) for v in key_of.values())
res["orbit_pairs_over_codewords"] = {str(k_): v for k_, v in pairs.items()}
res["two_per_codeword_are_opposite_chirality"] = all(len(set(v)) == 2 for v in key_of.values())
print("orbits of the two pezzotopes over each codeword:", dict(pairs), "| always opposite:", res["two_per_codeword_are_opposite_chirality"])
json.dump(res, open(os.path.join(ROOT, "data", "w33_pezzotope_chirality.json"), "w"), indent=1)
