"""Integral Gysin ring and modular winding/BF census for S1 bundles over S2 x S2.

Independent extension of the 2026-11-16 D9 M/IIB notes.  This is a
mathematical certificate in a specified two-derivative sector, NOT a string
vacuum-stability proof.  Standard-library only.
"""
from __future__ import annotations
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "data" / "toe_20261116_circle_bundle_ring_winding_lattice.json"

def extended_gcd(a: int, b: int) -> tuple[int, int, int]:
    if b == 0:
        return abs(a), (1 if a >= 0 else -1), 0
    g, x, y = extended_gcd(b, a % b)
    return g, y, x - (a // b) * y

def circle_ring(p: int, q: int) -> dict:
    """Y(p,q) -> S2xS2, c1=p*x+q*y, x*x=y*y=0, x*y top class."""
    if not (p or q):
        raise ValueError("Nontrivial circle Chern class required")
    g = math.gcd(p, q)
    a, b = p // g, q // g
    g1, s, minus_r = extended_gcd(a, b)
    assert g1 == 1
    r = -minus_r
    assert a * s - b * r == 1
    # In H2(Y), u=a*x+b*y has order g; t=r*x+s*y is free.
    # H4(Y)=Z_g generated by w=x*y; products follow from x*x=y*y=0.
    square_torsion = (2 * a * b) % g
    mixed = (a * s + b * r) % g
    square_free = (2 * r * s) % g
    # H3(Y)=Z generated by a class z with pi_*(z)=a*x-b*y.
    # <t*z,[Y]> = a*s-b*r=1, <u*z,[Y]>=0.
    return {
        "c1": [p, q], "gcd": g, "primitive_charges": [a, b],
        "H2_free_generator_in_pullback_basis": [r, s],
        "H2_torsion_generator_in_pullback_basis": [a, b],
        "H2": "Z" if g == 1 else f"Z + Z_{g}",
        "H3": "Z", "H4": "0" if g == 1 else f"Z_{g}",
        "pi1": "trivial" if g == 1 else f"Z_{g}",
        "free_H3_pushforward": [a, -b],
        "cup_product_mod_g": {
            "u_squared": square_torsion,
            "u_times_t": mixed,
            "t_squared": square_free,
            "top_t_times_z": 1,
            "top_u_times_z": 0
        },
        "torsion_generator_square_nonzero": bool(square_torsion),
        "warning": "The gcd determines additive groups, NOT necessarily the integral cohomology ring."
    }

def lower_mass(lam: float) -> float:
    if lam < 0:
        raise ValueError("lambda must be nonnegative")
    return lam - 2.0 - math.sqrt(4 + 16 * lam)

def winding_census(N: int, N0: int, tau: complex = 1j) -> dict:
    """Counts nonzero torus Fourier labels in the derived BF-violating band.

    Each (m,n) denotes one complex Fourier label; opposite labels pair
    into real sine/cosine modes.  This is NOT a count of all IIB fields.
    """
    if N < 1 or N0 < 1 or tau.imag <= 0:
        raise ValueError("Need N,N0>=1 and Im(tau)>0")
    R = 4.0 * N / (math.pi * N0)
    y, x = tau.imag, tau.real
    nmax = math.ceil(math.sqrt(R / y)) + 1
    modes = []
    for n in range(-nmax, nmax + 1):
        center = -n * x
        width = math.sqrt(R * y)
        mmin = math.floor(center - width) - 1
        mmax = math.ceil(center + width) + 1
        for m in range(mmin, mmax + 1):
            if m == n == 0:
                continue
            Q = ((m + x * n) ** 2) / y + y * n * n
            if 0.0 < Q < R:
                lam = (3.0 * math.pi * N0 / N) * Q
                assert 0 < lam < 12 + 1e-10
                modes.append({"label": [m, n], "Q": Q,
                              "lambda": lam, "m2L2": lower_mass(lam)})
    modes.sort(key=lambda z: (z["lambda"], z["label"]))
    seen = {tuple(z["label"]) for z in modes}
    assert all((-m, -n) in seen for m, n in seen)
    return {
        "N": N, "N0": N0, "tau": [x, y],
        "modular_invariant_threshold_Q": R,
        "number_of_unstable_nonzero_Fourier_labels": len(modes),
        "number_of_opposite_label_pairs": len(modes)//2,
        "is_BF_violation_present_in_this_sector": bool(modes),
        "min_mass_m2L2": min((z["m2L2"] for z in modes), default=None),
        "modes": modes
    }

def winding_weyl_bound(N: int, N0: int, tau: complex) -> dict:
    """Explicit unit-area lattice cell bound, a rigorous elementary Weyl law.

    Fundamental parallelogram centered on each lattice site has area 1 and
    all its points lie within delta=(|v1|+|v2|)/2 of that site.
    """
    if N < 1 or N0 < 1 or tau.imag <= 0:
        raise ValueError("Need N,N0>=1 and Im(tau)>0")
    radius = math.sqrt(4*N/(math.pi*N0))
    delta = (1+abs(tau))/(2*math.sqrt(tau.imag))
    lower = math.pi*max(radius-delta,0)**2-1
    upper = math.pi*(radius+delta)**2-1
    actual = winding_census(N,N0,tau)["number_of_unstable_nonzero_Fourier_labels"]
    assert lower-1e-8 <= actual <= upper+1e-8
    return {"N":N,"N0":N0,"tau":[tau.real,tau.imag],
            "exact_count":actual,"area_leading_term":4*N/N0,
            "lower_proved_bound":lower,"upper_proved_bound":upper,
            "cell_cover_radius":delta}

def verify() -> dict:
    # Ring-level distinction missed by homotopy/homology alone:
    # L(3,1) x S2 has torsion square zero, T11/Z3 has nonzero square.
    l30 = circle_ring(3, 0)
    l33 = circle_ring(3, 3)
    assert l30["gcd"] == l33["gcd"] == 3
    assert l30["cup_product_mod_g"]["u_squared"] == 0
    assert l33["cup_product_mod_g"]["u_squared"] == 2
    for p, q in [(1,1),(2,2),(3,3),(4,4),(3,0),(6,10),(0,-7),(-4,-4)]:
        rec = circle_ring(p,q)
        a,b=rec["primitive_charges"]
        r,s=rec["H2_free_generator_in_pullback_basis"]
        assert a*s-b*r==1
        assert rec["cup_product_mod_g"]["top_t_times_z"]==1
    # The BF band is open: 0 and 12 saturate the bound, with
    # minimum at lambda=15/4 and m^2 L^2=-25/4.
    assert abs(lower_mass(0)+4)<1e-13
    assert abs(lower_mass(12)+4)<1e-13
    assert abs(lower_mass(15/4)+25/4)<1e-13
    square = {}
    for N,N0,expected in [(1,1,4),(1,2,0),(2,1,8),(5,1,20)]:
        record=winding_census(N,N0)
        assert record["number_of_unstable_nonzero_Fourier_labels"]==expected
        square[f"{N}/{N0}"]=record
    # Under tau -> tau+1, the lattice labels transform bijectively.
    for tau in [1j, complex(0.34,1.2), complex(0.5,math.sqrt(3)/2)]:
        assert winding_census(5,2,tau)["number_of_unstable_nonzero_Fourier_labels"]==winding_census(5,2,tau+1)["number_of_unstable_nonzero_Fourier_labels"]
        assert winding_census(5,2,tau)["number_of_unstable_nonzero_Fourier_labels"]==winding_census(5,2,-1/tau)["number_of_unstable_nonzero_Fourier_labels"]
    return {
        "status": "EXACT_GYSIN_CUP_PRODUCTS_AND_NUMERICAL_MODULAR_BF_LATTICE_CENSUS",
        "scope": "Circle-bundle integral cohomology plus the specified M-theory sphere-odd torus-momentum sector; does not certify full 10D/11D stability.",
        "ring_example_same_gcd_distinct_cup_square": {"3_0":l30, "3_3":l33},
        "square_shape_cases":square,
        "fixed_shape_weyl_cell_bounds":[winding_weyl_bound(r,1,1j) for r in (1,2,5,10,25,100,400)],
        "fixed_tau_weyl_asymptotic":"U=4*N/N0 + O_tau(sqrt(N/N0)) at fixed tau",
        "hexagonal_Qmin":2/math.sqrt(3),
        "every_shape_instability_if_N_over_N0_gt":math.pi/(2*math.sqrt(3)),
        "square_shape_instability_iff_N_over_N0_gt":math.pi/4,
        "corrective_comment":"Square N=N0=1 has four unstable nonzero Fourier labels because lambda1=3*pi<12; prior untracked local audit comment incorrectly called this case BF-safe.",
        "notes":"Gysin ring products are integral; BF census uses floating point for moduli away from exact thresholds."
    }

