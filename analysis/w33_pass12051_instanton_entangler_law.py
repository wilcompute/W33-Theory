"""Pass 12051: an instanton-sized entangler. The parameter-free law eps = C exp(-pi (Im tau1 + Im tau2)), with one
universal C fixed by the up home, passes on one quark branch (chi^2 1.3-1.7 for 1 dof). But that is the branch the
charged leptons exclude: no branch satisfies both (Claude track).

Law. In the mirror (type IIA) reading of magnetized branes, the theta moduli are complexified Kahler moduli. An
entangler generated by a worldsheet instanton spanning both tori scales as exp(-pi (y1 + y2)) = |q1 q2|^(1/2). Test
the parameter-free form eps_sector = C exp(-pi (y1 + y2)), with ONE universal C.
  * Up home (y1 = y2 = 0.8745, eps_u = 0.00552 i): C_u = 1.343 (+- 5.3%). So the up hierarchy is |q| up to an O(1)
    factor; eps is not mysterious there once Im tau ~ 0.87.
  * Down homes in the corpus: C_d/C_u = 3.6 (12005), 10.4 (12007), 1.12 (12045 branch A), and 2.5e4 - 2.5e5 for
    branches B, C, D, G. Only branch A is near the law.
Test (overdetermined). Impose eps_d = C_u e^eta exp(-pi (y + y_d)) on the 12045 geometric-row down system (eta a
nuisance with sigma 5.3%). Then 6 residuals face 5 free parameters + eta: one degree of freedom.
  * From branch A: chi^2 = 1.33 (comparator errors) or 1.73 (lattice-precision errors), all pulls < ~1 sigma,
    eta = 0.03. The law PASSES on branch A.
  * Multistart (90 starts per error set, 60 broad): the best solutions are branch A and its symmetry images only.
  * Look-elsewhere: one of seven branches lands within ~12% of the law. Over the observed log-spread of C_d, that
    chance is roughly 0.15-0.2.
  * Conflict: branch A is excluded by the charged leptons under the 12007 shared matching (12045, 13-16 sigma), and
    stays excluded at the constrained solution (recomputed here). The leptons favour branch C (with the 12047 Clebsch),
    which violates the law by 2.5e4. No branch satisfies both.
Reading. A single worldsheet-instanton law can make the quark sector of the geometric row overdetermined -- and it
fits. But the branch it selects cannot carry the charged leptons. Either the lepton sector has its own structure
(as 12045-12047 concluded), or the law is a coincidence on branch A.
Scope: the 12045 geometric-row model; one universal C; mirror-instanton motivation only (no instanton computation).
Not new: worldsheet-instanton Yukawas (Cremades-Ibanez-Marchesano; Cvetic-Papadimitriou); hierarchies from
near-fixed points.
"""

import json
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import least_squares

ROOT = Path(__file__).resolve().parents[1]
for p in ("analysis", "analysis/search_drivers_12045"):
    sys.path.insert(0, str(ROOT / p))
import barrfit as B  # noqa: E402
import instlaw as I  # noqa: E402
from jointlep import leptons  # noqa: E402
from w33_pass11942_hypercharge_wilson_leptons import LEPTONS  # noqa: E402

OUT = ROOT / "data" / "w33_pass12051_instanton_entangler_law.json"
HOMES = {"12005": (-.8404552787929092, .08087153936666885), "12007": (-.3497011260666278, .09754766874005429),
         "A": (-1.8444766914898252, 0.05894435138670266), "B": (1.139142, -1.15415), "C": (0.995395, 0.44687),
         "D": (0.9455762833705734, 0.7941912695168974), "G": (1.1304145066407365, 1.1538734295107838)}
MULTISTART_RECORD = dict(starts_per_error_set=90, broad_starts=60, best_chi2=dict(comparator=1.332, precise=1.733),
                         finding="every best solution is branch A or its symmetry images; no other branch satisfies the law")


def main():
    checks, res = {}, {}
    Y = B.Y_UP
    Cu = I.CU
    res["C_u"] = Cu
    ratios = {k: float(abs(ed) * np.exp(np.pi * (Y + np.exp(lyd))) / Cu) for k, (lyd, ed) in HOMES.items()}
    res["C_d_over_C_u"] = ratios
    checks["up home: C_u = eps_u e^{2 pi y} = 1.34 (O(1))"] = bool(abs(Cu - 1.3434) < 1e-3)
    checks["only branch A lies within 25% of the universal law"] = bool(
        [k for k, v in ratios.items() if abs(np.log(v)) < np.log(1.25)] == ["A"])
    A = np.array([-1.8444766914898252, 0.028382479377949063, 5.083585000284045, -0.0775199696196673, -0.3673566495323771, 0.0])
    fits = {}
    for mode in ("comparator", "precise"):
        r = least_squares(I.res, A, args=(1, I.ERRS[mode]), xtol=1e-14, ftol=1e-14, gtol=1e-14, max_nfev=4000)
        x = I.full(r.x, 1)
        lp = leptons(x)
        fits[mode] = dict(chi2=float(np.sum(r.fun ** 2)), pulls=r.fun.tolist(), eta=float(r.x[5]), x=x.tolist(),
                          leptons=[float(lp[0]), float(lp[1])], lepton_ratio=[float(lp[0] / LEPTONS["mmu_mtau"]), float(lp[1] / LEPTONS["me_mmu"])])
    res["constrained_fit_A"] = fits
    checks["law imposed on branch A: chi^2 < 3 for 1 dof (both error sets), |eta| < 0.1"] = bool(
        all(f["chi2"] < 3 and abs(f["eta"]) < 0.1 for f in fits.values()))
    checks["conflict: at the constrained solution the 12007 lepton ratios are still off by > x2.5"] = bool(
        all(max(abs(np.log(r)) for r in f["lepton_ratio"]) > np.log(2.5) for f in fits.values()))
    res["multistart_record"] = MULTISTART_RECORD
    res["checks"] = checks
    res["all_checks_pass"] = all(checks.values())
    OUT.write_text(json.dumps(res, indent=2, default=float))
    print(json.dumps(checks, indent=1), res["all_checks_pass"])
    return res


if __name__ == "__main__":
    main()
