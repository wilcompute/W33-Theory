"""Exact Dijkgraaf-Witten choices for the actual C2^3 deck group.

Finite quantum doubles and type-III twists are established mathematics.
Earlier repo quantum-double owners: w33_anyons_from_2T.py (different group),
w33_novel_dw_tqft_sp4.py (different group and dimensional convention).
Here Z(T3)=dim H(T2); we do not equate a surface with a3D partition function.
The cocycle and gauge Hamiltonian are supplied choices, not native predictions.
"""
import collections
import itertools
import json
import pathlib

import numpy as np
import sympy as s

ROOT=pathlib.Path(__file__).resolve().parents[1]


def bit(x,j):return (x>>j)&1


def omega(a,b,c):return (-1)**(bit(a,0)*bit(b,1)*bit(c,2))


def alpha(g,x,y):return omega(g,x,y)*omega(x,y,g)*omega(x,g,y)


def regular(g,x):
    m=s.zeros(8)
    for y in range(8):m[x^y,y]=alpha(g,x,y)
    return m


def build():
    native=json.loads((ROOT/'data/w33_20261102_deck_monodromy_network.json').read_text())
    assert native['deck_structure']=='C2^3' and native['branch_addresses']==[1,2,4,7]
    for a,b,c,d in itertools.product(range(8),repeat=4):
        assert omega(b,c,d)*omega(a,b^c,d)*omega(a,b,c)==omega(a^b,c,d)*omega(a,b,c^d)
    flux=[];spins=collections.Counter({'1':8})
    for g in range(8):
        for x,y,z in itertools.product(range(8),repeat=3):
            assert alpha(g,x,y)*alpha(g,x^y,z)==alpha(g,y,z)*alpha(g,x,y^z)
        radical=[x for x in range(8) if all(alpha(g,x,y)==alpha(g,y,x) for y in range(8))]
        assert radical==(list(range(8)) if g==0 else [0,g])
        dim=1 if g==0 else 2
        number=len(radical)
        mats=[regular(g,x) for x in range(8)]
        assert all(mats[x]*mats[y]==alpha(g,x,y)*mats[x^y] for x,y in itertools.product(range(8),repeat=2))
        row=dict(flux=g,radical=radical,irreducible_count=number,irreducible_dimension=dim)
        if g:
            phase=s.I if alpha(g,g,g)==-1 else s.Integer(1)
            assert mats[g]**2==phase**2*s.eye(8)
            projectors=[(s.eye(8)+sign*mats[g]/phase)/2 for sign in (1,-1)]
            assert all(p*p==p and p.rank()==4 for p in projectors)
            block_dimensions=[s.Matrix.hstack(*[(p*m).reshape(64,1) for m in mats]).rank() for p in projectors]
            assert block_dimensions==[4,4]
            row.update(projective_spin_phases=[str(phase),str(-phase)],central_block_dimensions=block_dimensions)
            spins[str(phase)]+=1;spins[str(-phase)]+=1
        flux.append(row)
    dimensions=[r['irreducible_dimension'] for r in flux for _ in range(r['irreducible_count'])]
    assert collections.Counter(dimensions)=={1:8,2:14} and sum(d*d for d in dimensions)==64
    # The alternating cocycle evaluation on an oriented3-torus.
    signs=[]
    for a,b,c in itertools.product(range(8),repeat=3):
        value=omega(a,b,c)*omega(b,c,a)*omega(c,a,b)*omega(a,c,b)*omega(c,b,a)*omega(b,a,c)
        signs.append(value)
    assert collections.Counter(signs)=={1:344,-1:168}
    assert sum(signs)//8==22
    assert spins=={'1':14,'-1':6,'I':1,'-I':1}
    # The chosen local cocycle phase is literally CCZ on three selected bits.
    # Its derivative under X0 contains the quadratic controlled-Z phase.
    phase=lambda x:(-1)**(((x>>0)&1)*((x>>1)&1)*((x>>2)&1))
    assert all(phase(x^1)*phase(x)==(-1)**(((x>>1)&1)*((x>>2)&1)) for x in range(8))
    moments=[]
    for x,z in itertools.product(range(8),repeat=2):
        expectation=s.I**((x&z).bit_count())*sum(phase(v^x)*phase(v)*(-1)**((z&v).bit_count()) for v in range(8))/8
        moments.append(s.simplify(expectation**4))
    normalized_moment=s.simplify(sum(moments)/8)
    assert normalized_moment==s.Rational(11,32)
    return dict(status='PASS_NATIVE_DECK_TYPE_III_QUANTUM_DOUBLE',native_branch_fluxes=native['branch_addresses'],
        group='C2^3',chosen_cocycle='omega(a,b,c)=(-1)^(a0*b1*c2)',cocycle_quadruples_checked=4096,
        flux_sectors=flux,anyon_dimension_multiplicities={'1':8,'2':14},anyon_count=22,total_quantum_dimension_squared=64,
        topological_spin_multiplicities=dict(spins),untwisted_anyon_count=64,
        T3_cocycle_weight_counts={str(k):v for k,v in collections.Counter(signs).items()},
        T3_partition=22,torus_state_space_dimension=22,
        supplied_cocycle_resource=dict(local_phase='CCZ on bits(a0,b1,c2)',
            conjugation_witness='CCZ X0 CCZ = X0 CZ12, which is not a Pauli operator',
            normalized_Pauli_fourth_moment_of_CCZ_plus_state=str(normalized_moment),
            boundary='This supplied cubic phase is an additional non-Clifford primitive; it is not generated by the native finite Clifford gate group. No preparation protocol or protected logical CCZ is inferred.'),
        prior='Type-III D^omega(C2^3), including its22 anyons and spin counts, is prior mathematics; the bridge here supplies the actual native deck-group/meridian dictionary. The earlier2T double is a different choice of gauge group.',
        boundary='A supplied2+1D finite gauge/TQFT construction on the identified carrier, not a derivation of anyons from the native projector Hamiltonian. Braids of twisted finite-group doubles have finite images (Etingof-Rowell-Witherspoon); non-Abelian anyons here do not imply braid-only universality or3+1D gravity.')


if __name__=='__main__':
    d=build();(ROOT/'data/w33_20261102_deck_twisted_quantum_double.json').write_text(json.dumps(d,indent=2)+'\n',encoding='utf-8')
    print(d['status'],d['anyon_dimension_multiplicities'],d['T3_partition'],flush=True)
