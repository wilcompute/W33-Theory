"""Pass 12653: the two-moment bound kappa <= 3 (Pass 12652) holds uniformly on ALL six-element two-qubit Pauli supports whose 15
pairwise differences are the 15 non-zero vectors of F_2^4 (the hypothesis of the proof).  Cross-track check of the parallel
assistant's report (2026-11-13, pasted into the session): 448 such supports, three affine-symplectic orbits of sizes 16, 192, 240,
the repository pentagon model {II,XI,ZI,XZ,IX,ZY} in the 192-orbit (PPT Choi), and an explicit non-stabiliser equality family
    y_t = (1, it, -it, 1)/sqrt(2(1+t^2)),  sum_M M|y_t><y_t|M^dag = I + 2|v_t><v_t|,  v_t = (-it, 1, 1, it)/sqrt(2(1+t^2)).
Here: (1) count supports; (2) orbits under Sp(4,2) x translations (generated by transvections + translations); (3) Tr G = 6 and
Tr G^2 = 12 for random y on every support, and kappa (alternating maximisation) per orbit -- is the bound ATTAINED on every orbit?;
(4) PPT of the Choi matrix per orbit rep; (5) the y_t family identity and spectrum (3,1,1,1), <XX> at t = 2.
usage: py -3 analysis/w33_kappa_448_supports.py"""
import itertools, json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
I2 = np.eye(2); X = np.array([[0, 1], [1, 0]]); Z = np.diag([1, -1]); Y = np.array([[0, -1j], [1j, 0]])
one = {(0, 0): I2, (1, 0): X, (0, 1): Z, (1, 1): Y}
lab = {(0, 0): "I", (1, 0): "X", (0, 1): "Z", (1, 1): "Y"}
# vector (x1, x2, z1, z2) as int: bits 0,1 = x ; 2,3 = z
def mat(v):
    return np.kron(one[(v & 1, v >> 2 & 1)], one[(v >> 1 & 1, v >> 3 & 1)])
def name(v):
    return lab[(v & 1, v >> 2 & 1)] + lab[(v >> 1 & 1, v >> 3 & 1)]
def omega(a, b):
    return (bin((a & 3) & (b >> 2)).count("1") + bin((a >> 2) & (b & 3)).count("1")) % 2

supports = [S for S in itertools.combinations(range(16), 6) if len({a ^ b for a, b in itertools.combinations(S, 2)}) == 15]
# orbits under transvections T_u: v -> v + omega(u, v) u, and translations v -> v + c
gens = [lambda S, u=u: tuple(sorted(v ^ (u if omega(u, v) else 0) for v in S)) for u in range(1, 16)]
gens += [lambda S, c=c: tuple(sorted(v ^ c for v in S)) for c in range(1, 16)]
left = set(supports); orbits = []
while left:
    s = min(left); orb = {s}; fr = [s]
    while fr:
        nx = []
        for S in fr:
            for gfun in gens:
                T = gfun(S)
                if T not in orb: orb.add(T); nx.append(T)
        fr = nx
    orbits.append(sorted(orb)); left -= orb
rng = np.random.default_rng(0)


def kappa(Ms, starts=60):
    best = 0
    for _ in range(starts):
        y = rng.standard_normal(4) + 1j * rng.standard_normal(4); y /= np.linalg.norm(y)
        for _ in range(300):
            W = np.array([M @ y for M in Ms]).T
            x = np.linalg.eigh(W @ W.conj().T)[1][:, -1]
            W2 = np.array([M.conj().T @ x for M in Ms]).T
            y = np.linalg.eigh(W2 @ W2.conj().T)[1][:, -1]
        val = sum(abs(np.vdot(x, M @ y)) ** 2 for M in Ms); best = max(best, val)
    return best


def choi_ppt(Ms):
    J = sum(np.outer(M.reshape(-1), M.reshape(-1).conj()) for M in Ms)  # unnormalised Choi of A -> sum M A M^dag (vec convention)
    Jt = J.reshape(4, 4, 4, 4).transpose(0, 3, 2, 1).reshape(16, 16)
    return float(np.linalg.eigvalsh(Jt).min())


model = tuple(sorted([0, 1, 4, 1 | 8, 2, 4 | 2 | 8]))  # II, XI, ZI, XZ, IX, ZY
assert [name(v) for v in model] and len(set(model)) == 6
res = dict(n_supports=len(supports), orbit_sizes=sorted(len(o) for o in orbits), orbits=[])
for o in orbits:
    rep = o[0]; Ms = [mat(v) for v in rep]
    for S in o:
        M2 = [mat(v) for v in S]
        y = rng.standard_normal(4) + 1j * rng.standard_normal(4); y /= np.linalg.norm(y)
        W = np.array([M @ y for M in M2]).T; G = W.conj().T @ W
        assert abs(np.trace(G).real - 6) < 1e-9 and abs(np.trace(G @ G).real - 12) < 1e-9
    k = kappa(Ms)
    res["orbits"].append(dict(size=len(o), rep=[name(v) for v in rep], contains_model=model in o, kappa=k,
                              choi_pt_min_eig=choi_ppt(Ms), moment_identities_all_members=True))
    print(res["orbits"][-1], flush=True)
# y_t family on the model
Mm = [mat(v) for v in (0, 1, 4, 1 | 8, 2, 4 | 2 | 8)]
fam = []
for t in (0.0, 0.5, 2.0, -3.0):
    y = np.array([1, 1j * t, -1j * t, 1]) / np.sqrt(2 * (1 + t * t)); v = np.array([-1j * t, 1, 1, 1j * t]) / np.sqrt(2 * (1 + t * t))
    Sm = sum(M @ np.outer(y, y.conj()) @ M.conj().T for M in Mm)
    ok = np.allclose(Sm, np.eye(4) + 2 * np.outer(v, v.conj()))
    XX = np.vdot(y, np.kron(X, X) @ y).real
    fam.append(dict(t=t, identity_holds=bool(ok), spectrum=[round(float(e), 9) for e in np.linalg.eigvalsh(Sm)], XX_on_y=XX,
                    XX_on_v=float(np.vdot(v, np.kron(X, X) @ v).real)))
res["y_t_family"] = fam
print(fam, flush=True)
json.dump(res, open(os.path.join(ROOT, "data", "w33_kappa_448_supports.json"), "w"), indent=1)
