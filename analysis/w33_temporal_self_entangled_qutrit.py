    points = projective_points()
    adjacency = adjacency_sets(points)
    lines = all_isotropic_lines(points)

    shift_lock = (1, 0, 1, 0)   # X_p X_f
    phase_lock = (0, 1, 0, 2)   # Z_p Z_f^{-1}
