"""Part MCLXIII: Temporal self-entangled qutrit bridge.

The user-level intuition is: one qutrit is read as past/future copies of the
same ternary system, and "now" is the contraction/evaluation between them.

Finite model:
  |Omega> = (|00> + |11> + |22>) / sqrt(3)

This is the Choi state of the identity qutrit channel.  Its stabilizer is the
Lagrangian line generated by X_p X_f and Z_p Z_f^{-1}.  Projectivizing all
nonzero two-qutrit Pauli phase-space vectors in F_3^4 gives exactly the W33
40-point symplectic polar space.
"""

from __future__ import annotations

import json
from collections import Counter
from fractions import Fraction
from itertools import combinations, product
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
Q = 3
F3 = (0, 1, 2)

Vector = tuple[int, int, int, int]
Line = frozenset[Vector]


def normalize(vector: Vector) -> Vector:
    """Normalize a nonzero F3^4 vector to its projective representative."""
    for entry in vector:
        if entry % Q:
            inverse = 1 if entry % Q == 1 else 2
            return tuple((inverse * value) % Q for value in vector)  # type: ignore[return-value]
    raise ValueError("zero vector has no projective normalization")


def add_scaled(left: Vector, a: int, right: Vector, b: int) -> Vector:
    return tuple((a * left[index] + b * right[index]) % Q for index in range(4))  # type: ignore[return-value]


def symplectic(left: Vector, right: Vector) -> int:
    """Two-qutrit Pauli commutation form on (X_p,Z_p,X_f,Z_f) exponents."""
    a, b, c, d = left
    a2, b2, c2, d2 = right
    return (a * b2 - b * a2 + c * d2 - d * c2) % Q


def projective_points() -> list[Vector]:
    points = {normalize(vector) for vector in product(F3, repeat=4) if any(vector)}
    return sorted(points)


def span_line(first: Vector, second: Vector) -> Line:
    points: set[Vector] = set()
    for a, b in product(F3, repeat=2):
        if a == 0 and b == 0:
            continue
        points.add(normalize(add_scaled(first, a, second, b)))
    return frozenset(points)


def all_isotropic_lines(points: list[Vector]) -> list[Line]:
    lines: set[Line] = set()
    for first, second in combinations(points, 2):
        if symplectic(first, second) != 0:
            continue
        line = span_line(first, second)
        if len(line) == Q + 1:
            assert all(symplectic(left, right) == 0 for left, right in combinations(line, 2))
            lines.add(line)
    return sorted(lines, key=lambda line: tuple(sorted(line)))


def adjacency_sets(points: list[Vector]) -> list[set[int]]:
    adjacency = [set() for _ in points]
    for left, right in combinations(range(len(points)), 2):
        if symplectic(points[left], points[right]) == 0:
            adjacency[left].add(right)
            adjacency[right].add(left)
    return adjacency


def srg_parameters(adjacency: list[set[int]]) -> dict[str, object]:
    degrees = [len(row) for row in adjacency]
    lambda_counts: Counter[int] = Counter()
    mu_counts: Counter[int] = Counter()
    for left, right in combinations(range(len(adjacency)), 2):
        common = len(adjacency[left] & adjacency[right])
        if right in adjacency[left]:
            lambda_counts[common] += 1
        else:
            mu_counts[common] += 1
    return {
        "v": len(adjacency),
        "k_values": sorted(set(degrees)),
        "edges": sum(degrees) // 2,
        "lambda_counts": dict(sorted(lambda_counts.items())),
        "mu_counts": dict(sorted(mu_counts.items())),
    }


def bell_expectation_survives(vector: Vector) -> bool:
    """Return whether <Omega|P(vector)|Omega> is nonzero.

    For P=(X^a Z^b)_past tensor (X^c Z^d)_future, direct evaluation on
    |Omega> = sum_j |j,j>/sqrt(3) gives survival exactly when a=c and b+d=0.
    """
    a, b, c, d = vector
    return a == c and (b + d) % Q == 0


def find_spread_containing(required: Line, lines: list[Line], points: list[Vector]) -> list[Line]:
    """Find one deterministic symplectic spread containing the required line."""
    all_points = set(points)
    point_to_lines: dict[Vector, list[Line]] = {point: [] for point in points}
    for line in lines:
        for point in line:
            point_to_lines[point].append(line)
    for point in points:
        point_to_lines[point].sort(key=lambda line: tuple(sorted(line)))

    def search(selected: list[Line], covered: set[Vector]) -> list[Line] | None:
        if covered == all_points:
            return selected
        point = min(all_points - covered)
        for line in point_to_lines[point]:
            if line in selected or line & covered:
                continue
            result = search(selected + [line], covered | set(line))
            if result is not None:
                return result
        return None

    spread = search([required], set(required))
    if spread is None:
        raise AssertionError("no spread found containing temporal Bell line")
    return spread


