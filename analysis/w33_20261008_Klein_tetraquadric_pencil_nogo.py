I=S.I
def terms(t):
 if t=="inf":return S.Integer(1),S.Integer(-1),S.Integer(0)
 x=S.Integer(1);y=t
 return S.expand(x*x+y*y),S.expand(x*x-y*y),S.expand(2*x*y)
def calc(t,a,b):
 tup=[terms(j) for j in t]
 return S.expand(S.prod(x[0] for x in tup)+a*S.prod(x[1] for x in tup)+b*S.prod(x[2] for x in tup))
def derivative(t,a,b,i):
 tup=[terms(j) for j in t]
