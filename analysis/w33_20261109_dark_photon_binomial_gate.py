#!/usr/bin/env python3
"""Native W33 dark-state photon test with exact binomial source-shot power.

Prepared initial dark vector; a real bipartite Hamiltonian with one,
fourteen or fifteen unit-modulus pi phase flips predicts a line-port
occupation P_line(t) that is exactly computable by singular decompositions.
Calibrate independent detector dark floor and photon survival; all
launched trials count. Exact binomial critical count controls size <=5%.
"""
import json,sys,math
from pathlib import Path
import numpy as np
from scipy.stats import binom
from scipy.linalg import expm
from w33_20261109_flux_dark_mode_fragility import build

def signal(T,psi,t):
    u,s,v=np.linalg.svd(T,full_matrices=True)
    amps=np.abs(u.conj().T@psi)**2
    return float(np.dot(amps,np.sin(t*s)**2))

def threshold(N,p0,alpha=.05):
    x=int(binom.ppf(1-alpha,N,p0))+1
    while binom.sf(x-1,N,p0)>alpha:x+=1
    while x>0 and binom.sf(x-2,N,p0)<=alpha:x-=1
    assert binom.sf(x-1,N,p0)<=alpha+1e-12
    return x

def exact_size_power_N(p0,p1,alpha=.05,power=.95):
    assert 0<=p0<p1<=1
    lo,hi=1,1
    while binom.sf(threshold(hi,p0)-1,hi,p1)<power:
        hi*=2
        if hi>4000000:return None
    while lo<hi:
        mid=(lo+hi)//2
        if binom.sf(threshold(mid,p0)-1,mid,p1)>=power:hi=mid
        else:lo=mid+1
    n=hi;k=threshold(n,p0)
    return {"launched_trials":n,"required_line_click_count":k,
       "exact_false_positive_probability":float(binom.sf(k-1,n,p0)),
       "exact_power_under_pessimistic_alternative":float(binom.sf(k-1,n,p1))}

def main(path=None):
    B,edges,G=build(); A=B@B.T-4*np.eye(40)
    P=(8*np.eye(40)-4*A+np.ones((40,40)))/24
    psi=P[:,0]/math.sqrt(3/8)
    assert np.linalg.norm(B.T@psi)<1e-12
    prior=json.loads((Path(__file__).resolve().parents[1]/"data/w33_20261109_flux_mass_gap_design.json").read_text())
    supports=[(x["point"],x["line"]) for x in prior["best_15_edges"]]
    families={}
    for k in (0,1,14,15):
        T=B.astype(complex)
        for p,l in supports[:k]:T[p,l]=-1
        sig=np.linalg.svd(T,compute_uv=False)
        grid=np.linspace(.01,6,600)
        traces=np.array([signal(T,psi,t) for t in grid])
        ix=int(np.argmax(traces))
        families[str(k)]={"changed_links":k,
          "remaining_chiral_zero_modes":int(80-2*sum(sig>1e-9)),
          "max_line_probability_within_time_0_to_6":float(traces[ix]),
          "dimensionless_time_at_max":float(grid[ix]),
          "p_line_at_t_1":signal(T,psi,1.),
          "minimum_singular_value":float(sig[-1])}
    assert families["0"]["max_line_probability_within_time_0_to_6"]<1e-20
    assert families["1"]["max_line_probability_within_time_0_to_6"]>0
    assert families["15"]["minimum_singular_value"]>0
    # Experimental decision uses common fixed measurement time chosen
    # from a numerical target (not an independently validated device).
    eta_det=.85;source=.95;dark_min=.0008;dark_max=.0012
    # Real source/detector calibration is separately required.
    p0=dark_max
    for k in (1,14,15):
        x=families[str(k)]
        signal_low=eta_det*source*x["max_line_probability_within_time_0_to_6"]
        p1=1-(1-dark_min)*(1-signal_low)
        assert p1>p0
        x["conservative_prob_click_if_alternative"]=p1
        x["conservative_null_probability_upper"]=p0
        x["exact_binomial_5pct_false_positive_95pct_power"]=exact_size_power_N(p0,p1)
        assert x["exact_binomial_5pct_false_positive_95pct_power"]
    # Crosscheck the singular formula against the actual 80x80 unitary
    # at representative times for the 15-edge detuned coupling.
    T=B.astype(complex)
    for p,l in supports:T[p,l]=-1
    H=np.block([[np.zeros((40,40)),T],[T.conj().T,np.zeros((40,40))]])
    direct=[]
    for t in (.1,1.,3.):
        v=expm(-1j*t*H)@np.r_[psi,np.zeros(40)]
        px=float(np.linalg.norm(v[40:])**2)
        ps=signal(T,psi,t)
        assert abs(px-ps)<1e-12
        direct.append({"time":t,"matrix_exponential_line_probability":px,
                       "svd_formula_line_probability":ps})
    out={"status":"PASS_W33_DARK_NULL_PHOTON_BINOMIAL_CALIBRATED_LOSS_GATE",
         "tested_changed_pi_incidence_links":[0,1,14,15],
         "all_traces_from_ideal_initial_40port_dark_state":families,
         "source_photon_survival_fraction":source,
         "line_detector_efficiency":eta_det,
         "independent_dark_probability_interval_per_launched_trial":[dark_min,dark_max],
         "signal_lower_probability_formula":"p1=1-(1-dark_min)*(1-source_survival*eta_det*P_line)",
         "null_upper_probability":p0,
         "type_I_alpha":.05,"target_power":.95,
         "finite_exact_binomial_size_power_controls":True,
         "matrix_exponential_independent_controls":direct,
         "crucial_scope":"This tests the photon probability generated by an IDEAL 80-mode chiral W33 quantum walk. Source loss and detector efficiencies enter only at preparation/readout; internal mode-dependent loss, dephasing, calibration errors in the initial 40-port state and actual Hamiltonian are NOT included. Even with 14 link changes the remaining exact zero modes generally differ from the initial prepared dark state; fixed-input leakage alone cannot certify spectral nullity. Actual lab measurements would need trusted hardware and independent null/dark calibration. The selected optimal time assumes a known alternative, not arbitrary state discovery.",
         "prior_art":"Exact binomial test, SVD exponentiation of bipartite walks and photon dark-state nulling are established techniques. The W33 graph and 15-phase support supply the specific test case."}
    if path:Path(path).write_text(json.dumps(out,indent=2,sort_keys=True)+"\n",encoding="utf8")
    print("W33_DARK_BINOMIAL",json.dumps({k:{"maxP":round(v["max_line_probability_within_time_0_to_6"],5),
         "zero":v["remaining_chiral_zero_modes"],
         "N":v.get("exact_binomial_5pct_false_positive_95pct_power",{}).get("launched_trials")}
       for k,v in families.items()}))
    return out

if __name__=="__main__":main(sys.argv[1] if len(sys.argv)>1 else None)
