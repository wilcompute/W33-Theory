def primitive_roots(p,order):
    assert (p-1)%order==0
    for g in range(2,p):
        if pow(g,order,p)==1 and all(pow(g,k,p)!=1 for k in range(1,order)):
            return [pow(g,k,p) for k in range(order)]
    raise RuntimeError("primitive roots unavailable")


def native_character_census():
    short,volt,commutators=_native_rows()
    assert len(short)==105 and len(volt)==135 and len(commutators)==6
    cases=[]
    # Three distinct torsion orders; no invalid bad-prime rank inference.
    for modulus,order in ((103,3),(101,4),(101,5)):
        roots=primitive_roots(modulus,order)
        hist={}
        for exps in product(range(order),repeat=4):
            zs=[roots[e] for e in exps]
            f=[bloch_row(face,volt,zs,modulus) for face in short]
            six=[bloch_row(loop,volt,zs,modulus) for loop in commutators]
            mixed=[[sum(int(R[i,j])*six[j][k] for j in range(6))%modulus
                    for k in range(135)] for i in range(3)]
            rows=f+mixed
            active=any(exps[j] for j in range(3))
            if active:rows += [six[0],six[5]]
            rank_repair=rank_mod(rows,modulus)
            rank_full=rank_mod(f+six,modulus)
            assert rank_repair==rank_full== (105 if not any(exps) else 108), {
                "prime":modulus,"exponents":exps,"repaired":rank_repair,"full":rank_full
            }
            label=str(rank_repair)
            hist[label]=hist.get(label,0)+1
        cases.append({"prime":modulus,"torsion_order":order,
                      "characters":order**4,
                      "repaired_rank_histogram":hist,
                      "same_ranks_as_full_six_loop":True})
    return cases


