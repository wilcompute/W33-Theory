#!/usr/bin/env python3
"""Exact q=3 W33 adjacency-CSS no-go for *nonuniform* diagonal T patterns.

Any product of T_j**theta_j (theta_j in Z8) preserving the [[40,8,6]]
codespace has every theta_j even and is therefore Clifford.
Regenerates F3 geometry and provides a four-equation contradiction.
"""
import itertools
import json

def geometry():
    def norm(v):
        t=pow(next(z for z in v if z),-1,3)
        return tuple(t*z%3 for z in v)
    pts=sorted({norm(v) for v in itertools.product(range(3),repeat=4) if any(v)})
    def B(a,b):
        return (a[0]*b[1]-a[1]*b[0]+a[2]*b[3]-a[3]*b[2])%3
    A=[sum(1<<j for j,y in enumerate(pts) if i!=j and B(x,y)==0)
       for i,x in enumerate(pts)]
    assert len(A)==40 and all(a.bit_count()==12 for a in A)
    assert all((a&b).bit_count()%2==0 for a in A for b in A)
    return A

def span_basis(words):
    piv={}
    for x in words:
        z=x
        while z:
            k=z.bit_length()-1
            if k in piv:z^=piv[k]
            else:piv[k]=z;break
    return list(piv.values())

def null_basis(rows,n=40):
    A=rows[:];r=0;piv={}
    for j in range(n):
        k=next((i for i in range(r,len(A)) if A[i]>>j&1),None)
        if k is None:continue
        A[r],A[k]=A[k],A[r]
        for i in range(len(A)):
            if i!=r and (A[i]>>j&1):A[i]^=A[r]
        piv[j]=r;r+=1
    out=[]
    for j in range(n):
        if j not in piv:
            v=1<<j
            for col,i in piv.items():
                if A[i]>>j&1:v^=1<<col
            out.append(v)
    assert all((v&a).bit_count()%2==0 for v in out for a in rows)
    return out

def solve(eqs):
    piv={}
    for t,(z,rhs) in enumerate(eqs):
        a=z;v=rhs;proof=1<<t
        while a:
            k=a.bit_length()-1
            if k in piv:
                b,r,old=piv[k]
                a^=b;v^=r;proof^=old
            else:piv[k]=(a,v,proof);break
        if not a and v:
            return len(piv),[i for i in range(t+1) if proof>>i&1]
    return len(piv),None

def certify():
    A=geometry();C=span_basis(A);K=null_basis(A)
    assert len(C)==16 and len(K)==24
    masks=[x&c for x in K for c in C]
    assert len(masks)==384 and all(z.bit_count()%2==0 for z in masks)
    rank,err=solve([(z,0) for z in masks])
    assert rank==39 and err is None
    # Let U=product T_i^theta_i. For all c in C and x in ker(A),
    # constant amplitudes on |x+C> require theta dot (x AND c)=0 mod4.
    # Modulo 2, theta parity is in a 1D nullspace, generated by 1^40.
    # If all odd, write theta_i=1+2s_i (mod4).
    # Then s dot (x AND c)=|x AND c|/2 (mod2).
    rank2,proof=solve([(z,(z.bit_count()//2)%2) for z in masks])
    assert proof is not None
    xor=0;rhs=0;witness=[]
    for t in proof:
        z=masks[t];xor^=z;rhs^=(z.bit_count()//2)%2
        witness.append(dict(kernel_basis=t//len(C),code_basis=t%len(C),
                            mask=hex(z),size=z.bit_count()))
    assert xor==0 and rhs==1 and len(proof)==4
    return dict(status="PASS",n=40,stabilizer_rank=16,kernel_rank=24,
                logical_qubits=8,constraints=384,parity_rank=rank,
                odd_theta_pattern_impossible=True,
                contradiction_four_terms=witness,
                contradiction_xor_mask=hex(xor),contradiction_rhs=rhs,
                conclusion="All surviving diagonal T-exponent patterns theta_j in Z8 have even theta_j; resulting logical gates are Clifford.",
                boundary="Does not exclude magic injection, adaptive protocols, non-diagonal gates or other CSS codes.")

if __name__=="__main__":print(json.dumps(certify(),indent=2))
