Vec4 = tuple[int, int, int, int]
Mat2 = tuple[int, int, int, int]
Flat4 = tuple[int, ...]
ZERO4: Vec4 = (0, 0, 0, 0)
I2: Mat2 = (1, 0, 0, 1)
