def rank(rows):
    piv={}
    for x in rows:
        while x:
            p=x.bit_length()-1
            if p in piv:x^=piv[p]
            else:piv[p]=x;break
    return len(piv)

def main():
    G=build_W(5);stars=[0]*len(G['flags'])
    for a,es in enumerate(G['apt_edges']):
        bit=1<<a
        for e in es:stars[e]|=bit
    byp=defaultdict(list)
    for e,(p,l) in enumerate(G['flags']):byp[p].append(e)
    W=[];meta=[]
    for p in range(len(G['pts'])):
        fs=byp[p];assert len(fs)==6
        for i,j in itertools.combinations(range(6),2):
            W.append(stars[fs[i]]^stars[fs[j]]);meta.append((p,i,j))
