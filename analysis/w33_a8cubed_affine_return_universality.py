"""Conditional dynamical-Lie universality of the A8^3 affine-return layer.

The repository already certifies a 9x9x9=729 twisted ground register, local
weight-one algebra sl9^3, and Niemeier glue generated by permutations of
(1,1,4).  For a lattice vertex pair V_lambda V_-lambda the free-boson OPE has
quadratic descendant (J_lambda)^2/2.  Since lambda=(lambda_1,lambda_1,lambda_4)
has all three factor components nonzero, this descendant contains nonzero
cross terms H_i tensor H_j on a connected three-block interaction graph.

This file records the exact Lie-algebra consequence under one explicit control
assumption: local sl9 zero modes and at least one such nonzero cross term on
each edge of a connected block graph are independently addressable Hamiltonians.
Then simplicity of sl9 implies the local adjoint orbit of H_i spans sl9, so
commutators generate sl9 tensor sl9 on an edge.  Hence

  sl(d^2) = sl(d)⊗1 ⊕ 1⊗sl(d) ⊕ sl(d)⊗sl(d),

and induction across a connected graph gives sl(d^n).  For d=9,n=3 this is
sl729, dimension 729^2-1 = 531440.

This is a mathematical controllability theorem conditional on access to the
certified VOA operators.  It is not a claim that current Holonet hardware has
implemented or independently drives those Hamiltonians.
"""
from __future__ import annotations
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'data'/'w33_a8cubed_affine_return_universality.json'

def sl_dim(d:int)->int:return d*d-1

def edge_closure_dim(d:int)->int:
    a=sl_dim(d)
    # sl(d)⊗1 + 1⊗sl(d) + sl(d)⊗sl(d)
    return a+a+a*a

def main(write=True):
    glue=json.loads((ROOT/'data'/'w33_a8_cubed_niemeier_glue.json').read_text())
    reg=json.loads((ROOT/'data'/'w33_e8cubed_leech_six_qutrit_register.json').read_text())
    assert glue['status']=='PASS' and reg['status']=='PASS'
    assert glue['glue']['order']==27 and glue['minimal_cross_factor_weight']==2
    gen=glue['generator_vertex_operators'][0]
    word=tuple(gen['glue_word']);assert word==(1,1,4) and all(k%9 for k in word)
    assert reg['E8_cubed']['ground_register_factorization'].startswith('9 x 9 x 9')
    d=9;n=3
    assert edge_closure_dim(d)==sl_dim(d*d)==6560
    full=d**n
    assert full==729 and sl_dim(full)==531440
    # The quadratic current descendant of J=H1+H2+H3 has all three cross terms.
    edges=[(1,2),(1,3),(2,3)]
    out={
      'schema':'w33.a8cubed_affine_return_universality.v1','status':'PASS',
      'headline':'Conditional on independent control of the certified local sl9 zero modes and one nonzero quadratic return-OPE cross term on a connected block graph, the A8^3 9x9x9 register has dynamical Lie algebra sl729, dimension 531440. The glue generator (1,1,4) supplies cross terms on all three block pairs through (J_lambda)^2.',
      'register':{'block_dimension':d,'blocks':n,'Hilbert_dimension':full,'local_algebra':'sl9^3'},
      'glue_return':{'word':list(word),'weight':gen['ground_weight'],'all_factor_components_nonzero':True,
                     'quadratic_descendant':'(J_lambda)^2/2','cross_edges':[list(e) for e in edges]},
      'lie_closure':{'single_edge':'sl81','single_edge_dimension':edge_closure_dim(d),
                     'connected_three_block_graph':'sl729','full_dimension':sl_dim(full),
                     'proof':'sl9 is simple, so the local adjoint orbit of any nonzero H spans sl9; commutators of local controls with H⊗K generate sl9⊗sl9. Adding local summands gives sl81. Repeating across a connected edge to the third block gives sl729.'},
      'external_control_theorem':'Consistent with Nielsen-Bremner-Dodd-Childs-Dawson, Phys. Rev. A 66, 022317 (2002): any fixed entangling qudit interaction plus local unitaries is universal for Hamiltonian simulation.',
      'control_assumption':'The relevant affine zero modes and quadratic V_c V_-c return descendants can be independently addressed with continuously tunable real Hamiltonian coefficients.',
      'physical_boundary':'The repository certifies the operator algebra, not hardware addressability, switching bandwidth, leakage suppression, or an implemented pulse sequence. Therefore this is conditional controllability, not a machine-level universality certificate.',
      'checks':{'register_729':True,'glue_word_114':True,'weight2_return_sector':True,'all_three_cross_edges':True,'sl81_dimension':True,'sl729_dimension_531440':True}}
    if write:OUT.write_text(json.dumps(out,indent=2)+'\n')
    print(json.dumps(out,indent=2));return out
if __name__=='__main__':main(True)
