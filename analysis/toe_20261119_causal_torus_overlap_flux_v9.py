SZ=np.diag([1.,-1.])

def rank2(columns):
    """GF2 rank of sparse boundary columns, encoded as Python integers."""
    pivots={}
    for col in columns:
        col=int(col)
        if col<0 or col.bit_length()>100000:raise ValueError('malformed boundary bitset')
        steps=0
        while col:
            k=col.bit_length()-1
            if k in pivots:
                col^=pivots[k]
                if col and col.bit_length()-1>=k:raise ValueError('GF2 pivot did not decrease')
            else:
                pivots[k]=col
                break
            steps+=1
            if steps>10000:raise ValueError('GF2 elimination exceeded finite dimension')
    return len(pivots)

def torus_incidence(n):
    """Antichain -> later witness relation generated by periodic 2x2 shadows."""
    N=n*n
    R=np.zeros((N,N),np.uint8)
    for ax in range(n):
        for ay in range(n):
            a=ax*n+ay
            for dx in (0,1):
                for dy in (0,1):
                    w=((ax+dx)%n)*n+(ay+dy)%n
                    R[a,w]=1
    assert (R.sum(axis=0)==4).all() and (R.sum(axis=1)==4).all()
    return R

def dowker_homology(R):
    """GF2 simplicial 3-skeleton of nerve: simplex iff shared past witness."""
    N=R.shape[1]
    maximal=[tuple(np.flatnonzero(R[a])) for a in range(R.shape[0])]
    faces=[sorted({tuple(s) for simplex in maximal for s in itertools.combinations(simplex,k)})
           for k in (1,2,3,4)]
    ranks=[0]
    for dim in (1,2,3):
        lower={face:i for i,face in enumerate(faces[dim-1])}
        cols=[]
        for simplex in faces[dim]:
            bits=0
            for face in itertools.combinations(simplex,dim):
                bits^=1<<lower[face]
            cols.append(bits)
        ranks.append(rank2(cols))
    b0=len(faces[0])-ranks[1]
    b1=len(faces[1])-ranks[1]-ranks[2]
    b2=len(faces[2])-ranks[2]-ranks[3]
    return {"bettis_0_1_2":[b0,b1,b2],"simplex_counts_0_to_3":[len(x) for x in faces],
            "boundary_ranks_1_to_3":ranks[1:]}

def four_cycles(G):
    """Enumerate *all* induced square faces, no coordinate input."""
    vertices=sorted(G)
    out=set()
    for a in vertices:
        for b,c in itertools.combinations(sorted(G[a]),2):
            if c in G[b]:continue  # chord
            common=G[b].intersection(G[c])-{a}
            for d in common:
                if d in G[a]:continue  # opposite corner cannot be a chord
                cycle=(a,b,d,c)
                # canonical under dihedral changes
                candidates=[]
                for s in range(4):
                    rot=cycle[s:]+cycle[:s]
                    candidates.append(rot)
                    candidates.append(tuple(reversed(rot)))
                out.add(min(candidates))
    return sorted(out)

def recover_torus(R,require_homology=True):
    R=np.asarray(R,dtype=np.uint8)
    if R.ndim!=2 or R.shape[0]!=R.shape[1]:raise ValueError("square incidence required")
    n=math.isqrt(R.shape[1])
    if n*n!=R.shape[1] or n<5:raise ValueError("requires square grid n>=5 as benchmark")
    nerve=dowker_homology(R)
    if require_homology and nerve["bettis_0_1_2"]!=[1,2,1]:
        raise ValueError("failed torus Dowker nerve homology")
    C=R.astype(int).T@R.astype(int)
    np.fill_diagonal(C,0)
    maximum=int(np.max(C))
    if maximum!=2:raise ValueError("incorrect shadow-overlap signature")
    N=n*n
    graph={v:set(np.flatnonzero(C[v]==maximum)) for v in range(N)}
    if any(len(v)!=4 for v in graph.values()):raise ValueError("not a four-valent torus graph")
    squares=four_cycles(graph)
    if len(squares)!=N:raise ValueError(f"expected exactly {N} elementary squares, got {len(squares)}")
    root=0
    # At root, two neighbors are perpendicular iff they share an elementary face.
    xnext=min(graph[root])
    perpendicular=[u for u in sorted(graph[root]) if u!=xnext and
                 any(root in s and xnext in s and u in s for s in squares)]
    if len(perpendicular)!=2:raise ValueError("cannot extract local perpendicular axis")
    ynext=perpendicular[0]
    def opposite(v,previous):
        candidates=graph[v]-{previous}
        pair=[w for w in candidates if not any(v in s and previous in s and w in s for s in squares)]
        if len(pair)!=1:raise ValueError("local opposite direction not uniquely identified")
        return pair[0]
    xaxis=[root,xnext]
    while len(xaxis)<n:
        xaxis.append(opposite(xaxis[-1],xaxis[-2]))
    if opposite(xaxis[-1],xaxis[-2])!=root:raise ValueError("x cycle did not close")

    # Parallel-transport the +y direction along +x by using the unique
    # diagonal completing the elementary square.
    yseed=[ynext]
    for i in range(n-1):
        left=xaxis[i];right=xaxis[i+1];up=yseed[-1]
        candidates=(graph[right]&graph[up])-{left}
        if len(candidates)!=1:raise ValueError("cannot parallel-transport y direction")
        yseed.append(next(iter(candidates)))
    coord={}
    for i in range(n):
        row=[xaxis[i],yseed[i]]
        while len(row)<n:
            row.append(opposite(row[-1],row[-2]))
        if opposite(row[-1],row[-2])!=row[0]:raise ValueError("y cycle did not close")
        for j,v in enumerate(row):
            if v in coord:raise ValueError("overlapping inferred grid")
            coord[v]=(i,j)
    if len(coord)!=N:raise ValueError("non-surjective inferred coordinates")
    inverse={v:k for k,v in coord.items()}
    for v,(i,j) in coord.items():
        for delta in ((1,0),(-1,0),(0,1),(0,-1)):
            w=inverse[((i+delta[0])%n,(j+delta[1])%n)]
            if w not in graph[v]:raise ValueError("inferred coordinate is not graph-local")
    # Independent GF2 cubical homology on inferred faces
    edges=sorted({tuple(sorted((i,j))) for i in graph for j in graph[i]})
    edgeids={e:k for k,e in enumerate(edges)}
    # Cast numpy.int64 labels BEFORE shifts: 1 << np.int64(64) overflows.
    rank1=rank2([(1<<int(a))^(1<<int(b)) for a,b in edges])
    faces_cols=[]
    for f in squares:
        bits=0
        for a,b in zip(f,f[1:]+f[:1]):
            bits^=1<<edgeids[tuple(sorted((a,b)))]
        faces_cols.append(bits)
    rank2faces=rank2(faces_cols)
    cellular=[N-rank1,len(edges)-rank1-rank2faces,len(squares)-rank2faces]
    if cellular!=[1,2,1]:raise ValueError("independent cubical torus topology failed")
    return {"n":n,"N":N,"graph":graph,"faces":squares,"coordinate":coord,
            "inverse_coordinate":inverse,"nerve":nerve,
            "cellular_betti":cellular,"cellular_boundary_ranks":[rank1,rank2faces],
            "V_E_F":[N,len(edges),len(squares)],
            "Euler_V_minus_E_plus_F":N-len(edges)+len(squares)}

def gauge_shifts(recovered,Q):
    """External uniform flux Q on edges of order-inferred square torus."""
    n=recovered["n"];N=n*n
    inverse=recovered["inverse_coordinate"]
    Tx=np.zeros((N,N),complex);Ty=np.zeros((N,N),complex)
    for x in range(n):
        for y in range(n):
            v=inverse[x,y]
            ux=np.exp(-2j*np.pi*Q*y/(n*n))
            uy=np.exp(+2j*np.pi*Q*x/n) if y==n-1 else 1.
            Tx[v,inverse[(x+1)%n,y]]=ux
            Ty[v,inverse[x,(y+1)%n]]=uy
    plaquettes=[]
    for x in range(n):
        for y in range(n):
            v=inverse[x,y];vr=inverse[(x+1)%n,y];vu=inverse[x,(y+1)%n]
            u_x=Tx[v,vr];u_y_next=Ty[vr,inverse[(x+1)%n,(y+1)%n]]
            u_x_next=Tx[vu,inverse[(x+1)%n,(y+1)%n]];u_y=Ty[v,vu]
            plaquettes.append(float(np.angle(u_x*u_y_next*np.conj(u_x_next)*np.conj(u_y))))
    Q_calc=round(sum(plaquettes)/(2*np.pi))
    assert Q_calc==Q and max(abs(a-2*np.pi*Q/(n*n)) for a in plaquettes)<1e-11
    return Tx,Ty,{"input_flux_Q":Q,"recovered_flux_Q":Q_calc,
                  "min_plaquette_angle":min(plaquettes),"max_plaquette_angle":max(plaquettes),
                  "flux_mean_plaquette_angle":float(np.mean(plaquettes))}

def overlap_from_shifts(Tx,Ty,m=1.,full=False):
    N=Tx.shape[0]
    D=(2-m)*np.eye(2*N,dtype=complex)
    for T,g in ((Tx,SX),(Ty,SY)):
        D-=.5*(np.kron(T,I2-g)+np.kron(T.conj().T,I2+g))
    g5=np.kron(np.eye(N),SZ)
    H=g5@D
    if np.linalg.norm(H-H.conj().T)>1e-10:raise ValueError("not gamma5 Hermitian")
    lam,V=np.linalg.eigh(H)
    gap=float(np.min(abs(lam)))
    if gap<1e-8:raise ValueError("gapless Wilson kernel")
    index=int(round(-.5*float(np.sign(lam).sum())))
    ans={"index":index,"Hermitian_kernel_gap":gap,"Hermitian_residual":float(np.linalg.norm(H-H.conj().T))}
    if full:
        signH=(V*np.sign(lam))@V.conj().T
        ov=np.eye(2*N,dtype=complex)+g5@signH
        gw=g5@ov+ov@g5-ov@g5@ov
        ans["GW_Frobenius_residual"]=float(np.linalg.norm(gw))
        ans["zero_mode_count"]=int(np.sum(abs(np.linalg.eigvals(ov))<1e-8))
        assert ans["GW_Frobenius_residual"]<1e-10
        assert ans["zero_mode_count"]>=abs(index)
    return ans

def one_case(n):
    recovered=recover_torus(torus_incidence(n))
    out={"n":n,"V_E_F":recovered["V_E_F"],"Euler":recovered["Euler_V_minus_E_plus_F"],
         "nerve_homology":recovered["nerve"],"cellular_betti":recovered["cellular_betti"],
         "cellular_boundary_ranks":recovered["cellular_boundary_ranks"],"flux_cases":[]}
    for Q in (-1,0,1):
        Tx,Ty,plaquette=gauge_shifts(recovered,Q)
        idx=overlap_from_shifts(Tx,Ty,m=1.,full=(n==5 and Q==1))
        if idx["index"]!=-Q:raise ValueError(f"index mismatch n={n} Q={Q} {idx}")
        out["flux_cases"].append({**plaquette,**idx})
    return out

