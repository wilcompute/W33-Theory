def pass_2885() -> dict:
    print()
    print("=" * 78)
    print("Pass 2885 -- what ARE the 188 hardest elements?")
    print("=" * 78)
    # The Pass 2866 triple, which is the SHORTEST of the six (Pass 2882).  An
    # earlier version of this line used TRIPLES[0] and reported a 2-element shell
    # at distance 23 -- correct for that triple, and the wrong triple to ask about.
    best_triple = ("F_p", "CX_pf", "CX_fp")
    print(f"  triple: {' + '.join(best_triple)}  (the shortest of the six)")
    r = bfs_diameter(best_triple, want_shell=True)
    shell, sp_list, tvecs = r["_shell"], r["_sp_list"], r["_tvecs"]
    print(f"  elements at distance {r['diameter']}: {shell.size}")

    NT = 81
    sp_ids = shell // NT
    t_ids = shell % NT
    print(f"  distinct linear parts among them : {len(set(sp_ids.tolist()))}")
    print(f"  distinct translations among them : {len(set(t_ids.tolist()))}")

    tcount = Counter(t_ids.tolist())
    print(f"  translation multiset: {sorted(Counter(tcount.values()).items())}"
          f"  (size -> how many translations occur that often)")

    # do they share a linear part, i.e. is the worst case one coset?
    spcount = Counter(sp_ids.tolist())
    print(f"  linear-part multiset: {sorted(Counter(spcount.values()).items())}")

    # order statistics of the linear parts -- a conjugation-invariant fingerprint
    def order_of(M):
        k, P = 1, M
        while P != IDENT:
            P = mul(P, M)
            k += 1
        return k
    orders = Counter(order_of(sp_list[i]) for i in set(sp_ids.tolist()))
    print(f"  element orders of the distinct linear parts: {dict(sorted(orders.items()))}")

    # traces are conjugation invariants over F_3
    traces = Counter(sum(sp_list[i][j][j] for j in range(4)) % 3
                     for i in set(sp_ids.tolist()))
    print(f"  traces mod 3 of those linear parts: {dict(sorted(traces.items()))}")

    single_trace = len(traces) == 1
    print(f"\n  the hard shell has a single trace class: {single_trace}")
    print("""
  SO THE HARD SHELL IS RARE BUT NOT STRUCTURED.  188 of 4,199,040 is 0.0045%, yet those
  188 spread over 54 distinct linear parts, element orders 4 through 18, and all three
  trace classes.  There is no single "hardest instruction" to name, and the hypothesis
  that the worst case would be one conjugacy class or one coset is REFUTED.

  What survives is the useful part: 188 is small enough to enumerate exactly, so a
  compiler regression suite can contain EVERY worst-case input rather than sampling for
  them.  A negative structural result and a positive engineering one from the same run.""")
    return {"diameter": r["diameter"], "shell_size": int(shell.size),
            "distinct_linear_parts": len(set(sp_ids.tolist())),
            "distinct_translations": len(set(t_ids.tolist())),
            "linear_part_orders": {str(k): v for k, v in sorted(orders.items())},
            "traces_mod_3": {str(k): v for k, v in sorted(traces.items())},
            "single_trace_class": bool(single_trace)}


