"""Passes 2882-2885 -- four questions, two of them from outside the programme.

PASS 2882 -- DO THE OTHER FIVE MINIMAL TRIPLES DO BETTER THAN 19?
    Pass 2789 found six minimal generating triples; Pass 2866 measured the diameter of one
    of them at 19.  If another is shorter, that one is the triple to build, and the choice
    is free -- all six generate the same group.

PASS 2885 (OUTSIDE) -- WHAT ARE THE 188 HARDEST ELEMENTS?
    Only 188 of 4,199,040 group elements sit at distance exactly 19.  A worst case that
    rare is worth naming: it is the compiler's hardest test vector, and if the 188 have
    structure then "the hardest program" is a group-theoretic object rather than a lucky
    find.

PASS 2884 (OUTSIDE) -- THE 240 EDGES AS A BUDGET.
    docs/index.html gives the Hodge Laplacian spectrum on 1-chains as
    {0: 81, 4: 120, 10: 24, 16: 15}, summing to 240 = the edge count.  So the machine's
    240 wires decompose into four named sectors, and two of those numbers are already
    architectural quantities elsewhere in this project: 15 is the support-shell dimension
    and 24 is the order of the single-qutrit Clifford group modulo phase.  This
    recomputes the spectrum independently and then states VERY carefully which of those
    are maps and which are only equal integers -- the repo's second documented failure
    mode is exactly an over-read of a count match.

PASS 2883 -- IS THE 81 = 81 COINCIDENCE A MAP?
    H_1(W(3,3); Z) = Z^81 and |F_3^4| = 81.  The blueprint states the counts agree and
    declines to claim more.  This asks the sharper question: is there a natural
    Sp(4,3)-equivariant isomorphism, or are the two 81s different representations?

    py -3 analysis/w33_pass2882_2885_diameters_hardest_and_budget.py
"""

