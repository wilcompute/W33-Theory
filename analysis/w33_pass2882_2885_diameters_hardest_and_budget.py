def pass_2884() -> dict:
    print()
    print("=" * 78)
    print("Pass 2884 -- the 240 edges as a budget")
    print("=" * 78)

    # Build W(3,3): 40 points of PG(3,3), collinear iff the symplectic form vanishes.
    J = [[0, 1, 0, 0], [2, 0, 0, 0], [0, 0, 0, 1], [0, 0, 2, 0]]
    pts, seen = [], set()
    for v in np.ndindex(3, 3, 3, 3):
        if v == (0, 0, 0, 0):
            continue
        key = min(tuple((c * k) % 3 for k in v) for c in (1, 2))
        if key in seen:
            continue
        seen.add(key)
        pts.append(key)
    n = len(pts)
    print(f"  projective points of PG(3,3): {n}")

    def form(u, v):
        return sum(u[i] * J[i][j] * v[j] for i in range(4) for j in range(4)) % 3

    adj = np.zeros((n, n), dtype=bool)
    for i in range(n):
        for j in range(n):
            if i != j and form(pts[i], pts[j]) == 0:
                adj[i, j] = True
    edges = [(i, j) for i in range(n) for j in range(i + 1, n) if adj[i, j]]
    tris = [t for t in combinations(range(n), 3)
            if adj[t[0], t[1]] and adj[t[0], t[2]] and adj[t[1], t[2]]]
    print(f"  edges {len(edges)}   triangles {len(tris)}")

    # Hodge Laplacian on 1-chains: L1 = d0 d0^T + d1^T d1
    eidx = {e: k for k, e in enumerate(edges)}
    d0 = np.zeros((len(edges), n))
    for (i, j), k in eidx.items():
        d0[k, i], d0[k, j] = -1.0, 1.0
    d1 = np.zeros((len(tris), len(edges)))
    for r, (a, b, c) in enumerate(tris):
        d1[r, eidx[(a, b)]] = 1.0
        d1[r, eidx[(b, c)]] = 1.0
        d1[r, eidx[(a, c)]] = -1.0
    L1 = d0 @ d0.T + d1.T @ d1
    ev = np.round(np.linalg.eigvalsh(L1), 6)
    spec = Counter(ev.tolist())
    print(f"  Hodge L1 spectrum: {dict(sorted(spec.items()))}")
    total = sum(spec.values())
    print(f"  multiplicities sum to {total} = the edge count: {total == len(edges)}")

    harmonic = spec.get(0.0, 0)
    print(f"""
  So the machine's {len(edges)} wires split into four sectors, and the harmonic one has
  dimension {harmonic} -- the same as the frame register file and the logical dimension of
  the substrate's own qutrit CSS code [240, 81, d_Z = 4] (prior art: docs/index.html).

  THE OTHER THREE NUMBERS, AND WHAT IS AND IS NOT BEING CLAIMED.  Two of them coincide
  with quantities that appear elsewhere in this architecture:
      15 = the dimension of the support shell (parallel track, Pass 2808)
      24 = |SL(2,3)| = the single-qutrit Clifford group modulo phase (Pass 2708)
  These are EQUAL INTEGERS.  No map is exhibited here in either case, and this project's
  second documented failure mode is precisely an over-read of a count match.  They are
  recorded as a question -- is either coincidence carried by a natural map? -- and not as
  a decomposition of the machine into its subsystems, which is what it would be if the
  maps existed.""")
    return {"points": n, "edges": len(edges), "triangles": len(tris),
            "hodge_spectrum": {str(k): v for k, v in sorted(spec.items())},
            "harmonic_dimension": harmonic,
            "sums_to_edge_count": bool(total == len(edges)),
            "count_matches_flagged_not_claimed": ["15 = support shell",
                                                  "24 = |SL(2,3)|"]}


