def pass_2882() -> dict:
    print("=" * 78)
    print("Pass 2882 -- diameters of all six minimal triples")
    print("=" * 78)
    print("  triple                       diameter   mean    shell at diameter")
    res = {}
    for names in TRIPLES:
        r = bfs_diameter(names)
        key = " + ".join(names)
        res[key] = {k: v for k, v in r.items() if not k.startswith("_")}
        print(f"  {key:28s} {r['diameter']:5d}   {r['mean']:7.3f}   {r['shell_size']:6d}")
    best = min(res.items(), key=lambda kv: (kv[1]["diameter"], kv[1]["mean"]))
    diams = {v["diameter"] for v in res.values()}
    print(f"\n  best: {best[0]}  diameter {best[1]['diameter']}, mean {best[1]['mean']:.3f}")
    print(f"  distinct diameters across the six: {sorted(diams)}")
    if len(diams) == 1:
        print("""
  ALL SIX HAVE THE SAME DIAMETER.  That is not obvious a priori -- the six triples are
  different generating sets -- and it means the choice among them is free at the
  instruction-count level.  Pick whichever is cheapest in silicon; none of them costs a
  longer worst-case program.""")
    else:
        print("\n  The triples differ, so the choice is NOT free: build the shortest.")
    return {"per_triple": res, "distinct_diameters": sorted(diams),
            "choice_is_free": len(diams) == 1}


