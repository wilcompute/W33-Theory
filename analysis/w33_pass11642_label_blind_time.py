def perm_sign(p):
    s = 1
    for i, j in itertools.combinations(range(4), 2):
        if p[i] > p[j]:
            s = -s
    return s


SIGNS = np.array([perm_sign(p) for p in PERMS], np.int64)


def mub_data(n_points=420, seed=11642):
    w = np.exp(2j * np.pi / 3)
    F = np.array([[w ** (j * k) for k in range(3)] for j in range(3)]) / np.sqrt(3)
    Xm = np.roll(np.eye(3), 1, axis=0)
    Zm = np.diag([1, w, w * w])
    bases = [np.eye(3)]
    for a in range(3):
        _, V = np.linalg.eig(Xm @ np.linalg.matrix_power(Zm, a))
        bases.append(V)
    # labels Z, X, XZ, XZ2; complex conjugation swaps the last two (Pass 11641)
    rng = np.random.default_rng(seed)
    a, b = rng.integers(-3, 4, size=(2, n_points, 3))
    psi = a + b * w
    q = np.stack([3 * np.abs(psi @ B.conj()) ** 2 for B in bases], 1)      # (pts, 4, 3)
    qi = np.rint(q).astype(np.int64)
    assert np.abs(q - qi).max() < 1e-7
    n3 = qi[:, 0].sum(1)
    assert all((qi[:, b].sum(1) == n3).all() for b in range(4))
    e2 = qi[:, :, 0] * qi[:, :, 1] + qi[:, :, 0] * qi[:, :, 2] + qi[:, :, 1] * qi[:, :, 2]
    P3 = qi[:, :, 0] * qi[:, :, 1] * qi[:, :, 2]
    # time reversal check: conj(psi) swaps MUB spectra 2 <-> 3
    qc = np.stack([3 * np.abs(np.conj(psi) @ B.conj()) ** 2 for B in bases], 1)
    assert np.allclose(np.sort(qc[:, 2], 1), np.sort(q[:, 3], 1)) and np.allclose(np.sort(qc[:, 0], 1), np.sort(q[:, 0], 1))
    return n3 % PR, e2 % PR, P3 % PR, F


def lb_monomials(k):
    """(a, i[4], j[4]) with a + 2 sum i + 3 sum j = k"""
    out = []
    for J in range(k // 3 + 1):
        for I in range((k - 3 * J) // 2 + 1):
            a = k - 3 * J - 2 * I
            for js in itertools.product(range(J + 1), repeat=4):
                if sum(js) != J:
                    continue
                for is_ in itertools.product(range(I + 1), repeat=4):
                    if sum(is_) == I:
                        out.append((a, is_, js))
    return out


def powmod(x, e):
    r = np.ones_like(x)
    for _ in range(e):
        r = r * x % PR
    return r


