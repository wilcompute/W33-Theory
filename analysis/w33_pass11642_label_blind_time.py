"""Pass 11642: label-blind time -- which Clifford invariants of a qutrit state see only the four MUB outcome SPECTRA.

Measure a qutrit state in each of its four mutually unbiased bases and forget which outcome is which inside each basis:
what remains is, for every MUB b, the multiset of its three probabilities, i.e. (with N = |psi|^2)
    e2_b = sum_{s<s' in b} p_s p_s' ,     Pi_b = prod_{s in b} p_s .
A Clifford unitary permutes the four MUBs by an element of A4; complex conjugation (time reversal) swaps two of them.
So the LABEL-BLIND invariants are the S4-symmetric (time-even) and S4-alternating (time-odd) polynomials in N, e2_b, Pi_b.

Questions answered here, exactly (evaluations at Z[omega] points, where q_s = 3 p_s is an integer, modulo P = 2^31 - 19;
rank mod P <= rank over Q, and equality with the Molien dimension of Pass 11491 is a proof of spanning):
  1. even: is every time-even invariant label-blind?  (Pass 11534 says the even ring is generated by the stabiliser moments
     M_k = sum_b sum_{s in b} p_s^k through degree 20, which are label-blind; checked independently here.)
  2. odd: in which degrees do label-blind time arrows exist, and what fraction of the time-odd module do they span?
     A degree argument gives >= 9 (an alternant needs four distinct monomials in (e2, Pi), of degrees >= 0+2+3+4);
     the true arrow starts at degree 6 (Pass 11491).
  3. relations: the complete list of minimal polynomial relations among N, e2_b, Pi_b through a degree bound.
"""

