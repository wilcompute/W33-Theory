"""Finite-isometry repair of the quadric: exact cost in gauge monodromy.

Companion: analysis/2026-11-18_tetrahedral_quadric_repair_cost.md.
This is a geometric obstruction/control, not a new completed vacuum.
"""
import json
from itertools import product
from pathlib import Path
import sympy as s

ROOT = Path(__file__).resolve().parents[1]


def run():
    cyc = s.Matrix([[0, 1, 0], [0, 0, 1], [1, 0, 0]])
    signs = [s.diag(*v) for v in product([-1, 1], repeat=3)
             if v[0]*v[1]*v[2] == 1]
    tetra = [d*cyc**j for d in signs for j in range(3)]
    key = lambda m: tuple(m)
    lookup = {key(m): i for i, m in enumerate(tetra)}
    identity = lookup[key(s.eye(3))]
    assert len(lookup) == 12
    mult = {(i,j): lookup[key(a*b)] for i,a in enumerate(tetra)
            for j,b in enumerate(tetra)}
    orders = []
    for i in range(12):
        p, n = i, 1
        while p != identity:
            p, n = mult[p,i], n+1
        orders.append(n)
    assert sorted(orders) == [1]+[2]*3+[3]*8
    elements = list(product(range(12), range(5), range(2)))
    def mul(x,y):
        i,a,b = x
        j,c,d = y
        return (mult[i,j], (a+(-1)**b*c)%5, (b+d)%2)
    assert len({mul(x,y) for x in elements for y in elements}) == 120
    # h=(-I3, reflection in the normal real plane), det(h)=1.
    # It reverses the C5 rotation and commutes with the tetrahedral group.
    h = (identity,0,1)
    g = (identity,1,0)
    assert mul(h,h) == (identity,0,0)
    assert mul(mul(h,g),h) == (identity,4,0)
    # Characteristic-zero fixed dimensions: normal eigenvalue+1 has
    # dimension2(identity),0(nontrivial rotation),1(reflection).
    fixed_census = {}
    cyclic_strata = {}
    for i,a,b in elements:
        zdim = 3-(((-1)**b)*tetra[i]-s.eye(3)).rank()
        normaldim = (2 if a == 0 else 0) if b == 0 else 1
        dim = zdim+normaldim
        fixed_census[dim] = fixed_census.get(dim,0)+1
        if dim == 3:
            n, p = 1, (i,a,b)
            while p != (identity,0,0):
                p,n = mul(p,(i,a,b)),n+1
            cyclic_strata[n] = cyclic_strata.get(n,0)+1
    assert sum(fixed_census.values()) == 120
    assert cyclic_strata == {2:18,3:8,5:4}, cyclic_strata
    # Orthogonal finite-order eigenspaces of eigenvalue1 are nondegenerate.
    # A dimension3 fixed space therefore cuts a quadratic complex surface,
    # whose link is3-dimensional. Generic transverse cyclic types are A1,A2,A4.
    # The normal subgroup generated by fixed-point elements is already all
    # of the holomorphic group. Adding hK (which has fixed points) kills K too.
    stabilizer_generators = [(i,a,b) for i,a,b in elements
        if 3-(((-1)**b)*tetra[i]-s.eye(3)).rank()
           + ((2 if a == 0 else 0) if b == 0 else 1) == 3]
    reached, todo = {(identity,0,0)}, [(identity,0,0)]
    while todo:
        x = todo.pop()
        for y in stabilizer_generators:
            xy = mul(x,y)
            if xy not in reached:
                reached.add(xy); todo.append(xy)
    assert len(reached) == 120

    # Lie algebra centralizer, in the original five orthogonal coordinates.
    v = s.symbols('x0:10')
    B = s.zeros(5)
    pairs = [(i,j) for i in range(5) for j in range(i+1,5)]
    for x,(i,j) in zip(v,pairs):
        B[i,j],B[j,i] = x,-x
    rotation = s.zeros(5)
    rotation[3,4],rotation[4,3] = 1,-1
    H = s.diag(-1,-1,-1,1,-1)
    T = s.diag(cyc,s.eye(2))
    V = s.diag(signs[0],s.eye(2))
    def rank(gens):
        eq = s.Matrix([x for A in gens for x in B*A-A*B])
        return eq.jacobian(v).rank()
    assert rank([rotation]) == 6
    assert rank([rotation,H]) == 7
    assert rank([rotation,H,T,V]) == 10
    # The Reeb direction has already been removed by real conjugation K.

    # Holomorphic normal swap gives +diagram reversal, unlike the -reversal
    # of anti-holomorphic K. Only the latter is the inner longest Weyl element.
    J = s.zeros(5)
    for i in range(5):
        J[i,4-i] = 1
    roots = [s.eye(5)[:,i]-s.eye(5)[:,i+1] for i in range(4)]
    assert all(-J*r == roots[3-i] for i,r in enumerate(roots))
    assert all(J*r == -roots[3-i] for i,r in enumerate(roots))
    # Outer Lie automorphism theta(X)=-J X^T J; fixed algebra is so5(C).
    basis = []
    for i in range(5):
        for j in range(5):
            if i != j:
                e = s.zeros(5); e[i,j] = 1; basis.append(e)
    for i in range(4):
        e = s.zeros(5); e[i,i] = 1; e[4,4] = -1; basis.append(e)
    constraints = s.Matrix.hstack(*[s.Matrix(list(-J*e.T*J-e)) for e in basis])
    assert 24-constraints.rank() == 10
    # hK-fixed real slice has signature(1,4); its unit-link section is two S3s.
    assert H.det() == 1 and H.trace() == -3
    return dict(status='PASS', group='A4(tetrahedral rotations) x D10, order120; '
                'adjoin commuting K for order240',
                generator_h='(-I3 on z, real reflection on normal2-plane)',
                holomorphic_fixed_ambient_dimension_census=fixed_census,
                fixed_three_plane_element_order_census=cyclic_strata,
                generic_cyclic_ADE_types=['A1','A2','A4'],
                geometric_so5_centralizer_dimensions=dict(original_C5=4,
                    add_h=3,add_h_and_tetrahedral=0),
                Reeb_direction='odd under K, already projected out',
                holomorphic_group_generated_by_point_stabilizers=120,
                underlying_full_quotient_pi1='trivial: holomorphic stabilizers '
                    'generate all120 elements, and hK has fixed points and kills K',
                normal_cycle_monodromy_h='E_i -> E_(5-i), outer A4 diagram involution',
                normal_cycle_monodromy_K='E_i -> -E_(5-i), inner longest Weyl element',
                canonical_outer_fixed_algebra='so5, dimension10, rank2',
                new_antiholomorphic_fixed_stratum='hK-fixed slice has signature(1,4); '
                    'unit-link intersection is S0 x S3 before other identifications',
                conclusion='The finite extension removes the continuous geometric '
                    'algebra, but introduces extra A1/A2 loci and outer SU5 monodromy. '
                    'It does not inherit the previous flat SU5-to-SM calculation.',
                scope='No full singular-stratum gluing, quantum spectrum, chiral '
                    'matter or new completed vacuum. Fixed-plane census is exact '
                    'characteristic-zero linear algebra, not a count of all connected '
                    'strata in the final quotient.')


