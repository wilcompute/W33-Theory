#!/usr/bin/env python3
"""Exact finite E6 Weyl-orthogonal 36 anisotropic Pauli reflection
representation, plus full Pauli normalizer audit of original 8-mode
Albert clock. Distinguish 36-point transvections (order 2 on labels)
from order 4 27D signed packet gates and order 8 8D Clifford lifts.
"""
from pathlib import Path
import sys,json
import numpy as np
from sympy.combinatorics import Permutation,PermutationGroup
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"analysis"))
import toe_20261114_exact_gaussian_us8_pauli_clock as E
OUT=ROOT/"data/toe_20261114_pauli_E6_orthogonal_Clifford_group.json"

def tracecoeff(P,Q):
    v=np.trace(P@Q)/8
    assert abs(v.imag)<1e-10
    assert abs(v.real-round(v.real))<1e-10
    return int(round(v.real))

def main():
    pauli,quad,nonquad,pauli_terms=E.pauli_data()
    quad_index={v:i for i,v in enumerate(quad)}
    generators=[]
    for a in nonquad:
        assert E.q(a)==1
        dest=[v^a if E.omega(a,v) else v for v in quad]
        assert set(dest)==set(quad)
        p=Permutation([quad_index[v] for v in dest])
        assert p.order()==2
        # On the 8D physical qubit Hilbert space: H=I+iP_a.
        # H†H=2I, H^4=-4I, so U=H/sqrt2 has U^4=-I.
        H=np.eye(8,dtype=complex)+1j*pauli[a]
        assert np.array_equal(H.conj().T@H,2*np.eye(8))
        assert np.array_equal(np.linalg.matrix_power(H,4),-4*np.eye(8))
        # 1/2 H P_v H† = +P_v if commute, else ±P_(v xor a).
        for v in range(1,64):
            w=v^a if E.omega(a,v) else v
            lhs=H@pauli[v]@H.conj().T
            sign=tracecoeff(pauli[w],lhs/2)
            assert abs(sign)==1
            assert np.array_equal(lhs,2*sign*pauli[w])
        generators.append(p)
    group=PermutationGroup(generators)
    order=int(group.order())
    assert order==51840,order
    # The 27D induced label action is exactly O_6^-(2) ~ W(E6).
    # The sign-lift may form a larger central extension; do not
    # assert its order from the label action.
    d=json.loads((ROOT/"data/toe_20261114_exact_gaussian_integer_USp8_pauli_Albert_intertwiner.json").read_text())
    H=(np.asarray(d["reduced_clock_8_numerator_real"],dtype=np.int64)
       +1j*np.asarray(d["reduced_clock_8_numerator_imag"],dtype=np.int64))
    den=int(d["reduced_clock_8_denominator"])
    assert den==2
    assert np.array_equal(H.conj().T@H,den*den*np.eye(8))
    assert np.array_equal(np.linalg.matrix_power(H,3),-den**3*np.eye(8))
    mapping={}
    n_on_q=0
    for v in range(1,64):
        lhs=H@pauli[v]@H.conj().T
        outcomes=[(w,tracecoeff(pauli[w],lhs/(den*den)))
                  for w in range(1,64)]
        hits=[(w,c) for w,c in outcomes if c]
        assert len(hits)==1,(v,hits)
        w,s=hits[0]
        assert s in (-1,1)
        assert E.q(v)==E.q(w)
        mapping[str(v)]=[w,s]
        if E.q(v)==0:n_on_q+=1
    assert n_on_q==27
    p=Permutation([quad_index[mapping[str(v)][0]] for v in quad])
    assert p in group
    assert p.order()==3
    out=dict(
      status="PASS_EXACT_36_PAULI_CLIFFORD_TRANSVECTIONS_W_E6_51840_AND_ORIGINAL_CLOCK",
      source="27-point elliptic quadratic form Q0+omega(v,YII), 36 anisotropic three-qubit Paulis, exact eight-mode Gaussian numerator",
      n_anisotropic_reflections=36,
      group_on_27_pauli_labels_order=order,
      group_is_classical_Weyl_E6="Orthogonal group O^-(6,2) acting faithfully on 27 quadric points, generated by the 36 transvections sigma_a(v)=v+omega(a,v)a (published standard group order 51840).",
      each_eight_mode_elementary_gate="(I+iP_a)/sqrt(2), order8 in U(8), projective Pauli-Clifford; fourth power -I8",
      each_27D_elementary_packet="Signed monomial order4 on 27; its permutation action is the order2 orthogonal transvection.",
      original_eight_mode_clock_is_3qubit_Clifford=True,
      original_eight_mode_clock_Pauli_images=mapping,
      original_eight_mode_clock_cubed_equals_minus_identity=True,
      original_27D_label_permutation_order=3,
      original_27D_label_permutation_in_W_E6=True,
      negative_quantum_computation_result="In this particular 8D three-qubit encoding, the group generated by these compact 36 quarter-turns and the original order-six Albert clock consists of Clifford operations. Stabilizer inputs and Pauli measurements in that circuit class admit Gottesman-Knill simulation and cannot alone supply universal fault-tolerant quantum computing. DOES NOT rule out other E6/noncompact, encoded 27-mode, photon dynamics, or external magic-state injection.",
      note_prior_art="Orthogonal transvection picture, 36 anisotropic centers, 72 root bases and 51840 W(E6) group are classical and specifically in Alrwajfeh/Al-Ali Bani-Ata J Lie Theory 35 (2025) 157-164, Proposition 2.3. New here is explicit repo matrix, operator, clock and exact arithmetic dictionary.")
    OUT.write_text(json.dumps(out,indent=2,sort_keys=True)+"\n")
    print(json.dumps({k:out[k] for k in ("status","group_on_27_pauli_labels_order","original_eight_mode_clock_is_3qubit_Clifford","original_27D_label_permutation_in_W_E6")},indent=2),flush=True)
    return out
if __name__=="__main__":main()
