def q_from_effects(mats,rho):
    out=[]
    for K in mats:
        rates=np.diag(K@rho@K.conj().T).real
        out.append(rates/rates.sum())
    return np.concatenate(out)

def augmented(A,q):
    K=len(q)//9
    Q=np.zeros((9*K,K))
    for b in range(K):Q[9*b:9*b+9,b]=q[9*b:9*b+9]
    return np.column_stack((A,-Q))

def inversion(A,b,q,ops):
    M=augmented(A,q)
    sigma=float(np.linalg.svd(M,compute_uv=False)[-1])
    x=np.linalg.solve(M,-b)
    rho=np.eye(9)/9+np.einsum("k,kij->ij",x[:80],ops)
    norm=float(np.linalg.svd(realign(rho),compute_uv=False).sum())
    return x,rho,norm,sigma

def worst_case_witness(A,b,q,ops,effect_frobenius_error,prob_linf_error):
    x,rho,norm,sigma=inversion(A,b,q,ops)
    # The 80 traceless Hermitian operators are Hilbert-Schmidt orthonormal.
    # Parseval: ||delta A_(row,:)||2 <= ||delta E_row||F <= e.
    # delta b_row=Tr(delta E)/9 <= e/3.
    # Q(q) has disjoint 9-outcome columns, so ||delta Q||op <= 3eps.
    m=len(q)
    dm=math.sqrt(m)*effect_frobenius_error+3*prob_linf_error
    db=math.sqrt(m)*effect_frobenius_error/3
    if dm>=sigma:
        return dict(certified=False,lower_ccnr=float("-inf"),
                    bound_is_finite=False,condition_failed=True)
    delta=(db+dm*float(np.linalg.norm(x)))/(sigma-dm)
    # ||R(delta rho)||_* <= sqrt(rank<=9)||R(delta rho)||F
    #  = 3 ||delta rho||F = 3||delta theta||2.
    lower=norm-3*delta
    return {"certified":bool(lower>1),"nominal_ccnr":norm,
            "ccnr_conservative_lower":float(lower),
            "state_coefficients_error_upper":float(delta),
            "sigma_min_augmented":sigma,
            "nominal_unknown_vector_l2":float(np.linalg.norm(x)),
            "per_effect_frobenius_error_upper":effect_frobenius_error,
            "per_probability_95pct_error_upper":prob_linf_error,
            "matrix_perturbation_upper":dm,
            "rhs_perturbation_upper":db,
            "bound_is_finite":True,"condition_failed":False}

def max_allowance(A,b,q,ops,mode):
    lo,hi=0.,.01
    for i in range(60):
        mid=(lo+hi)/2
        eps=mid if mode=="q" else 0.
        e=mid if mode=="effect" else 0.
        if worst_case_witness(A,b,q,ops,e,eps).get("certified",False):
            lo=mid
        else:hi=mid
    return lo

def test_adversarial_calibration(mats,A,b,ops,rho,scales):
    rng=np.random.default_rng(202611090783)
    data=[]
    for phase in scales:
        # Delta E is a complete actual POVM perturbation, generated by
        # a phase recalibration error BEFORE the programmed optical gate.
        perturbed=[]
        for K in mats:
            phases=rng.uniform(-phase,phase,size=9)
            perturbed.append(K@np.diag(np.exp(1j*phases)))
        q=q_from_effects(perturbed,rho)
        e=max(float(np.linalg.norm(np.outer(K[j,:].conj(),K[j,:])-
                                   np.outer(J[j,:].conj(),J[j,:]),"fro"))
              for K,J in zip(mats,perturbed) for j in range(9))
        x,rhon,cn,sigma=inversion(A,b,q,ops)
        truth=float(np.linalg.svd(realign(rho),compute_uv=False).sum())
        error=float(np.linalg.norm(rhon-rho,"fro"))
        L=worst_case_witness(A,b,q,ops,e,0.)
        if L["bound_is_finite"]:
            assert error<=L["state_coefficients_error_upper"]+1e-12
            assert truth>=L["ccnr_conservative_lower"]-1e-12
        data.append({"phase_error_input_radians_max":phase,
                     "actual_max_POVM_effect_Frobenius_error":e,
                     "nominal_ccnr":cn,
                     "true_ccnr":truth,
                     "actual_rho_error_Frobenius":error,
                     "conservative":L})
    return data

def main(path=None):
    details,(B,U,V,ops)=optimized(return_components=True)
    mats,A,b=calibrated_inverse(B,U,V,ops,.995,.003,
                            np.random.default_rng(2026110920))
    rho=horodecki_state(.236)
    q=q_from_effects(mats,rho)
    x,reconstructed,ideal_norm,sigma=inversion(A,b,q,ops)
    real_norm=float(np.linalg.svd(realign(rho),compute_uv=False).sum())
    assert np.max(abs(reconstructed-rho))<1e-12
    assert abs(ideal_norm-real_norm)<1e-12
    # Inverted thresholds based on exact expected conditional probabilities;
    # not a real statistical power estimate.
    emax=max_allowance(A,b,q,ops,"effect")
    epsmax=max_allowance(A,b,q,ops,"q")
    K=10;alpha=.05
    required_accepted_N=int(math.floor(math.log(2*9*K/alpha)/(2*epsmax**2))+1)
    joint_e=emax/4
    eps=epsmax/4
    joint=worst_case_witness(A,b,q,ops,joint_e,eps)
    assert joint["certified"]
    sources={"Horodecki_a0p236":rho}
    r=np.random.default_rng(20261109)
    z=r.normal(size=3)+1j*r.normal(size=3)
    y=r.normal(size=3)+1j*r.normal(size=3)
    v=np.kron(z/np.linalg.norm(z),y/np.linalg.norm(y))
    sources["pure_separable_control"]=np.outer(v,v.conj())
    stress={k:test_adversarial_calibration(mats,A,b,ops,s,
                                            (1e-7,1e-6,1e-5,1e-4))
            for k,s in sources.items()}
    assert all(not c["conservative"].get("certified",False)
               for c in stress["pure_separable_control"])
    out={"status":"PASS_BOUND_FULL_POVM_CALIBRATION_AND_SHOTS_DETERMINISTIC",
         "calibration_mesh_intensity_per_element":.995,
         "calibration_mesh_phase_rms":.003,
         "Horodecki_a":.236,
         "ideal_CCNR":real_norm,
         "selfnormalizing_augmented_sigma_min":sigma,
         "maximum_effect_Frobenius_error_for_expected_values_zero_statistical_noise":emax,
         "maximum_each_conditional_frequency_error_zero_calibration_error":epsmax,
         "prospective_95pct_independent_accepted_shots_per_setting_for_zero_calibration_error":required_accepted_N,
         "joint_error_example":{"per_effect_Frobenius_error":joint_e,
                                "each_conditional_probability_error":eps,**joint},
         "adversarial_full_complex_POVM_phase_stress":stress,
         "assumptions":"Effect error bounded in Frobenius per outcome; independent IID accepted shots with simultaneous Hoeffding union bound; source stationary; full POVM basis/normalization trusted; q measured conditional on clicks; no claim of device independence.",
         "scope":"A deterministic Lipschitz guarantee and synthetic expected-frequency resource benchmark, not a measured confidence interval, new entanglement theorem, or viable present-day experimental shot budget."}
    if path:Path(path).write_text(json.dumps(out,indent=2,sort_keys=True)+"\n",encoding="utf8")
    print("PASS robust full POVM bound",json.dumps({
         "CCNR":real_norm,"sigma":sigma,"effect_max":emax,
         "eps_max":epsmax,"N95_per_setting":required_accepted_N,
         "joint_lower":joint["ccnr_conservative_lower"],
         "stress_max_error":max(c["actual_rho_error_Frobenius"]
                 for v in stress.values() for c in v)}))
    return out

if __name__=="__main__":
    main(sys.argv[1] if len(sys.argv)>1 else None)
