def positive_root(k):
    values, u = np.linalg.eigh(k)
    assert min(values) > 0
    return (u*np.sqrt(values))@u.conj().T


def lepton_probe(B=None):
    m = np.array([[1, 1, 0], [0, 2, 1], [1, 0, 3]], float)
    if B is None:
        B = np.array([1+1j, 2-1j, 1+2j])
    K = np.eye(3)-np.outer(B.conj(), B)/(4+np.vdot(B, B).real)
    A = positive_root(K)
    down = m@A; charged = A.T@m.T
    assert np.max(abs(charged-down.T)) < 1e-13
    # Real bare Majorana n; common doublet mixing is a congruence.
    n = np.diag([1., 2., 5.])
    nu = A.T@n@A
    # Two-component convention: W contains e_L^T Me e^c and nu^T mnu nu.
    # Therefore the LEFT charged rotation diagonalizes Me* Me^T.
    _, ue = np.linalg.eigh(charged.conj()@charged.T)
    _, un = np.linalg.eigh(nu.conj().T@nu)
    # Takagi U solves U^T nu U=diag; eigenvectors of nu^dag nu are U.
    mixing = ue.conj().T@un
    J = (mixing[0, 0]*mixing[1, 1]*mixing[0, 1].conj()*mixing[1, 0].conj()).imag
    P = np.array([[1, 0, 0], [0, 0, 1], [0, 1, 0]])
    return dict(charged_singulars=np.sort(np.linalg.svd(charged, compute_uv=False)).tolist(),
                down_singulars=np.sort(np.linalg.svd(down, compute_uv=False)).tolist(),
                PMNS_abs_squared=abs(mixing**2).tolist(), J=float(J),
                theta13_deg=float(np.degrees(np.arcsin(abs(mixing[0, 2])))),
                kernel_parity_commutator=float(np.max(abs(K@P-P@K))),
                unitarity_error=float(np.max(abs(mixing.conj().T@mixing-np.eye(3)))))


