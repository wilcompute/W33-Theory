def scalar_loop(portals=(.1, .2), cp_sign=1, scale=1.):
    """Declared neutral-scalar self-energy; excludes gauge/SUSY diagrams.

    Fields h, ReS1, ImS1, ReS2, ImS2 have unit real-coordinate kinetic
    normalization. Yukawa matrices are derivatives in these coordinates.
    The quadratic scalar Hessian below is a supplied positive local EFT
    Hessian with gauge mode lifted in R_xi; its gauge-mode Yukawa has zero
    theta trace independently. No scalar tadpole shift is included.
    """
    m = np.array([[1, 1, 0], [0, 2, 1], [1, 0, 3]], float)*.1
    r = np.array([1, 2, 1], float)*.1
    t = np.array([1, -1, 2], float)*.1
    M = np.zeros((4, 4), complex); M[:3, :3] = m
    M[3, :3] = r+cp_sign*1j*t; M[3, 3] = .2
    vertices = np.zeros((5, 4, 4), complex)
    vertices[0, :3, :3] = m
    vertices[1, 3, :3] = r; vertices[2, 3, :3] = 1j*r
    vertices[3, 3, :3] = t; vertices[4, 3, :3] = 1j*t
    # Hessian of the explicit CP-real potential recorded below, plus the
    # R_xi gauge-mode lift. This is a distinct non-SUSY model.
    K = np.diag([1., 3., 1.5, 1.5, 3.])
    K[1, 4] = K[4, 1] = cp_sign
    K[2, 3] = K[3, 2] = cp_sign*.5
    K[0, 1] = K[1, 0] = portals[0]
    K[0, 4] = K[4, 0] = cp_sign*portals[1]
    ms, O = np.linalg.eigh(K); assert min(ms) > 0
    U, masses, Vh = np.linalg.svd(M)
    V = Vh.conj().T
    delta = np.zeros((4, 4), complex); divergent = 0j
    for a, mass2 in enumerate(ms):
        gamma = np.einsum("i,ijk->jk", O[:, a], vertices)
        delta += gamma @ ((V*(masses*b0(masses**2, mass2, scale))) @ U.conj().T) @ gamma
        divergent += np.trace(np.linalg.solve(M, gamma@M.conj().T@gamma))
    delta /= 16*np.pi**2
    theta = np.trace(np.linalg.solve(M, delta)).imag
    return dict(theta=float(theta), theta_divergent_coefficient=float(divergent.imag),
                scalar_mass_squared=ms.tolist(), portals=list(portals),
                determinant_phase_before=float(np.angle(np.linalg.det(M))),
                exact_logdet_shift=float(np.angle(np.linalg.det(M+delta)/np.linalg.det(M))))


