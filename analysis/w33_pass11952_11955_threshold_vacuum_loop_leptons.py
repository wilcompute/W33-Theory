def b0(x, y, scale=1.):
    """Finite MSbar B0(0;x,y), positive mass squares; equal-mass limit."""
    x = np.asarray(x, float)
    out = np.empty_like(x)
    mask = abs(x-y) < 1e-8*np.maximum(x, y)
    out[mask] = -np.log(y/scale**2)
    out[~mask] = 1-(x[~mask]*np.log(x[~mask]/scale**2)-y*np.log(y/scale**2))/(x[~mask]-y)
    return out


