#!/usr/bin/env python3
"""Exact E8/W(E6) finite model shared by Passes 1132--1136.

Coordinates are doubled so every E8 root is integral with norm squared 8.
The chosen A2 triple is deterministic (lexicographically first), and W(E6)
is generated by six reflections in the 72 roots orthogonal to that A2 plane.
"""
from __future__ import annotations

from collections import Counter, deque
from functools import lru_cache
from itertools import combinations, product
import math
from typing import Iterable

import numpy as np


def e8_roots() -> tuple[tuple[int, ...], ...]:
    roots: list[tuple[int, ...]] = []
    for i, j in combinations(range(8), 2):
        for si in (-2, 2):
            for sj in (-2, 2):
                v = [0] * 8
                v[i], v[j] = si, sj
                roots.append(tuple(v))
    for signs in product((-1, 1), repeat=8):
        if sum(s == -1 for s in signs) % 2 == 0:
            roots.append(tuple(signs))
    assert len(roots) == len(set(roots)) == 240
    assert {sum(x * x for x in r) for r in roots} == {8}
    return tuple(roots)


def dot(a: Iterable[int], b: Iterable[int]) -> int:
    return sum(x * y for x, y in zip(a, b))


@lru_cache(maxsize=1)
def base_data() -> dict[str, object]:
    roots = e8_roots()
    index = {r: i for i, r in enumerate(roots)}
    chosen: tuple[int, int, int] | None = None
    for i, a in enumerate(roots):
        for j in range(i + 1, len(roots)):
            b = roots[j]
            if dot(a, b) != -4:
                continue
            c = tuple(-x - y for x, y in zip(a, b))
            if c in index:
                chosen = tuple(sorted((i, j, index[c])))
                break
        if chosen is not None:
            break
    assert chosen is not None
    a2_roots = [roots[i] for i in chosen]
    orthogonal = [
        i for i, r in enumerate(roots)
        if all(dot(r, a) == 0 for a in a2_roots)
    ]
    assert len(orthogonal) == 72

    def d(i: int, j: int) -> int:
        return dot(roots[i], roots[j])

    adjacent = {i: [j for j in orthogonal if d(i, j) == -4] for i in orthogonal}
    simple: tuple[int, ...] | None = None
    for center in orthogonal:
        for leaf, left, right in combinations(adjacent[center], 3):
            if any(d(x, y) != 0 for x, y in combinations((leaf, left, right), 2)):
                continue
            for left_end in adjacent[left]:
                if left_end == center or any(d(left_end, x) != 0 for x in (center, leaf, right)):
                    continue
                for right_end in adjacent[right]:
                    if right_end in (center, leaf, left, left_end):
                        continue
                    if any(d(right_end, x) != 0 for x in (center, leaf, left, left_end)):
                        continue
                    simple = (left_end, left, leaf, center, right, right_end)
                    break
                if simple is not None:
                    break
            if simple is not None:
                break
        if simple is not None:
            break
    assert simple is not None
    gram = [[d(i, j) for j in simple] for i in simple]
    assert sorted(sum(v == -4 for v in row) for row in gram) == [1, 1, 1, 2, 2, 3]
    return {
        "roots": roots,
        "root_index": index,
        "a2_triple": chosen,
        "e6_root_indices": tuple(orthogonal),
        "e6_simple_indices": simple,
        "e6_simple_gram": gram,
    }


def reflection_permutation(root_index: int) -> np.ndarray:
    data = base_data()
    roots = data["roots"]
    index = data["root_index"]
    r = np.asarray(roots[root_index], dtype=np.int16)
    out = np.empty(240, dtype=np.uint8)
    for i, v in enumerate(roots):
        vv = np.asarray(v, dtype=np.int16)
        coeff = int(vv.dot(r) // 4)
        image = tuple((vv - coeff * r).tolist())
        out[i] = index[image]
    return out


def compose(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """Composition a after b."""
    return a[b]


def inverse(p: np.ndarray) -> np.ndarray:
    q = np.empty_like(p)
    q[p] = np.arange(len(p), dtype=p.dtype)
    return q


@lru_cache(maxsize=1)
def e6_generators() -> tuple[np.ndarray, ...]:
    simple = base_data()["e6_simple_indices"]
    gens = tuple(reflection_permutation(i) for i in simple)
    identity = np.arange(240, dtype=np.uint8)
    assert all(np.array_equal(compose(g, g), identity) for g in gens)
    return gens


@lru_cache(maxsize=1)
def we6_group() -> tuple[np.ndarray, ...]:
    identity = np.arange(240, dtype=np.uint8)
    seen = {identity.tobytes()}
    elements = [identity]
    queue = deque([identity])
    for_current = e6_generators()
    while queue:
        x = queue.popleft()
        for g in for_current:
            y = compose(g, x)
            key = y.tobytes()
            if key not in seen:
                seen.add(key)
                elements.append(y)
                queue.append(y)
    assert len(elements) == 51840
    return tuple(elements)


@lru_cache(maxsize=1)
def a2_triples() -> tuple[tuple[int, int, int], ...]:
    roots = base_data()["roots"]
    index = base_data()["root_index"]
    triples: set[tuple[int, int, int]] = set()
    for i, a in enumerate(roots):
        for j in range(i + 1, len(roots)):
            b = roots[j]
            if dot(a, b) != -4:
                continue
            c = tuple(-x - y for x, y in zip(a, b))
            triples.add(tuple(sorted((i, j, index[c]))))
    assert len(triples) == 2240
    return tuple(sorted(triples))


@lru_cache(maxsize=1)
def a2_generator_actions() -> tuple[np.ndarray, ...]:
    triples = a2_triples()
    index = {t: i for i, t in enumerate(triples)}
    actions: list[np.ndarray] = []
    for g in e6_generators():
        action = np.empty(len(triples), dtype=np.int16)
        for i, triple in enumerate(triples):
            action[i] = index[tuple(sorted(int(g[x]) for x in triple))]
        actions.append(action)
    return tuple(actions)


def orbit_partition(actions: Iterable[np.ndarray], degree: int) -> list[list[int]]:
    unseen = set(range(degree))
    orbits: list[list[int]] = []
    actions = tuple(actions)
    while unseen:
        seed = min(unseen)
        orbit = {seed}
        queue = deque([seed])
        while queue:
            x = queue.popleft()
            for g in actions:
                y = int(g[x])
                if y not in orbit:
                    orbit.add(y)
                    queue.append(y)
        unseen -= orbit
        orbits.append(sorted(orbit))
    return sorted(orbits, key=lambda x: (len(x), x[0]))


@lru_cache(maxsize=1)
def a2_orbits() -> tuple[tuple[int, ...], ...]:
    result = orbit_partition(a2_generator_actions(), len(a2_triples()))
    assert [len(x) for x in result] == [1, 1, 27, 27, 27, 27, 27, 27, 240, 270, 270, 432, 432, 432]
    return tuple(tuple(x) for x in result)


@lru_cache(maxsize=1)
def cubic_supports() -> tuple[tuple[int, int, int], ...]:
    data = base_data()
    roots = data["roots"]
    a2 = [np.asarray(roots[i], dtype=int) for i in data["a2_triple"]]
    shells: dict[tuple[int, int, int], list[int]] = {}
    for i, root in enumerate(roots):
        pattern = tuple(dot(root, x) for x in a2)
        shells.setdefault(pattern, []).append(i)
    patterns27 = sorted(pattern for pattern, shell in shells.items() if len(shell) == 27)
    assert len(patterns27) == 6
    shell = shells[patterns27[-1]]
    sums: dict[tuple[int, ...], list[tuple[int, int, int]]] = {}
    for triple in combinations(shell, 3):
        total = tuple(sum(roots[i][k] for i in triple) for k in range(8))
        sums.setdefault(total, []).append(tuple(sorted(triple)))
    constant, supports = max(sums.items(), key=lambda kv: len(kv[1]))
    assert len(supports) == 45
    assert all(tuple(sum(roots[i][k] for i in t) for k in range(8)) == constant for t in supports)
    return tuple(sorted(supports))


@lru_cache(maxsize=1)
def cubic_generator_actions() -> tuple[np.ndarray, ...]:
    supports = cubic_supports()
    index = {t: i for i, t in enumerate(supports)}
    actions: list[np.ndarray] = []
    for g in e6_generators():
        action = np.empty(45, dtype=np.int8)
        for i, support in enumerate(supports):
            action[i] = index[tuple(sorted(int(g[x]) for x in support))]
        actions.append(action)
    return tuple(actions)


def permutation_order(p: np.ndarray) -> int:
    seen = np.zeros(len(p), dtype=bool)
    result = 1
    for i in range(len(p)):
        if seen[i]:
            continue
        j, length = i, 0
        while not seen[j]:
            seen[j] = True
            j = int(p[j])
            length += 1
        result = math.lcm(result, length)
    return result


def generated_subgroup(generators: Iterable[np.ndarray]) -> tuple[np.ndarray, ...]:
    generators = tuple(generators)
    if not generators:
        return (np.arange(240, dtype=np.uint8),)
    all_gens = generators + tuple(inverse(g) for g in generators)
    identity = np.arange(len(generators[0]), dtype=generators[0].dtype)
    seen = {identity.tobytes()}
    elements = [identity]
    queue = deque([identity])
    while queue:
        x = queue.popleft()
        for g in all_gens:
            y = compose(g, x)
            key = y.tobytes()
            if key not in seen:
                seen.add(key)
                elements.append(y)
                queue.append(y)
    return tuple(elements)


def greedy_generators(group: Iterable[np.ndarray]) -> tuple[np.ndarray, ...]:
    group = tuple(group)
    selected: list[np.ndarray] = []
    current = generated_subgroup(selected)
    current_keys = {x.tobytes() for x in current}
    for x in group:
        if x.tobytes() in current_keys:
            continue
        selected.append(x)
        current = generated_subgroup(selected)
        current_keys = {y.tobytes() for y in current}
        if len(current) == len(group):
            break
    assert len(current) == len(group)
    return tuple(selected)


def group_invariants(group: Iterable[np.ndarray]) -> dict[str, object]:
    group = tuple(group)
    center = [
        a for a in group
        if all(np.array_equal(compose(a, b), compose(b, a)) for b in group)
    ]
    inverses = {x.tobytes(): inverse(x) for x in group}
    commutators: list[np.ndarray] = []
    for a in group:
        ai = inverses[a.tobytes()]
        for b in group:
            bi = inverses[b.tobytes()]
            commutators.append(compose(ai, compose(bi, compose(a, b))))
    derived = generated_subgroup(commutators)
    return {
        "order": len(group),
        "center_order": len(center),
        "derived_order": len(derived),
        "abelianization_order": len(group) // len(derived),
        "element_order_distribution": dict(sorted(Counter(permutation_order(x) for x in group).items())),
    }
