import w33_e8_spectral_bridge as spectral  # noqa: E402


OUTPUT_PATH = ROOT / "PART_MCCCLXXXVII_AFFINE_TETRACODE_E8_GLUE_BRIDGE_results.json"
STANDARD_TETRACODE_GENERATORS = ((0, 1, 1, 1), (1, 0, 1, 2))


def _counter(values: Iterable[Any]) -> dict[str, int]:
    return {str(key): int(value) for key, value in sorted(Counter(values).items())}


def gf3_row_basis(rows: Iterable[tuple[int, ...]]) -> list[tuple[int, ...]]:
    matrix = [list(int(entry) % 3 for entry in row) for row in rows if any(int(entry) % 3 for entry in row)]
    if not matrix:
        return []

    row_count = len(matrix)
    col_count = len(matrix[0])
    rank = 0
    basis: list[tuple[int, ...]] = []

    for col in range(col_count):
        pivot = None
        for row in range(rank, row_count):
            if matrix[row][col] % 3:
                pivot = row
                break
        if pivot is None:
            continue

        matrix[rank], matrix[pivot] = matrix[pivot], matrix[rank]
        inverse = 1 if matrix[rank][col] == 1 else 2
        matrix[rank] = [(entry * inverse) % 3 for entry in matrix[rank]]

        for row in range(row_count):
            if row == rank or not matrix[row][col] % 3:
                continue
            factor = matrix[row][col]
            matrix[row] = [(matrix[row][idx] - factor * matrix[rank][idx]) % 3 for idx in range(col_count)]

        basis.append(tuple(matrix[rank]))
        rank += 1

    return basis


def span(generators: Iterable[tuple[int, ...]]) -> set[tuple[int, ...]]:
    gens = list(generators)
    if not gens:
        return {()}

    words: set[tuple[int, ...]] = set()
    for coeffs in product(range(3), repeat=len(gens)):
        word = [0] * len(gens[0])
        for coefficient, generator in zip(coeffs, gens):
            for idx, entry in enumerate(generator):
                word[idx] = (word[idx] + coefficient * entry) % 3
        words.add(tuple(word))
    return words


def dot_mod3(left: tuple[int, ...], right: tuple[int, ...]) -> int:
    return sum(a * b for a, b in zip(left, right)) % 3


def hamming_weight(word: tuple[int, ...]) -> int:
    return sum(1 for entry in word if entry % 3)


def standard_tetracode() -> set[tuple[int, ...]]:
    return span(STANDARD_TETRACODE_GENERATORS)


def nonneighbor_tetracode_words(point: int) -> dict[str, Any]:
    anchor_lines = sorted(spectral.point_lines[point])
    coordinate_labels: dict[int, dict[int, int]] = {}
    for line in anchor_lines:
        coordinate_labels[line] = {
            other_point: idx
            for idx, other_point in enumerate(sorted(q for q in spectral.lines[line] if q != point))
        }

    words: list[tuple[int, int, int, int]] = []
    witnesses: list[dict[str, Any]] = []
    for other_point in range(40):
        if other_point == point or spectral.adj[point][other_point]:
            continue

        word: list[int] = []
        common_neighbors: list[int] = []
        for line in anchor_lines:
            common = [q for q in spectral.lines[line] if q != point and spectral.adj[other_point][q]]
            if len(common) != 1:
                raise AssertionError((point, other_point, line, common))
            common_neighbors.append(common[0])
            word.append(coordinate_labels[line][common[0]])

        tuple_word = tuple(word)
        words.append(tuple_word)
        witnesses.append(
            {
                "nonneighbor": int(other_point),
                "word": list(map(int, tuple_word)),
                "common_neighbors_on_anchor_lines": list(map(int, common_neighbors)),
            }
        )

    unique_words = sorted(set(words))
    basis = gf3_row_basis(unique_words)
    code = span(basis)
    nonzero_weights = [hamming_weight(word) for word in code if any(word)]
    isotropic = all(dot_mod3(left, right) == 0 for left in code for right in code)
    multiplicities = Counter(words)

    return {
        "point": int(point),
        "point_vector": list(map(int, spectral.points[point])),
        "anchor_lines": list(map(int, anchor_lines)),
        "words_with_multiplicity": [list(map(int, word)) for word in words],
        "witnesses": witnesses,
        "unique_words": [list(map(int, word)) for word in unique_words],
        "multiplicity_profile": _counter(multiplicities.values()),
        "basis": [list(map(int, row)) for row in basis],
        "rank": len(basis),
        "is_linear": code == set(unique_words),
        "is_self_dual_tetracode": len(code) == 9
        and len(basis) == 2
        and isotropic
        and min(nonzero_weights) == 3
        and max(nonzero_weights) == 3,
        "weight_profile": _counter(hamming_weight(word) for word in code),
        "standard_tetracode_generators": [list(row) for row in STANDARD_TETRACODE_GENERATORS],
        "matches_standard_tetracode_exactly": code == standard_tetracode(),
    }


def affine_tetracode_e8_glue_packet() -> dict[str, Any]:
    representative = nonneighbor_tetracode_words(0)

    rank_profile: list[int] = []
    multiplicity_profiles: list[str] = []
    basis_profiles: list[tuple[tuple[int, ...], ...]] = []
    standard_matches: list[bool] = []
    tetracode_flags: list[bool] = []
    weight_profiles: list[str] = []

    for point in range(40):
        report = nonneighbor_tetracode_words(point)
        rank_profile.append(report["rank"])
        multiplicity_profiles.append(str(report["multiplicity_profile"]))
        basis_profiles.append(tuple(tuple(row) for row in report["basis"]))
        standard_matches.append(bool(report["matches_standard_tetracode_exactly"]))
        tetracode_flags.append(bool(report["is_self_dual_tetracode"]))
        weight_profiles.append(str(report["weight_profile"]))

    a2_four_roots = 4 * 6
    glue_roots = (9 - 1) * 27
    e8_root_total = a2_four_roots + glue_roots

    checks = {
        "representative_has_27_nonneighbor_words": len(representative["words_with_multiplicity"]) == 27,
        "representative_has_9_unique_words": len(representative["unique_words"]) == 9,
        "representative_each_codeword_has_multiplicity_3": representative["multiplicity_profile"] == {"3": 9},
        "representative_rank_is_2": representative["rank"] == 2,
        "representative_is_linear": representative["is_linear"] is True,
        "representative_is_self_dual_tetracode": representative["is_self_dual_tetracode"] is True,
        "representative_matches_standard_tetracode": representative["matches_standard_tetracode_exactly"] is True,
        "all_40_points_have_rank_2": _counter(rank_profile) == {"2": 40},
        "all_40_points_have_3fold_multiplicity_profile": _counter(multiplicity_profiles) == {"{'3': 9}": 40},
        "all_40_points_are_self_dual_tetracodes": all(tetracode_flags),
        "all_40_points_have_weight_profile_0_1_3_8": _counter(weight_profiles) == {"{'0': 1, '3': 8}": 40},
        "e8_root_count_from_a2_four_plus_tetracode_glue": e8_root_total == 240,
    }

    return {
        "part": "MCCCLXXXVII",
        "theorem": "Affine tetracode E8 glue bridge",
        "input_bridge": "MCCCLXXXVI E6 triality contrast rank-8 bridge",
        "representative_point": representative,
        "all_point_profiles": {
            "rank": _counter(rank_profile),
            "multiplicity_profile": _counter(multiplicity_profiles),
            "basis_profile": _counter(basis_profiles),
            "standard_tetracode_exact_match": _counter(standard_matches),
            "self_dual_tetracode": _counter(tetracode_flags),
            "weight_profile": _counter(weight_profiles),
        },
        "e8_glue_count": {
            "a2_four_root_subsystem": a2_four_roots,
            "nonzero_tetracode_words": 8,
            "phase_lifts_per_nonzero_word": 27,
            "tetracode_glue_roots": glue_roots,
            "total": e8_root_total,
            "identity": "240 = 4*6 + 8*27",
        },
        "claim_boundary": (
            "finite tetracode glue theorem for the W33 incidence map; it identifies "
            "the E8 Construction-A/Eisenstein glue pattern but does not by itself "
            "choose metric scale in the continuum"
        ),
        "reading": (
            "For each W33 anchor point, the 27 nonneighbors do not form an arbitrary "
            "3^3 cloud when read through the four lines through the anchor. They "
            "collapse to the ternary tetracode [4,2,3]_3, each codeword appearing "
            "three times. Combined with MCCCLXXXVI's A2^4 rank-8 contrast quotient, "
            "this recovers the standard E8 pattern: four A2 coordinate planes plus "
            "tetracode glue, with root count 24 + 8*27 = 240."
        ),
        "checks": checks,
        "n_verified": sum(1 for value in checks.values() if value),
    }


def main() -> None:
    packet = affine_tetracode_e8_glue_packet()
    with open(OUTPUT_PATH, "w", encoding="utf-8") as handle:
        json.dump(packet, handle, indent=2)

