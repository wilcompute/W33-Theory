"""Part MCCCLXXXVII: affine tetracode E8 glue bridge.

MCCCLXXXVI found the rank-8 adjacent/E6 quotient: line-wise ternary contrasts
of the 24 adjacent triplet sums give four scaled A2 blocks.  The external E8
lattice construction says the missing glue for A2^4 is the ternary tetracode,
the self-dual [4,2,3]_3 code generated by

    (0,1,1,1), (1,0,1,2).

This verifier shows that W33 supplies exactly that code internally.

Fix a W33 point p.  There are four lines through p.  For any nonneighbor x of
p, the GQ property gives exactly one common neighbor of p and x on each of the
four lines through p.  Label the three non-p points on each anchor line by
0,1,2.  Then x maps to a length-4 ternary word.

The 27 nonneighbors collapse to 9 unique words, each with multiplicity 3.  The
unique words form the ternary tetracode: rank 2, self-dual/isotropic, minimum
weight 3, and all 8 nonzero words have weight 3.

Together with MCCCLXXXVI, this gives the finite E8 glue pattern:

    A2^4 rank-8 contrast skeleton + tetracode glue = 24 + 8*27 = 240 roots.
"""

from __future__ import annotations

