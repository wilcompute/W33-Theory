from __future__ import annotations

import itertools
import json
import math


class TritVM:
    """The minimal machine: a ternary ALU with mod-3 add/sub/mul, a small trit register file and RAM."""

    def __init__(self, ram_trits=256):
        self.reg = [0] * 16
        self.ram = [0] * ram_trits
        self.ops = 0

    def ADD3(self, a, b):
        self.ops += 1
        return (a + b) % 3

    def SUB3(self, a, b):
        self.ops += 1
        return (a - b) % 3

    def MUL3(self, a, b):
        self.ops += 1
        return (a * b) % 3

    def forward(self, x, y):
        """The holonet forwarding test B(x,y) mod 3, in ONLY mod-3 ALU primitives. Adjacent iff 0."""
        t1 = self.MUL3(x[0], y[1])
        t2 = self.MUL3(x[1], y[0])
        t3 = self.MUL3(x[2], y[3])
        t4 = self.MUL3(x[3], y[2])
        s = self.SUB3(t1, t2)
        s = self.ADD3(s, t3)
        s = self.SUB3(s, t4)
        return s


