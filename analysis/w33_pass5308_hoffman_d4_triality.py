#!/usr/bin/env python3
"""Pass5308: the Hoffman-576 stabilizer contains canonical W(D4) and triality C3.

Starting from Pass5300's exact Hoffman cover stabilizer H of order576, define N
to be the subgroup generated by all 2-power-order elements of H.  This is
characteristic in H.  We prove

    |N|=192,
    N ~= (C2)^3 : S4 = W(D4),
    H/N ~= C3.

Moreover N has exactly three normal elementary-abelian subgroups V8 arising as
normal closures of three involution classes, and an order-3 element outside N
cycles those three V8s.  This is the finite-group triality fingerprint.
"""
from __future__ import annotations
import json
from collections import Counter
from pathlib import Path
from sympy.combinatorics import PermutationGroup
from analysis.w33_pass5300_hoffman576_latin_group_bridge import q5_hoffman

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'data/PART_W33_PASS5308_HOFFMAN_D4_TRIALITY.json'

def hist(G): return {str(k):v for k,v in sorted(Counter(int(g.order()) for g in G.generate_schreier_sims()).items())}
def key(g): return tuple(g.array_form)

def main():
    H,H13,_,_=q5_hoffman(); assert H.order()==576
    els=list(H.generate_schreier_sims())
    N=PermutationGroup([g for g in els if int(g.order()) in (1,2,4)])
    assert N.order()==192 and N.center().order()==2 and N.derived_subgroup().order()==96
    assert N.abelian_invariants()==[2]
    Nkeys={key(g) for g in N.generate_schreier_sims()}
    assert all(key((~h)*g*h) in Nkeys for h in H.generators for g in N.generators)

    # Three normal V8s, each C2^3.
    Vs=[]
    for cl in N.conjugacy_classes():
        g=next(iter(cl))
        if int(g.order())!=2: continue
        V=N.normal_closure([g])
        if V.order()==8 and V.center().order()==8 and V.abelian_invariants()==[2,2,2]:
            K=frozenset(key(x) for x in V.generate_schreier_sims())
            if all(K!=K0 for K0,_ in Vs): Vs.append((K,V))
    assert len(Vs)==3

    # Find an S4 complement to one normal V8.
    V=Vs[0][1];Vkeys={key(x) for x in V.generate_schreier_sims()};comp=None
    ord3=[g for g in N.generate_schreier_sims() if int(g.order())==3]
    ord4=[g for g in N.generate_schreier_sims() if int(g.order())==4]
    want={1:1,2:9,3:8,4:6}
    for a in ord4:
        for b in ord3:
            K=PermutationGroup([a,b])
            if K.order()!=24: continue
            if Counter(int(x.order()) for x in K.generate_schreier_sims())!=Counter(want): continue
            if sum(key(x) in Vkeys for x in K.generate_schreier_sims())==1:
                comp=K;break
        if comp:break
    assert comp is not None and comp.center().order()==1 and comp.derived_subgroup().order()==12
    assert PermutationGroup(list(V.generators)+list(comp.generators)).order()==192

    # Triality element outside N.
    t=None
    for x in els:
        if int(x.order())==3 and key(x) not in Nkeys and PermutationGroup(list(N.generators)+[x]).order()==576:
            t=x;break
    assert t is not None
    perm=[]
    for K,V0 in Vs:
        img=frozenset(key((~t)*x*t) for x in V0.generate_schreier_sims())
        perm.append(next(i for i,(K2,_) in enumerate(Vs) if img==K2))
    assert sorted(perm)==[0,1,2] and all(perm[i]!=i for i in range(3))
    z=next(x for x in N.center().generate_schreier_sims() if int(x.order())==2)
    assert (~t)*z*t==z

    out={
      'pass':5308,
      'status':'THEOREM_HOFFMAN576_IS_WD4_EXTENDED_BY_TRIALITY_C3',
      'H_order':576,
      'canonical_subgroup_definition':'N is generated by all 2-power-order elements of H',
      'N_order':192,
      'N_structure':'(C2)^3 : S4 = W(D4)',
      'N_center_order':2,
      'N_derived_order':96,
      'N_element_orders':hist(N),
      'normal_V8_count':3,
      'V8_structure':'(C2)^3',
      'S4_complement_order':24,
      'quotient_H_over_N':'C3',
      'triality_cycle_on_three_V8s':perm,
      'central_involution_fixed_by_triality':True,
      'conclusion':'H ~= W(D4) : C3, with the outer C3 cyclically permuting the three normal V8 triality sectors.',
      'boundary':'This identifies the abstract finite-group triality structure. It does not identify N with the orientation-preserving tesseract group; Pass5310 tests that separately.'}
    OUT.write_text(json.dumps(out,indent=2)+'\n');print(json.dumps(out,indent=2))
if __name__=='__main__': main()
