#!/usr/bin/env python3
"""Exact W33 oriented-288 / binary-tetrahedral Clifford interior bridge.

The order-576 W33 minimum-vector stabilizer H has a unique index-two subgroup
H+ obtained by killing the C2 quotient of its S3 factor.  Geometrically this is
the oriented minimum-vector stabilizer; algebraically it is generated by H'
and the order-three elements of H.

Independently, the determinant-one single-qubit Clifford commutator C1' is the
binary tetrahedral group 2T ~= SL(2,3).  The local two-qubit group

    C1' tensor C1' ~= (2T x 2T) / diag(C2)

has order 288.  Its 2-core is the central product Q8 * Q8 = 2_+^{1+4}, and the
quotient by that 2-core is C3 x C3.

This certificate reconstructs both groups independently, builds an explicit
isomorphism through their characteristic extraspecial kernels, and checks all
288^2 products.  It then records the extension-class divergence above the
common interior: W33 adds an involutory factor exchange, whereas the standard
complex Clifford non-entangling lift adds a swap whose square is scalar phase.
"""
