"""Passes 4755 and 4759 — canonical non-coordinate 24D residue lattice.

4755: use the primitive rank-24 orbital projector from Pass 4753. Scaling the
projected 270 coordinate orbit to squared norm 24 gives an integral rank-24
Gram matrix. The lattice generated by all 270 vectors has determinant
2^10*3^10*5^23. Because the Gram contains an entry 1, every scalar rescaling
that remains integral is integral; its determinant therefore retains an odd
5-adic exponent. Hence this *canonical projected lattice* cannot be a full-rank
sublattice of an integral unimodular 24-lattice such as Leech. This is a lattice
no-go, not a representation no-go.

4759 (outside box): sum the six residue vectors in each Pass-4758 cube. The 135
sums collapse three-at-a-time to 45 distinct vectors. After division of the
Gram by 9 they have norm 16 and pair inner products -4 or 1. Their Gram is
15 I - 5 A + J for an SRG(45,12,3,3), hence has rank 24 and is 30 times the
primitive (-3)-eigenspace projector of the GQ(4,2) quotient graph.
"""
