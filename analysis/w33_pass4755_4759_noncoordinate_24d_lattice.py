ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'data/PART_W33_PASS4755_4759_NONCOORDINATE_24D_LATTICE.json'

def mask(S):return sum(1<<i for i in S)

def main():
    pts,pidx,lines,A,apartments,_,_=geometry();A=np.asarray(A,dtype=np.uint8)
    residues=[]
    for C in itertools.combinations(range(40),4):
        if not np.any(np.sum(A[:,C],axis=1)&1):residues.append(tuple(C))
    rm=[mask(r) for r in residues];ridx={r:i for i,r in enumerate(residues)}
    _,G,_=build_groups(pts,pidx,lines)
    def ar(i,g):return ridx[tuple(sorted(g[x] for x in residues[i]))]
    H=[g for g in G if ar(0,g)==0];unseen=set(range(270));orbs=[]
    while unseen:
        x=min(unseen);O=sorted({ar(x,h) for h in H});orbs.append(O);unseen-=set(O)
    assert [len(O) for O in orbs]==[1,12,16,48,16,6,24,96,12,12,24,3]
    oi={x:k for k,O in enumerate(orbs) for x in O};trans={}
    for g in G:
        x=ar(0,g)
        if x not in trans:trans[x]=g
    def inv(p):
        q=[0]*len(p)
        for i,j in enumerate(p):q[j]=i
        return tuple(q)
    def rel(a,b):return oi[ar(b,inv(trans[a]))]
    OM=[]
    for k in range(12):
        M=np.zeros((270,270),dtype=np.int64)
        for i in range(270):
            for j in range(270):
                if rel(i,j)==k:M[i,j]=1
        OM.append(M)

    E=[Fraction(4,45),Fraction(2,135),Fraction(1,30),Fraction(2,135),Fraction(-1,45),Fraction(-1,270),Fraction(2,135),Fraction(-1,45),Fraction(2,135),Fraction(2,135),Fraction(-1,45),Fraction(-8,135)]
    G24=np.zeros((270,270),dtype=np.int64)
    for k,c in enumerate(E):
        z=270*c;assert z.denominator==1;G24+=int(z)*OM[k]
    assert set(np.diag(G24))=={24}
    assert set(G24.flatten())=={24,9,4,-1,-6,-16}
    assert math.gcd(*[abs(int(x)) for x in G24.flatten() if x])==1
    assert np.linalg.matrix_rank(G24.astype(float))==24

    # Exact determinant of the lattice generated by all 270 Gram generators.
    inds=[];rk=0
    for j in range(270):
        r=np.linalg.matrix_rank(G24[:,inds+[j]].astype(float),tol=1e-7)
        if r>rk:inds.append(j);rk=r
        if rk==24:break
    B=sp.Matrix(G24[np.ix_(inds,inds)].tolist());detB=abs(int(B.det()))
    X=sp.Matrix(G24[np.ix_(inds,range(270))].tolist());C=B.inv()*X
    D=int(sp.ilcm(*[sp.denom(x) for x in C]));assert D==3
    N=(D*C).applyfunc(int);S=smith_normal_form(N,domain=ZZ)
    invs=[abs(int(S[i,i])) for i in range(24)];idx=D**24//math.prod(invs);assert idx==3
    detL=detB//(idx*idx);fac=sp.factorint(detL)
    assert fac=={2:10,3:10,5:23}
    assert math.isqrt(detL)**2!=detL

    # Dependency cubes: 1080 cold triangles split by XOR, then edge incidence.
    cold=[set() for _ in range(270)]
    for i,j in itertools.combinations(range(270),2):
        if (rm[i]&rm[j]).bit_count()==2:cold[i].add(j);cold[j].add(i)
    tris=[]
    for a in range(270):
        for b in (x for x in cold[a] if x>a):
            for c in cold[a]&cold[b]:
                if c>b:tris.append((a,b,c))
    cir=[t for t in tris if rm[t[0]]^rm[t[1]]^rm[t[2]]==0];non=[t for t in tris if rm[t[0]]^rm[t[1]]^rm[t[2]]]
    ec={tuple(sorted(e)):i for i,t in enumerate(cir) for e in itertools.combinations(t,2)}
    en={tuple(sorted(e)):i for i,t in enumerate(non) for e in itertools.combinations(t,2)}
    badj=[set() for _ in range(1080)]
    for e in ec:
        a=ec[e];b=540+en[e];badj[a].add(b);badj[b].add(a)
    seen=set();cubeR=[]
    for s in range(1080):
        if s in seen:continue
        Q=[s];seen.add(s);C0=[]
        while Q:
            u=Q.pop();C0.append(u)
            for v in badj[u]:
                if v not in seen:seen.add(v);Q.append(v)
        assert len(C0)==8
        R=set()
        for u in C0:R.update(cir[u] if u<540 else non[u-540])
        assert len(R)==6;cubeR.append(tuple(sorted(R)))
    assert len(cubeR)==135
    def ip(S,T):return sum(int(G24[i,j]) for i in S for j in T)
    assert {ip(R,R) for R in cubeR}=={144}

    # Equality of cube-sum vectors is detected by inner product = norm = 144.
    parent=list(range(135))
    def find(x):
        while parent[x]!=x:parent[x]=parent[parent[x]];x=parent[x]
        return x
    def union(a,b):
        a,b=find(a),find(b)
        if a!=b:parent[b]=a
    for i,j in itertools.combinations(range(135),2):
        if ip(cubeR[i],cubeR[j])==144:union(i,j)
    groups=defaultdict(list)
    for i in range(135):groups[find(i)].append(i)
    assert len(groups)==45 and Counter(map(len,groups.values()))==Counter({3:45})
    reps=[v[0] for v in groups.values()]
    H45=np.array([[ip(cubeR[i],cubeR[j])//9 for j in reps] for i in reps],dtype=int)
    assert set(np.diag(H45))=={16}
    assert Counter(H45[i,j] for i in range(45) for j in range(i+1,45))==Counter({1:720,-4:270})
    Aq=(H45-np.eye(45,dtype=int)*15-np.ones((45,45),dtype=int))//-5
    assert np.array_equal(H45,15*np.eye(45,dtype=int)-5*Aq+np.ones((45,45),dtype=int))
    assert set(Aq.sum(1))=={12} and np.all(np.diag(Aq)==0) and np.array_equal(Aq,Aq.T)
    assert np.array_equal(Aq@Aq,9*np.eye(45,dtype=int)+3*np.ones((45,45),dtype=int))
    ev=np.linalg.eigvalsh(H45.astype(float));assert sum(abs(x)>1e-7 for x in ev)==24 and all(abs(x-30)<1e-6 for x in ev if abs(x)>1e-7)

    out={'passes':[4755,4759],
      '4755_canonical_24d_lattice':{'vectors':270,'rank':24,'norm':24,'pair_inner_products':[9,4,-1,-6,-16],
        'lattice_determinant':detL,'factorization':'2^10 * 3^10 * 5^23','generator_coordinate_saturation_index':idx,
        'unimodular_embedding_no_go':'For any scalar c making this Gram integral, c is an integer because an inner product 1 occurs. det(cL)=c^24 det(L) retains odd 5-adic valuation, so it cannot be the determinant-square of a full-rank sublattice of an integral unimodular lattice.',
        'representation_boundary':'This blocks the canonical projected residue lattice, not the abstract 24D PSp representation or other commensurable invariant lattices.'},
      '4759_cube_sum_45_frame':{'cube_sums':135,'equal_vector_packets':45,'packet_size':3,'normalized_norm':16,'normalized_inner_products':[-4,1],
        'Gram_formula':'15 I - 5 A + J','A_parameters':'SRG(45,12,3,3)','Gram_rank':24,'nonzero_Gram_eigenvalue':30,
        'interpretation':'the cube-sum vectors collapse through the selected135 three-packets to the canonical 24D spherical embedding of the 45-point GQ quotient'},
      'boundary':'The ATLAS-compatible 24D representation bridge is distinct from a Leech-lattice embedding; the latter requires an explicit invariant lattice isometry and the most canonical residue lattice fails the unimodular determinant test.'}
    OUT.write_text(json.dumps(out,indent=2,sort_keys=True)+'\n');print(json.dumps(out,indent=2,sort_keys=True));return 0
