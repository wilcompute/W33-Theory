"""Pass 12643: are mirror partners (same covered points) in the same Sp-orbit?  Orbits of the minimal maximal partial spreads under the
symplectic group generated by transvections t_u(x) = x + w(x,u) u (they generate Sp(2n,p)).  Two qutrits (control): pentads must split
into 2 orbits of 216 with partners in opposite orbits (Pass 12636/12641: only antiunitaries swap them).  Three qubits: orbit structure of
the 24,192 size-5 sets and whether partners share an orbit (then a unitary Clifford swaps them; in char 2, -1 = 1 so complex conjugation
fixes every line and cannot).
usage: py -3 analysis/w33_mirror_orbits.py"""
import json, os, contextlib, io, itertools
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
cs = {"__name__": "x", "__file__": os.path.join(HERE, "w33_strong_umub_census.py")}
_src = open(os.path.join(HERE, "w33_strong_umub_census.py"), encoding="utf-8").read()
with contextlib.redirect_stdout(io.StringIO()):
    exec(_src[: _src.index("\nres = {}")], cs)
def run(p, n, size):
    pts, lag, w = cs["geometry"](p, n); mps, _ = cs["maximal_partial_spreads"](lag)
    idx = {q: i for i, q in enumerate(pts)}
    def norm(v):
        c = next(x for x in v if x); inv = pow(c, -1, p); return tuple((x * inv) % p for x in v)
    gens = []
    for u in pts:
        perm = [idx[norm(tuple((x[k] + w(x, u) * u[k]) % p for k in range(2 * n)))] for x in pts]
        gens.append(perm)
    lagidx = {frozenset(L): i for i, L in enumerate(lag)}
    lperm = [[lagidx[frozenset(g[i] for i in L)] for L in lag] for g in gens]
    sets = {frozenset(S) for S in mps if len(S) == size}
    orbit_of = {}; orbits = []
    for S in sets:
        if S in orbit_of: continue
        k = len(orbits); orbit_of[S] = k; stack = [S]; cnt = 1
        while stack:
            T = stack.pop()
            for g in lperm:
                U = frozenset(g[L] for L in T)
                if U not in orbit_of: orbit_of[U] = k; stack.append(U); cnt += 1
        orbits.append(cnt)
    fib = {}
    for S in sets: fib.setdefault(frozenset().union(*[lag[L] for L in S]), []).append(S)
    same = sum(1 for v in fib.values() if len(v) == 2 and orbit_of[v[0]] == orbit_of[v[1]])
    return dict(orbit_sizes=sorted(orbits), fibres=len(fib), partners_in_same_orbit=same)
res = dict(two_qutrits=run(3, 2, 5)); print(res, flush=True)
res["three_qubits"] = run(2, 3, 5); print(res["three_qubits"], flush=True)
json.dump(res, open(os.path.join(ROOT, "data", "w33_mirror_orbits.json"), "w"), indent=1)
