#!/usr/bin/env python3
"""Exact weight-two simple-current/Pauli interaction algebra of Niemeier A8^3.

The A8^3 glue code C <= (Z9)^3 is generated by permutations of (1,1,4).
For SU(9)_1 the simple-current sector k has ground weight k(9-k)/18 and
finite ground representation Lambda^k(9).  This file enumerates all 27 sectors,
the complete weight-two contribution, fusion targets, and the induced action of
the two-qutrit Pauli group on every factor.

If P(v)P(w)=omega^Omega(v,w)P(w)P(v) on the fundamental 9, then on Lambda^k(9)
the commutator scalar is omega^(k Omega).  The A8^3 glue obeys
k1=k2=k3 mod 3, so each sector has a synchronized central character r.  For
r=1,2 the three-factor operator algebra therefore carries the nondegenerate
six-qutrit form r*(Omega1+Omega2+Omega3); for r=0 its Pauli commutator scalar
is trivial.  No diagonal equality v1=v2=v3 is imposed.
"""
from __future__ import annotations
import itertools, json, math
from collections import Counter
from fractions import Fraction
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'data'/'w33_a8_cubed_weight2_pauli_interactions.json'
GEN=((1,1,4),(1,4,1),(4,1,1))

def glue_code():
    C=set()
    for a,b,c in itertools.product(range(9),repeat=3):
        C.add(tuple((a*GEN[0][i]+b*GEN[1][i]+c*GEN[2][i])%9 for i in range(3)))
    return sorted(C)
def h(k): k%=9; return Fraction(k*(9-k),18)
def dim(k): return math.comb(9,k%9) if k%9 else 1

def spreads_W33_count():
    # Exact-cover count for the 40 totally isotropic lines of W(3,3).
    V=[v for v in itertools.product(range(3),repeat=4) if any(v)]
    def can(v):
        i=next(i for i,x in enumerate(v) if x); q=pow(v[i],-1,3)
        return tuple(q*x%3 for x in v)
    P=sorted({can(v) for v in V})
    def om(a,b): return (a[0]*b[1]-a[1]*b[0]+a[2]*b[3]-a[3]*b[2])%3
    lines=set()
    for a,b in itertools.combinations(P,2):
        if om(a,b): continue
        L=frozenset(can(tuple((x*a[j]+y*b[j])%3 for j in range(4)))
                    for x in range(3) for y in range(3) if x or y)
        if len(L)==4: lines.add(L)
    L=list(lines); by={p:[] for p in P}
    for i,l in enumerate(L):
        for p in l: by[p].append(i)
    n=0
    def rec(covered):
        nonlocal n
        if len(covered)==40: n+=1; return
        p=next(p for p in P if p not in covered)
        for i in by[p]:
            if covered.isdisjoint(L[i]): rec(covered|L[i])
    rec(set()); return len(lines),n

def main(write=True):
    C=glue_code(); assert len(C)==27
    sec=[]
    for w in C:
        hw=sum((h(k) for k in w),Fraction(0)); ds=[dim(k) for k in w]
        assert len(set(k%3 for k in w))==1
        sec.append({'word':list(w),'weight':str(hw),'dims':ds,'ground_dimension':math.prod(ds),
                    'central_character_mod3':w[0]%3})
    w2=[x for x in sec if x['weight']=='2']; assert len(w2)==18
    dimc=Counter(x['ground_dimension'] for x in w2)
    rc=Counter(x['central_character_mod3'] for x in w2)
    assert dimc==Counter({7056:6,10206:6,11664:6}) and rc==Counter({0:6,1:6,2:6})
    glue_ground=sum(x['ground_dimension'] for x in w2); assert glue_ground==173556

    # Vacuum/root-lattice weight two: 24 alpha_-2 + Sym^2(24) + one oscillator
    # on each of 216 roots + norm-four lattice vectors.  A8 has 756 norm-4
    # vectors (two +1 and two -1 among nine coordinates); cross-factor root pairs
    # contribute 3*72^2.
    norm4_A8=math.comb(9,2)*math.comb(7,2); assert norm4_A8==756
    norm4_A8cubed=3*norm4_A8+3*72*72
    vacuum_w2=24+24*25//2+216*24+norm4_A8cubed
    assert vacuum_w2==23328 and vacuum_w2+glue_ground==196884

    w2words=[tuple(x['word']) for x in w2]; fus=Counter()
    for a in w2words:
      for b in w2words:
        c=tuple((a[i]+b[i])%9 for i in range(3)); fus[str(sum((h(k) for k in c),Fraction(0)))]+=1
    assert fus==Counter({'0':18,'2':216,'3':90})
    nlines,nspreads=spreads_W33_count(); assert (nlines,nspreads)==(40,36)

    out={
      'schema':'w33.a8_cubed_weight2_pauli_interactions.v1','status':'PASS',
      'headline':'The A8^3 extension has 18 weight-two glue sectors, six each with synchronized Pauli central character r=0,1,2. Their ground dimensions are six each of 7056, 10206 and 11664, totaling 173556; adding the 23328 vacuum-sector weight-two states gives 196884. On r=1,2 sectors the induced three-factor Pauli commutator is the full six-qutrit W(11,3) form r*(Omega1+Omega2+Omega3), while r=0 sectors have trivial Pauli commutator scalar.',
      'glue':{'order':27,'weight_two_sectors':18,'central_character_census':{'0':6,'1':6,'2':6},
              'ground_dimension_census':{'7056':6,'10206':6,'11664':6},'weight_two_glue_ground_states':glue_ground},
      'vacuum_weight_two':{'alpha_minus_2':24,'symmetric_alpha_minus_1_squared':300,'root_times_oscillator':5184,
                           'A8_norm4_per_factor':norm4_A8,'A8cubed_norm4':norm4_A8cubed,'total':vacuum_w2},
      'total_weight_two_dimension':196884,
      'ordered_weight2_fusion_target_weight_census':dict(fus),
      'inter_register_operator':'O_c(v1,v2,v3)=Lambda^{k1}P(v1) tensor Lambda^{k2}P(v2) tensor Lambda^{k3}P(v3)',
      'commutator':'O_c(v) O_c(w) = omega^{r*(Omega(v1,w1)+Omega(v2,w2)+Omega(v3,w3))} O_c(w) O_c(v), r=ki mod 3',
      'degree_geometry':{'r_1_or_2':'nondegenerate F3^12 six-qutrit phase space W(11,3)','r_0':'trivial commutator scalar'},
      'selector_test':{'factor_W33_cartans':40,'factor_W33_spreads':nspreads,
        'preserved_symmetry':'Sp(4,3)^3 semidirect S3',
        'result':'No individual factor Cartan, spread, or heterotic Wilson fingerprint is selected by weight-two glue/central-character data alone; Sp(4,3) is transitive on the factor geometries and the glue depends on center charge, not Pauli degree.'},
      'sectors':sec,
      'checks':{'27_glue_sectors':True,'18_weight_two':True,'six_each_central_character':True,
                'weight_two_196884':True,'fusion_18_216_90':True,'W33_has_36_spreads':True}
    }
    if write: OUT.write_text(json.dumps(out,indent=2)+'\n')
    print(json.dumps({k:v for k,v in out.items() if k!='sectors'},indent=2)); return out
if __name__=='__main__': main(True)
