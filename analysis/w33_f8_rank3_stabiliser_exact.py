"""Pass 12671: the F_8 regulus minimum (nine MUBs of C^64) is attained on the joint eigenspace of a rank-3 Pauli group T, where
it is rigid; high-precision refinement there and exact identification of every squared Pauli expectation in Q(cos 2 pi/9).
Conventions (CZ model of Pass 12659, index x = 8a + b as six bits): (P(u,v) psi)[x] = (-1)^{v.(x^u)} psi[x^u].
T is generated by H1 = -i P(12,53), H2 = P(53,33), H3 = P(1,6) (all Hermitian, commuting, uncovered by the nine bases);
the minimiser is a +1 eigenvector of all three (found by w33_f8_order9_reduction.py-style restricted searches, Pass 12671 note).
Newton's method in mpmath (dps 50) on the 8-dim eigenspace (16 real parameters, Hessian by central differences, pseudo-inverse),
then pslq for every distinct value |<P>|^2 against [1, g, g^2], g = 2 cos(2 pi/9).
usage: py -3 analysis/w33_f8_rank3_stabiliser_exact.py"""
import collections, json, math, os, time
import numpy as np
import mpmath as mp
from scipy.optimize import minimize
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
src = open(os.path.join(HERE, "w33_regulus_constants_q16_q32.py"), encoding="utf-8").read()
gl = {"__name__": "x", "__file__": os.path.join(HERE, "w33_regulus_constants_q16_q32.py")}
exec(src[: src.index("rng = np.random")], gl)
q, mul, trace = gl["field"](3); _, fg = gl["model"](3)
pc = lambda n: bin(n).count("1") & 1
Xi = [[1 - 2 * trace(mul(a, b)) for b in range(8)] for a in range(8)]
Phi = [[[1 - 2 * trace(mul(t, mul(a, b))) for b in range(8)] for a in range(8)] for t in range(8)]
C8 = (47 - 32 * math.cos(2 * math.pi / 9)) / 9


def pauli(u, v):
    M = np.zeros((64, 64), complex)
    for x in range(64): M[x, x ^ u] = (-1) ** pc(v & (x ^ u))
    return M


H = [-1j * pauli(12, 53), pauli(53, 33), pauli(1, 6)]
for X in H: assert np.allclose(X, X.conj().T) and np.allclose(X @ X, np.eye(64))
for X in H:
    for Y in H: assert np.allclose(X @ Y, Y @ X)
Proj = np.eye(64, dtype=complex)
for X in H: Proj = Proj @ (np.eye(64) + X) / 2
# exact basis: projector entries lie in {0, +-1/8, +-i/8}; pick independent columns and orthonormalise in mpmath
cols = []; R = np.zeros((64, 0))
for j in range(64):
    c = Proj[:, j]
    if np.linalg.matrix_rank(np.column_stack([R, c]) if R.size else c[:, None], tol=1e-9) > len(cols):
        cols.append(j); R = Proj[:, cols]
    if len(cols) == 8: break
assert len(cols) == 8
mp.mp.dps = 50
exact = lambda z: mp.mpc(mp.mpf(int(round(z.real * 8))) / 8, mp.mpf(int(round(z.imag * 8))) / 8)
assert np.allclose(np.round(Proj * 8), Proj * 8)
Bm = [[exact(Proj[i, j]) for j in cols] for i in range(64)]
Q = []  # Gram-Schmidt
for j in range(8):
    v = [Bm[i][j] for i in range(64)]
    for w in Q:
        ip = mp.fsum(mp.conj(w[i]) * v[i] for i in range(64)); v = [v[i] - ip * w[i] for i in range(64)]
    nr = mp.sqrt(mp.fsum(abs(z) ** 2 for z in v)); Q.append([z / nr for z in v])
Bnum = np.array([[complex(Q[j][i]) for j in range(8)] for i in range(64)])


# double-precision start inside the eigenspace
def f8(w):
    t = w[:8] + 1j * w[8:]; A = Bnum @ t
    val, gr = fg(np.concatenate([A.real, A.imag])); G = Bnum.conj().T @ (gr[:64] + 1j * gr[64:])
    return val, np.concatenate([G.real, G.imag])


rng = np.random.default_rng(71)
runs = [minimize(f8, rng.standard_normal(16), jac=True, method="L-BFGS-B", options=dict(maxiter=50000, gtol=1e-14, ftol=1e-18)) for _ in range(20)]
best = min(runs, key=lambda r: r.fun); hits = sum(abs(r.fun * 64 - C8) < 1e-8 for r in runs)
print("double precision: best c", best.fun * 64, "hits", hits, "/20", flush=True)


def transform(A, t):
    Bq = [[A[a][b] * Phi[t][a][b] for b in range(8)] for a in range(8)]
    C = [[mp.fsum(Xi[k][a] * Bq[a][b] for a in range(8)) for b in range(8)] for k in range(8)]
    return [[mp.fsum(C[k][b] * Xi[b][l] for b in range(8)) / 8 for l in range(8)] for k in range(8)]


def back(W, t):
    C = [[mp.fsum(Xi[a][k] * W[k][l] for k in range(8)) for l in range(8)] for a in range(8)]
    D = [[mp.fsum(C[a][l] * Xi[l][b] for l in range(8)) / 8 for b in range(8)] for a in range(8)]
    return [[D[a][b] * Phi[t][a][b] for b in range(8)] for a in range(8)]


def state(x):
    t = [mp.mpc(x[2 * j], x[2 * j + 1]) for j in range(8)]
    A = [mp.fsum(Q[j][i] * t[j] for j in range(8)) for i in range(64)]
    nr = mp.sqrt(mp.fsum(abs(z) ** 2 for z in A)); return [z / nr for z in A], nr


def F_grad(x):
    A, nr = state(x); A2 = [[A[8 * a + b] for b in range(8)] for a in range(8)]
    f = mp.fsum(abs(z) ** 4 for z in A); G = [[2 * abs(A2[a][b]) ** 2 * A2[a][b] for b in range(8)] for a in range(8)]
    for t in range(8):
        K = transform(A2, t); f += mp.fsum(abs(K[k][l]) ** 4 for k in range(8) for l in range(8))
        Bk = back([[2 * abs(K[k][l]) ** 2 * K[k][l] for l in range(8)] for k in range(8)], t)
        for a in range(8):
            for b in range(8): G[a][b] += Bk[a][b]
    Gf = [G[i // 8][i % 8] for i in range(64)]
    ip = mp.fsum(mp.conj(u) * v for u, v in zip(A, Gf)); Gf = [v - ip * u for u, v in zip(A, Gf)]
    Gt = [mp.fsum(mp.conj(Q[j][i]) * Gf[i] for i in range(64)) for j in range(8)]
    gr = []
    for z in Gt: gr += [2 * mp.re(z) / nr, 2 * mp.im(z) / nr]
    return f - mp.mpf(9) / 64, gr


t0 = Bnum.conj().T @ (Bnum @ (best.x[:8] + 1j * best.x[8:]))
x = []
for z in t0: x += [mp.mpf(z.real), mp.mpf(z.imag)]
hist = []
for it in range(7):
    f, gr = F_grad(x); gn = mp.sqrt(mp.fsum(v * v for v in gr)); hist.append((it, mp.nstr(64 * f, 40), mp.nstr(gn, 4)))
    print(it, mp.nstr(64 * f, 45), "grad", mp.nstr(gn, 4), flush=True)
    if gn < mp.mpf(10) ** -40: break
    h = mp.mpf(10) ** -22; Hm = mp.matrix(16, 16)
    for i in range(16):
        xp = list(x); xm = list(x); xp[i] += h; xm[i] -= h
        gp = F_grad(xp)[1]; gm = F_grad(xm)[1]
        for j in range(16): Hm[j, i] = (gp[j] - gm[j]) / (2 * h)
    E, V = mp.eigsy((Hm + Hm.T) / 2); tol = mp.mpf(10) ** -10 * max(abs(e) for e in E)
    step = [mp.mpf(0)] * 16
    for k in range(16):
        if abs(E[k]) > tol:
            co = mp.fsum(V[j, k] * gr[j] for j in range(16)) / E[k]
            for j in range(16): step[j] += co * V[j, k]
    x = [a - b for a, b in zip(x, step)]
null_dim = sum(1 for e in E if abs(e) <= tol)
c8 = 64 * f
print("c8 (rank-3 eigenspace) =", mp.nstr(c8, 45), " closed form diff", mp.nstr(c8 - (47 - 32 * mp.cos(2 * mp.pi / 9)) / 9, 5), "hessian null dim", null_dim)
A, _ = state(x)
gam = 2 * mp.cos(2 * mp.pi / 9)
vals = {}
for u in range(64):
    for v in range(64):
        e = mp.fsum(mp.conj(A[y]) * (-1) ** pc(v & (y ^ u)) * A[y ^ u] for y in range(64))
        vals[(u, v)] = abs(e) ** 2
levels = []
for key, val in vals.items():
    if val < mp.mpf(10) ** -30: continue
    for L in levels:
        if abs(L["value"] - val) < mp.mpf(10) ** -30: L["count"] += 1; break
    else: levels.append(dict(value=val, count=1))
out_levels = []
for L in sorted(levels, key=lambda L: L["value"]):
    rel = mp.pslq([L["value"], 1, gam, gam * gam], maxcoeff=10 ** 6, maxsteps=10 ** 6)
    num = None if rel is None else [-rel[1] / rel[0], -rel[2] / rel[0], -rel[3] / rel[0]]
    out_levels.append(dict(value=mp.nstr(L["value"], 40), count=L["count"], relation=rel,
                           in_Q_gamma=None if rel is None else [str(mp.mpf(n)) for n in num]))
    print(mp.nstr(L["value"], 25), L["count"], rel, flush=True)
res = dict(generators=["-i P(12,53)", "P(53,33)", "P(1,6)"], double_hits=int(hits), c8=mp.nstr(c8, 45), newton=hist,
           hessian_null_dim=null_dim, n_nonzero=sum(L["count"] for L in levels), levels=out_levels,
           all_identified=all(L["relation"] is not None for L in out_levels), minimiser=[mp.nstr(z, 45) for z in x])
json.dump(res, open(os.path.join(ROOT, "data", "w33_f8_rank3_stabiliser_exact.json"), "w"), indent=1, default=str)
