def load(path,name):
    s=importlib.util.spec_from_file_location(name,path); assert s and s.loader
    m=importlib.util.module_from_spec(s); sys.modules[name]=m; s.loader.exec_module(m); return m

def hmul(g,h):
    a,b,c=g; A,B,C=h
    return ((a+A)%3,(b+B)%3,(c+C-b*A)%3)

def kmul(x,y):
    return (hmul(x[0],y[0]),(x[1]+y[1])%3)

def subgroup3(g):
    I=((0,0,0),0)
    return (I,g,kmul(g,g))

def right_cosets(K,S):
    unseen=set(K);out=[]
    while unseen:
        x=min(unseen)
        C=frozenset(kmul(x,s) for s in S)
        out.append(C); unseen-=C
    return out

def lift3(x):return 1+(int(x)%3)

def main(write=True):
    align=load(ROOT/"analysis/w33_e6_cubic_fourier54_alignment.py","phase_weld_align")
