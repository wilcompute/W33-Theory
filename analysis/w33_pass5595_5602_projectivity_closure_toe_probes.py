def relation_type(g, identity):
    return -1 if g == identity else fixed_points(g)


def fixedpoint_scheme_data(G, verify_all=False):
    identity = tuple(range(len(G[0])))
    typemap = {g: relation_type(g, identity) for g in G}
    types = sorted(set(typemap.values()))
    cls = {t: [g for g in G if typemap[g] == t] for t in types}
    reps = {t: cls[t][0] for t in types}
    rep_counts = {}
    for k, h in reps.items():
        for i in types:
            c = Counter()
            for x in cls[i]:
                c[typemap[compose(inverse_perm(x), h)]] += 1
            for j in types:
                rep_counts[(i, j, k)] = c[j]
    if verify_all:
        for k in types:
            for i in types:
                for j in types:
                    want = rep_counts[(i, j, k)]
                    for h in cls[k]:
                        got = 0
                        for x in cls[i]:
                            if typemap[compose(inverse_perm(x), h)] == j:
                                got += 1
                        assert got == want
    return {t: len(cls[t]) for t in types}, rep_counts


