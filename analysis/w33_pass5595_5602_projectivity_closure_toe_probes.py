class GFp2:
    def __init__(self, p, d):
        self.p = p
        self.d = d % p
        self.q = p * p

    def pair(self, x):
        return x % self.p, x // self.p

    def enc(self, a, b):
        return (a % self.p) + self.p * (b % self.p)

    def add(self, x, y):
        a, b = self.pair(x); c, d = self.pair(y)
        return self.enc(a + c, b + d)

    def neg(self, x):
        a, b = self.pair(x)
        return self.enc(-a, -b)

    def sub(self, x, y):
        return self.add(x, self.neg(y))

    def mul(self, x, y):
        a, b = self.pair(x); c, e = self.pair(y)
        return self.enc(a * c + b * e * self.d, a * e + b * c)

    def inv(self, x):
        if x == 0:
            raise ZeroDivisionError
        a, b = self.pair(x)
        den = (a * a - self.d * b * b) % self.p
        z = pow(den, -1, self.p)
        return self.enc(a * z, -b * z)

    def square(self, x):
        return self.mul(x, x)


def normF(v, F):
    for a in v:
        if a:
            z = F.inv(a)
            return tuple(F.mul(z, x) for x in v)
    raise ValueError("zero vector")


def p1_F(F):
    return [(1, t) for t in range(F.q)] + [(0, 1)]


def pg3_F(F):
    out = []
    for lead in range(4):
        for tail in itertools.product(range(F.q), repeat=3 - lead):
            out.append((0,) * lead + (1,) + tail)
    return out


def QF(v, F):
    return F.add(F.mul(v[0], v[1]), F.mul(v[2], v[3]))


def BF(u, v, F):
    return F.add(
        F.sub(F.mul(u[0], v[1]), F.mul(u[1], v[0])),
        F.sub(F.mul(u[2], v[3]), F.mul(u[3], v[2])),
    )


def segreF(u, v, F):
    return normF((
        F.mul(u[0], v[0]),
        F.mul(u[1], v[1]),
        F.mul(u[0], v[1]),
        F.neg(F.mul(u[1], v[0])),
    ), F)


def TapplyF(p, v, F):
    a, b, c, d = p
    return normF((
        F.sub(F.mul(c, v[0]), F.mul(a, v[1])),
        F.sub(F.neg(F.mul(b, v[0])), F.mul(d, v[1])),
    ), F)


def mat_apply_F(m, v, F):
    a, b, c, d = m
    return normF((
        F.add(F.mul(a, v[0]), F.mul(b, v[1])),
        F.add(F.mul(c, v[0]), F.mul(d, v[1])),
    ), F)


