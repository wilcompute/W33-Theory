def normp(v, q):
    v = tuple(x % q for x in v)
    for a in v:
        if a:
            z = pow(a, -1, q)
            return tuple(z * x % q for x in v)
    raise ValueError("zero vector")


def p1_prime(q):
    return [(1, t) for t in range(q)] + [(0, 1)]


def pg3_prime(q):
    out = []
    for lead in range(4):
        for tail in itertools.product(range(q), repeat=3 - lead):
            out.append((0,) * lead + (1,) + tail)
    return out


def Bp(u, v, q):
    return (u[0] * v[1] - u[1] * v[0] + u[2] * v[3] - u[3] * v[2]) % q


def Qp(v, q):
    return (v[0] * v[1] + v[2] * v[3]) % q


def mat_norm_prime(m, q):
    return normp(m, q)


def mat_apply_prime(m, v, q):
    a, b, c, d = m
    return normp((a * v[0] + b * v[1], c * v[0] + d * v[1]), q)


def pgl_psl_perms_prime(q):
    P = p1_prime(q)
    idx = {x: i for i, x in enumerate(P)}
    squares = {x * x % q for x in range(1, q)}
    pgl_mats = set()
    psl_mats = set()
    for vals in itertools.product(range(q), repeat=4):
        if not any(vals):
            continue
        a, b, c, d = vals
        if (a * d - b * c) % q == 0:
            continue
        key = mat_norm_prime(vals, q)
        pgl_mats.add(key)
        a, b, c, d = key
        if (a * d - b * c) % q in squares:
            psl_mats.add(key)
    def perms(mats):
        return sorted({tuple(idx[mat_apply_prime(m, v, q)] for v in P) for m in mats})
    return perms(pgl_mats), perms(psl_mats)


def row_bits_from_perm(g):
    n = len(g)
    x = 0
    for a in range(n):
        x |= 1 << (a * n + g[a])
    return x


