def compose(a, b):
    return tuple(a[b[i]] for i in range(len(a)))


def inverse_perm(a):
    out = [0] * len(a)
    for i, j in enumerate(a):
        out[j] = i
    return tuple(out)


def parity(p):
    s = 0
    for i in range(len(p)):
        for j in range(i + 1, len(p)):
            s ^= int(p[i] > p[j])
    return s


def fixed_points(p):
    return sum(i == p[i] for i in range(len(p)))


def perm_power(g, n):
    out = tuple(range(len(g)))
    for _ in range(n):
        out = compose(g, out)
    return out


def rank_bits(rows):
    basis = {}
    for x in rows:
        y = x
        while y:
            p = y.bit_length() - 1
            if p in basis:
                y ^= basis[p]
            else:
                basis[p] = y
                break
    return len(basis), basis


def in_span(x, basis):
    y = x
    while y:
        p = y.bit_length() - 1
        if p not in basis:
            return False
        y ^= basis[p]
    return True


def basis_list(rows):
    return list(rank_bits(rows)[1].values())


def enumerate_code(basis):
    code = [0]
    for b in basis:
        code += [x ^ b for x in code]
    return code


