#!/usr/bin/env python3
"""Execute five exact frontier audits for the 216/540 sentinel circuit geometry.

This single reconstruction deliberately shares the expensive PSp(4,3), C5, C6,
and bicolour incidence setup across five logically separate targets:

1. Restrict all seven bicolour spectral sectors to the order-648 W33 point
   stabilizer K, with exact character inner products and central-C3 splitting.
2. Give the conjugate sixes in the 24-sector a concrete Eisenstein/deck model:
   the 12-dimensional rational carrier has J=z-z^2 with J^2=-3, and a
   deterministic six-fibre witness spans it over Q(sqrt(-3)).
3. Resolve the 540-side right-kernel geometry, including the exact 216+324
   image/kernel split and the mutual position of the three 324-dimensional
   kernels for M, M+, M-.
4. Compute modular ranks of M, M+, M- and their Gram operators at the primes
   singled out by the integral spectrum (plus controls), providing a Smith-
   filtration audit without claiming a full integral SNF where it is not proved.
5. Close the 17 cross orbitals into the full two-fibre Schurian coherent
   configuration: enumerate C5xC5 and C6xC6 orbitals, certify cross-product
   structure constants, and locate A20/A30 inside the same-fibre orbital algebra.

All spectral projectors are exact integer Lagrange polynomials.  No floating
point eigenspaces are used.
"""
from __future__ import annotations

import hashlib
