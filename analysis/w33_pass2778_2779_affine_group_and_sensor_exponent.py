"""Passes 2778-2779 -- two questions the Pass 2774 reachability result left open.

PASS 2778.  Reachability says the 81 frames are covered once sigma^5 = Z is present.
It does not say what GROUP the instruction set generates, and "the frame space is
reachable" is much weaker than "every frame transformation is expressible".  The right
object is the affine symplectic group

    ASp(4,3) = F_3^4 : Sp(4,3),     order 81 * 51840 = 4199040,

and the question is whether the eight opcodes generate it, and whether ONE translation
generator suffices or a second is needed.

PASS 2779.  The parallel track's Pass 2768 sensor is

    Theta_k(g) = Tr(U_g^k)^9 / det(U_g^k),   k = 1,2

with the ninth power stated as making it "independent of the arbitrary global Clifford
phase".  The exponent is presented as a fact.  It has a reason, and the reason bounds
how cheap the sensor can be: under U -> lambda U on a d-dimensional representation,
Tr(U^k)^e -> lambda^{ke} Tr(U^k)^e and det(U^k) -> lambda^{kd} det(U^k), so the quotient
is invariant for ALL lambda in U(1) exactly when e = d.  Here d = 9 -- the dimension of
the two-qutrit state space, which under the Pass 2724 reading is End(C^3).

But if the phase ambiguity is not all of U(1) -- if the Clifford representatives can be
chosen so that the scalars appearing in the group are only an m-th root of unity -- then
any e = d mod m works, and the smallest is cheaper to measure.  So this computes the
actual scalar subgroup of the generated matrix group rather than assuming U(1).

    py -3 analysis/w33_pass2778_2779_affine_group_and_sensor_exponent.py
"""

