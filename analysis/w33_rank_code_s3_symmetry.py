"""Pass 12653: why are the size-7 node counts of the 8 O(5)-orbit representatives of S2 nearly equal (522,808 - 525,273)?
The three fixed Lagrangians of the rank-code form (graphs of S = 0, S = infinity, S = I) are permuted by symplectic maps
S -> S^{-1} (swaps 0, infinity) and S -> S + I (swaps 0, I), generating S3; these preserve 'nonsingular with nonsingular
difference' and maximality, so the S2 orbits under O(5) may merge under O(5) x S3.  Here: action of the two maps on the 8 orbits.
Control: on n = 3 the merged count must be consistent with the single Sp(6,2)-orbit of five-sets.  usage: py -3 analysis/w33_rank_code_s3_symmetry.py"""
import json, os
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
g = {"__name__": "x", "__file__": os.path.join(HERE, "w33_five_qubit_size6.py")}
src = open(os.path.join(HERE, "w33_five_qubit_size6.py"), encoding="utf-8").read()
exec(src[: src.index(chr(10) + "def run(")], g)
setup, code_of, orthogonal_group, congr = g["setup"], g["code_of"], g["orthogonal_group"], g["congr"]
def mat(n, pos, c):
    M = np.zeros((n, n), int)
    for b, (i, j) in enumerate(pos):
        if c >> b & 1: M[i, j] = M[j, i] = 1
    return M
def inv2(M):
    n = len(M); A = np.concatenate([M % 2, np.eye(n, dtype=int)], 1)
    r = 0
    for col in range(n):
        piv = next(k for k in range(r, n) if A[k, col])
        A[[r, piv]] = A[[piv, r]]
        for k in range(n):
            if k != r and A[k, col]: A[k] ^= A[r]
        r += 1
    return A[:, n:]
out = {}
for n in (3, 5):
    pos, sing, alt, ns = setup(n); O = orthogonal_group(n)
    I = code_of(n, pos, np.eye(n, dtype=int).tolist()); cand = ns[~sing[ns ^ I]].tolist()
    orbit_of = {}; reps = []
    for s in cand:
        if s in orbit_of: continue
        orb = {congr(n, pos, A, s) for A in O}
        for x in orb: orbit_of[x] = len(reps)
        reps.append((s, len(orb)))
    phi1 = lambda c: code_of(n, pos, inv2(mat(n, pos, c)).tolist())
    phi2 = lambda c: c ^ I
    act1 = [orbit_of[phi1(s)] for s, _ in reps]; act2 = [orbit_of[phi2(s)] for s, _ in reps]
    # merged classes under the group generated by the two permutations
    parent = list(range(len(reps)))
    def f(x):
        while parent[x] != x: x = parent[x]
        return x
    for a in (act1, act2):
        for i, j in enumerate(a): parent[f(i)] = f(j)
    classes = {}
    for i in range(len(reps)): classes.setdefault(f(i), []).append(i)
    out[n] = dict(n_orbits=len(reps), orbit_sizes=[sz for _, sz in reps], reps=[s for s, _ in reps], phi_inverse=act1, phi_plus_I=act2,
                  merged_classes=list(classes.values()))
    print(n, out[n], flush=True)
json.dump(out, open(os.path.join(ROOT, "data", "w33_rank_code_s3_symmetry.json"), "w"), indent=1)
