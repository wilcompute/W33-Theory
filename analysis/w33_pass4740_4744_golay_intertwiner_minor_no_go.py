"""Passes 4740 and 4744: demand an actual Golay intertwiner, or certify why it fails.

4740  The established W33/Golay files contain many exact parameter equalities,
      but a coordinate-equivariant bridge would require the W33 symmetry to act
      on the 24 Golay coordinates.  A faithful PSp(4,3) coordinate action is
      impossible: |PSp(4,3)|=2^6*3^4*5 does not divide
      |M24|=2^10*3^3*5*7*11*23.  This is only a coordinate-permutation no-go;
      it does NOT rule out a non-coordinate Leech/Conway representation.

      The most natural 24-coordinate puncture supplied by the new involution
      geometry removes the sixteen W33 lines fixed by a 45-class involution.
      It gives H10|_24 = [24,10,6], with an explicit weight-6 word, hence cannot
      be a subcode of the extended binary Golay [24,12,8].  Shortening H10 on
      those sixteen positions gives only [24,2,16].

4744  Census a second intrinsic 24-coordinate family: complements of the 135
      weight-16 H10 words.  All 135 give the same puncture signature [24,9,4]
      and shortening [24,1,24].  Thus neither canonical 24-coordinate family is
      Golay.  The dual puncture along the involution-fixed family is [24,22,2],
      so the minimum-shell side also fails immediately.  This turns the old
      numerical 24/12/8 bridge into a precise boundary: the standard coordinate
      route is blocked, while a non-coordinate Conway/Leech intertwiner remains
      a legitimate separate problem.
"""
from __future__ import annotations
import itertools,json,math
from collections import Counter
from pathlib import Path
