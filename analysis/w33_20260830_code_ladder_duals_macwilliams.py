#!/usr/bin/env python3
"""Close the binary W33 adjacency/sentinel code ladder under duality.

Let C_S be the [40,15,8]_2 sentinel generated by the 45 Hermitian supports and
C_A the rank-16 W33 adjacency-row code.  The prior extension theorem proves
C_S < C_A with quotient C2.  This audit computes both complete weight
enumerators, the unique nonzero coset enumerator, their MacWilliams duals, and
identifies the duals geometrically with the W33 line code and line-difference
code.
"""
from __future__ import annotations

import json
from collections import Counter
from math import comb
from pathlib import Path

from w33_20260829_pg34_polarity_sentinel import geometry, trade_incidence, gf2_basis, in_span

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data/PART_W33_20260830_CODE_LADDER_DUALS_MACWILLIAMS.json"


def mask(bits):
    return sum((x & 1) << i for i, x in enumerate(bits))


def enumerate_code(basis):
    words = set(); E = Counter()
    for coeff in range(1 << len(basis)):
        w = 0
        for i, b in enumerate(basis):
            if (coeff >> i) & 1:
                w ^= b
        words.add(w); E[w.bit_count()] += 1
    return words, dict(sorted(E.items()))


def krawtchouk(n, j, i):
    return sum(
        (-1) ** s * comb(i, s) * comb(n - i, j - s)
        for s in range(max(0, j - (n - i)), min(j, i) + 1)
    )


def macwilliams(E, n, k):
    size = 1 << k; out = {}
    for j in range(n + 1):
        z = sum(Ai * krawtchouk(n, j, i) for i, Ai in E.items())
        assert z % size == 0
        z //= size
        if z:
            out[j] = z
    return out


def main():
    N, A = geometry()
    B, _ = trade_incidence(N)
    adjacency = [mask(row) for row in A]
    sentinel = [sum((B[i][j] & 1) << i for i in range(40)) for j in range(45)]
    lines = [mask(row) for row in N]

    BA = gf2_basis(adjacency); BS = gf2_basis(sentinel)
    assert len(BA) == 16 and len(BS) == 15
    assert all(in_span(s, BA) for s in sentinel)
    assert all((x & y).bit_count() % 2 == 0 for x in BA for y in BA)

    WA, EA = enumerate_code(BA)
    WS, ES = enumerate_code(BS)
    expected_S = {0:1,8:45,12:720,16:6930,20:17376,24:6930,28:720,32:45,40:1}
    expected_A = {0:1,8:45,12:1120,16:15570,20:32064,24:15570,28:1120,32:45,40:1}
    assert ES == expected_S and EA == expected_A
    assert WS < WA

    coset = {w: EA.get(w, 0) - ES.get(w, 0) for w in sorted(set(EA) | set(ES))}
    coset = {w: n for w, n in coset.items() if n}
    expected_coset = {12:400,16:8640,20:14688,24:8640,28:400}
    assert coset == expected_coset and sum(coset.values()) == 1 << 15

    DA = macwilliams(EA, 40, 16)
    DS = macwilliams(ES, 40, 15)
    expected_DA = {
        0:1,6:240,8:2205,10:23760,12:182560,14:664560,16:2035170,
        18:3243600,20:4473024,22:3243600,24:2035170,26:664560,
        28:182560,30:23760,32:2205,34:240,40:1,
    }
    expected_DS = {
        0:1,4:40,6:240,8:5085,10:47824,12:353920,14:1378800,
        16:3944610,18:6699600,20:8694192,22:6699600,24:3944610,
        26:1378800,28:353920,30:47824,32:5085,34:240,36:40,40:1,
    }
    assert DA == expected_DA and DS == expected_DS

    dual_coset = {w: DS.get(w, 0) - DA.get(w, 0) for w in sorted(set(DS) | set(DA))}
    dual_coset = {w: n for w, n in dual_coset.items() if n}
    expected_dual_coset = {
        4:40,8:2880,10:24064,12:171360,14:714240,16:1909440,
        18:3456000,20:4221168,22:3456000,24:1909440,26:714240,
        28:171360,30:24064,32:2880,36:40,
    }
    assert dual_coset == expected_dual_coset

    # C_S^perp is exactly the binary line code.  All line indicators are
    # orthogonal to C_S and their rank is the required dual dimension 25.
    line_basis = gf2_basis(lines)
    assert len(line_basis) == 25
    assert all((l & s).bit_count() % 2 == 0 for l in lines for s in BS)
    # The 40 weight-four dual words are therefore exactly the 40 W33 lines.
    assert len(set(lines)) == 40 and {l.bit_count() for l in lines} == {4}
    assert DS[4] == 40

    # C_A^perp is exactly the line-difference code.  The prior universal line
    # parity theorem implies every line difference annihilates C_A; rank 24
    # matches the dual dimension.
    diffs = [lines[i] ^ lines[0] for i in range(1, 40)]
    diff_basis = gf2_basis(diffs)
    assert len(diff_basis) == 24
    assert all((d & a).bit_count() % 2 == 0 for d in diff_basis for a in BA)

    # Its 240 minimum weight-six words are precisely symmetric differences of
    # intersecting W33 line pairs (one common point -> 4+4-2 = 6).
    line_sets = [{i for i in range(40) if (l >> i) & 1} for l in lines]
    w6 = {
        lines[i] ^ lines[j]
        for i in range(40) for j in range(i)
        if len(line_sets[i] & line_sets[j]) == 1
    }
    assert len(w6) == 240 and {w.bit_count() for w in w6} == {6}
    assert all(in_span(w, diff_basis) for w in w6)
    assert DA[6] == 240

    out = {
        "schema": "w33.20260830.code-ladder-duals-macwilliams.v1",
        "status": "PASS",
        "primal": {
            "sentinel": {"parameters":"[40,15,8]_2","weightEnumerator":expected_S},
            "adjacency": {"parameters":"[40,16,8]_2","selfOrthogonal":True,"weightEnumerator":expected_A},
            "quotient": "C_A/C_S = C2",
            "nonzeroCosetWeightEnumerator": expected_coset,
            "minimumWords": "both codes have the same 45 weight-eight sentinel minima; the added coset starts at weight 12",
        },
        "dual": {
            "adjacencyDual": {"parameters":"[40,24,6]_2","weightEnumerator":expected_DA,"geometry":"span of all differences of W33 line indicators"},
            "sentinelDual": {"parameters":"[40,25,4]_2","weightEnumerator":expected_DS,"geometry":"binary span of the 40 W33 line indicators"},
            "quotient": "C_S^perp/C_A^perp = C2",
            "nonzeroCosetWeightEnumerator": expected_dual_coset,
            "weight4Words": "exactly the 40 W33 lines",
            "weight6WordsOfAdjacencyDual": "exactly the 240 symmetric differences of intersecting line pairs",
        },
        "theorem": "Duality turns the primal line-parity extension into a literal line-code extension: C_S^perp is the rank-25 W33 line code and C_A^perp is its rank-24 line-difference kernel. MacWilliams gives both full dual enumerators and both nontrivial coset enumerators exactly.",
        "boundary": "All statements are exact binary code/finite-geometry identities. No physical error-rate interpretation is implied by code distance alone.",
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"status":"PASS","CA":"[40,16,8]","CS":"[40,15,8]","CAdual":"[40,24,6]","CSdual":"[40,25,4]","lineCodeRank":25,"lineDifferenceRank":24}, sort_keys=True))


if __name__ == "__main__":
    main()
