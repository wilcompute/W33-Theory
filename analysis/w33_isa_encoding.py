def transvection(v, a, J):
    """Symplectic transvection T_{v,a}(x) = x + a*B(x,v)*v as a matrix (mod 3)."""
    d = len(v)
    v = np.array(v).reshape(d, 1)
    Jv = (J @ v) % 3
    return (np.eye(d, dtype=int) + a * (v @ Jv.T)) % 3


def is_symplectic(M, J):
    return np.array_equal((M.T @ J @ M) % 3, J % 3)


def projective_points(d):
    inv = {1: 1, 2: 2}

    def norm(v):
        for c in v:
            if c != 0:
                return tuple((x * inv[c]) % 3 for x in v)

    return sorted({norm(v) for v in itertools.product(range(3), repeat=d) if any(v)})


def group_closure(gens, d):
    """BFS closure of the matrix group generated by gens (mod 3); returns its order."""
    I = np.eye(d, dtype=int) % 3
    seen = {I.tobytes()}
    frontier = [I]
    while frontier:
        nxt = []
        for M in frontier:
            for g in gens:
                P = (g @ M) % 3
                key = P.tobytes()
                if key not in seen:
                    seen.add(key)
                    nxt.append(P)
        frontier = nxt
    return len(seen)


