#!/usr/bin/env python3
"""Exact A8^3 simple-current sector-return / monodromy audit.

The Niemeier A8^3 extension has glue C <= (Z/9)^3 generated by permutations
of (1,1,4).  Every glue sector has *integral* conformal weight (0,2,3), so the
discriminant quadratic form q(c)=h_c mod 1 vanishes identically on C.  Hence
the associated simple-current monodromy bicharacter

    b(c,d) = q(c+d)-q(c)-q(d)

also vanishes identically.  In particular all 13 nonzero inverse pairs
c,-c return to the vacuum sector with trivial simple-current exchange phase.

This is a stronger null than merely observing that the Z9 center acts by a
scalar: the entire abelian glue category is a bosonic/totally-isotropic simple-
current extension.  Thus a qutrit-T-like ninth-root phase cannot come from the
fusion/monodromy data of V_c V_-c -> V_0 alone.

The separate six-qutrit twisted ground register is an irreducible
3^(1+12) Heisenberg module of dimension 729.  By Schur/Stone-von Neumann, any
sector-return endomorphism which commutes with the full Heisenberg action is a
scalar.  Fusion data alone do not prove that a concrete descendant/OPE return
operator commutes with Heisenberg, so this file does NOT rule out a more
structured noncentral return map; it proves exactly what the certified glue
category can and cannot supply.
"""
from __future__ import annotations
from fractions import Fraction
import itertools, json
from collections import Counter
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'data'/'w33_a8cubed_sector_return_monodromy.json'
GEN=((1,1,4),(1,4,1),(4,1,1))

def h1(k:int)->Fraction:
    k%=9
    return Fraction(k*(9-k),18)

def hw(c):
    return sum((h1(k) for k in c),Fraction(0))

def add(a,b):return tuple((x+y)%9 for x,y in zip(a,b))
def neg(a):return tuple((-x)%9 for x in a)

def order(c):
    z=(0,0,0)
    for n in range(1,10):
        z=add(z,c)
        if z==(0,0,0):return n
    raise AssertionError

def main(write=True):
    C=set()
    for a,b,c in itertools.product(range(9),repeat=3):
        C.add(tuple((a*GEN[0][i]+b*GEN[1][i]+c*GEN[2][i])%9 for i in range(3)))
    assert len(C)==27
    hc=Counter(hw(c) for c in C);assert hc==Counter({Fraction(2):18,Fraction(3):8,Fraction(0):1})
    # q(c)=h_c modulo one and b(c,d)=q(c+d)-q(c)-q(d) vanish identically.
    assert all(hw(c).denominator==1 for c in C)
    assert all((hw(add(c,d))-hw(c)-hw(d)).denominator==1 for c in C for d in C)
    # There are 13 inverse pairs because C has odd order and no nonzero self-inverse element.
    seen={(0,0,0)};pairs=[]
    for c in sorted(C):
        if c in seen:continue
        d=neg(c);assert add(c,d)==(0,0,0) and d!=c
        pairs.append({'c':list(c),'minus_c':list(d),'weight':str(hw(c)),'order':order(c)})
        seen.add(c);seen.add(d)
    assert len(pairs)==13
    profile=Counter((x['weight'],x['order']) for x in pairs)
    reg=json.loads((ROOT/'data'/'w33_e8cubed_leech_six_qutrit_register.json').read_text())
    assert reg['status']=='PASS' and reg['common_register']['ground_state_dimension']==729
    out={
      'schema':'w33.a8cubed_sector_return_monodromy.v1','status':'PASS',
      'headline':'All 27 A8^3 glue simple currents are bosonic/totally isotropic: h_c is integral and the monodromy bicharacter vanishes identically. The 26 nonzero sectors form 13 inverse pairs V_c V_-c -> V_0 with trivial simple-current exchange phase. Thus glue fusion/monodromy alone cannot produce a qutrit-T-like ninth-root gate.',
      'glue':{'order':27,'weight_census':{str(k):v for k,v in sorted(hc.items())},'q_mod_1_identically_zero':True,'monodromy_bicharacter_identically_zero':True},
      'inverse_pairs':{'count':13,'profile_weight_order':{f'h{h}_ord{o}':n for (h,o),n in sorted(profile.items())},'pairs':pairs},
      'six_qutrit_register':{'dimension':729,'Heisenberg_shape':'3^(1+12)','Schur_boundary':'Any return endomorphism commuting with the full irreducible Heisenberg action is scalar.'},
      'result':'No nontrivial sector-return phase is available from the abelian simple-current topological data. A non-Clifford return map would have to use noncentral descendant/OPE action that is not fixed by the fusion group C.',
      'boundary':'This does not classify all intertwining operators on the twisted module. It closes only the topological/simple-current return mechanism and the Heisenberg-equivariant subcase.',
      'checks':{'C_order_27':True,'weights_0_2_3':True,'all_integral':True,'all_monodromy_zero':True,'13_inverse_pairs':True,'register_729':True}}
    if write:OUT.write_text(json.dumps(out,indent=2)+'\n')
    print(json.dumps(out,indent=2));return out
if __name__=='__main__':main(True)
