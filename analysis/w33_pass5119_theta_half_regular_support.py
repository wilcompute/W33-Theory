"""Pass5119: every apartment-code support is half-regular in the theta graph."""
from __future__ import annotations
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'data/PART_W33_PASS5119_THETA_HALF_REGULAR_SUPPORT.json'

def row(q):
    # Each apartment lies in 4(q-1) theta checks, and each check containing a
    # selected apartment contains exactly one other selected coordinate by even parity.
    return {'q':q,'theta_graph_degree':8*(q-1),'selected_induced_degree':4*(q-1),
            'selected_external_degree':4*(q-1),
            'apartment_count':q**4*(q+1)**2*(q*q+1)//8}

def main():
    anchors={str(q):row(q) for q in (2,3,4,5)}
    assert anchors['3']['theta_graph_degree']==16 and anchors['5']['selected_induced_degree']==16
    out={'pass':5119,'status':'THEOREM_ALL_Q_THETA_HALF_REGULAR_SUPPORT',
         'statement':'For every nonzero binary W(3,q) apartment-code word with support S, the theta point graph induced on S is 4(q-1)-regular inside the ambient 8(q-1)-regular theta graph. Every selected vertex also has exactly 4(q-1) neighbors outside S.',
         'proof':'The complete dual is generated by theta triples. Each apartment belongs to 4(q-1) theta checks and no apartment pair belongs to two checks. A selected coordinate forces exactly one of the other two coordinates in each incident theta triple to be selected, giving one distinct internal neighbor per check; the other endpoint is external.',
         'edge_boundary':'|delta_theta(S)|=4(q-1)|S|',
         'distance_reformulation':'Minimum distance is therefore a constrained induced-subgraph/isoperimetry problem in a graph reconstructed intrinsically from the code. The triangle parity constraints remain part of the constraint set.',
         'anchors':anchors,
         'boundary':'Half-regularity is necessary for codeword supports. It is not asserted to be sufficient without the full theta-triangle parity constraints.'}
    OUT.write_text(json.dumps(out,indent=2)+'\n');print(json.dumps(out,indent=2))
if __name__=='__main__':main()
