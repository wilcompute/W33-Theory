#!/usr/bin/env python3
"""Pass 205: the composition series of the reducible q=7 shadow.

Pass 199 found the 48-dimensional q=7 shadow is F2-reducible under the
substrate collineation group.  This witness computes its full composition
series (MeatAxe-style) from a generating pair -- no enumeration of the
big group Sp(4,7) -- and asks whether the higher ladder rungs are built
from copies of the E8 shadow:

1. THE SERIES.  Recursive submodule finding: locate a minimal nonzero
   submodule (spin the shortest cyclic submodule; if reducible, recurse),
   quotient, repeat.  The exact multiset of composition-factor dimensions
   is reported.

2. THE E8 QUESTION.  Whether any factor has dimension 8 (an E8-shadow
   piece) or whether the split is into other substrate constituents;
   the endomorphism dimension of the whole module is computed (a lower
   bound on the number of factors) as a cross-check.
"""

