"""Outside-the-box 2: triality.  For each tensor split {b, b-perp} the 24 maximally entangled bases are three unextendible 8-MUB sets
(Pass 12636 add. 2), coming from the three orthogonal frames of one D4 (Pass 12636).  D4's three frames are permuted by triality;
in E6, N(D4)/W(D4) = S3.  Test: the stabiliser of a split in PSp(4,3) (all 25920 elements, generated by transvections on the 40
points) acts on the three 8-sets - image S3 (triality) or smaller?  Also the subgroup swapping the two tensor factors b <-> b-perp,
and whether the factor swap acts on the three classes as a transposition.
usage: py -3 analysis/w33_split_triality.py"""
import itertools, json, os
from collections import Counter
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sb = {"__name__": "x", "__file__": os.path.join(HERE, "w33_pass12635_burkhardt_fan.py")}
exec(open(os.path.join(HERE, "w33_pass12635_burkhardt_fan.py"), encoding="utf-8").read().split("res = dict(")[0], sb)
P, iso, splits, w = sb["P"], sb["iso"], sb["splits"], sb["w"]
lines = [frozenset(L) for L in iso]
idx = {p: i for i, p in enumerate(P)}
norm = lambda v: next(tuple((x * pow(c, -1, 3)) % 3 for x in v) for c in v if c)
gens = [tuple(idx[norm(tuple((x + w(p, v) * vi) % 3 for x, vi in zip(p, v)))] for p in P) for v in P]
group = {tuple(range(40))}
frontier = [tuple(range(40))]
while frontier:
    new = []
    for g in frontier:
        for h in gens:
            k = tuple(h[g[i]] for i in range(40))
            if k not in group:
                group.add(k); new.append(k)
    frontier = new
print("|PSp(4,3)| on points:", len(group))
disj = [[not (lines[a] & lines[b]) for b in range(40)] for a in range(40)]
line_index = {L: i for i, L in enumerate(lines)}
def lines_of(g):
    return [line_index[frozenset(g[p] for p in L)] for L in lines]
summary = Counter()
for s_i, (b, bp) in enumerate(splits[:45]):
    missing = [l for l in range(40) if not (lines[l] & (b | bp))]
    # the three 8-sets: maximal cliques of size 8 inside the 24 missing lines (pairwise disjoint)
    eights = []
    def bk(R, Pc, X):
        if not Pc and not X:
            if len(R) == 8: eights.append(frozenset(R))
            return
        for v in list(Pc):
            bk(R | {v}, {u for u in Pc if disj[v][u]}, {u for u in X if disj[v][u]}); Pc = Pc - {v}; X = X | {v}
    bk(set(), set(missing), set())
    assert len(eights) == 3, len(eights)
    stab = [g for g in group if {frozenset(g[p] for p in b), frozenset(g[p] for p in bp)} == {b, bp}]
    images = set(); swap_images = set()
    for g in stab:
        gl = lines_of(g)
        perm = tuple(eights.index(frozenset(gl[l] for l in E)) for E in eights)
        images.add(perm)
        if frozenset(g[p] for p in b) == bp:
            swap_images.add(perm)
    summary[(len(stab), len(images), len(swap_images), tuple(sorted(Counter(sum(1 for i in range(3) if p[i] == i) for p in swap_images).items())))] += 1
print("per split (|stabiliser|, |image on the three 8-sets|, # images of factor-swapping elements, fixed-point profile of swap images): count")
for k, v in summary.items():
    print("  ", k, v)
res = {str(k): v for k, v in summary.items()}
json.dump(dict(summary=res, full_S3_on_all=all(eval(k)[1] == 6 for k in res)), open(os.path.join(ROOT, "data", "w33_split_triality.json"), "w"), indent=1)

# --- add the outer (antiunitary-type) coset: g0 = diag(1,1,-1,-1) scales the symplectic form by -1; <PSp, g0> = PGSp(4,3) (order 51840)
g0 = tuple(idx[norm((p[0], p[1], (-p[2]) % 3, (-p[3]) % 3))] for p in P)
assert all((w(P[g0[i]], P[g0[j]]) == 0) == (w(P[i], P[j]) == 0) for i in range(40) for j in range(40))  # projective: orthogonality preserved; form scaled by -1 on representatives
full = set(group) | {tuple(g0[g[i]] for i in range(40)) for g in group}
print("|PGSp(4,3)| on points:", len(full))
summ2 = Counter()
for s_i, (b, bp) in enumerate(splits):
    missing = [l for l in range(40) if not (lines[l] & (b | bp))]
    eights = []
    def bk2(R, Pc, X):
        if not Pc and not X:
            if len(R) == 8: eights.append(frozenset(R))
            return
        for v in list(Pc):
            bk2(R | {v}, {u for u in Pc if disj[v][u]}, {u for u in X if disj[v][u]}); Pc = Pc - {v}; X = X | {v}
    bk2(set(), set(missing), set())
    stab = [g for g in full if {frozenset(g[p] for p in b), frozenset(g[p] for p in bp)} == {b, bp}]
    imgs = {}
    for g in stab:
        gl = lines_of(g)
        perm = tuple(eights.index(frozenset(gl[l] for l in E)) for E in eights)
        outer = g not in group
        imgs.setdefault(perm, set()).add(outer)
    transpositions = [p for p in imgs if sum(1 for i in range(3) if p[i] == i) == 1]
    summ2[(len(stab), len(imgs), all(imgs[p] == {True} for p in transpositions))] += 1
print("per split in PGSp(4,3) (|stabiliser|, |image|, odd permutations come ONLY from the outer coset):", dict(summ2))
json.dump(dict(summary=res, pgsp=dict((str(k), v) for k, v in summ2.items())), open(os.path.join(ROOT, "data", "w33_split_triality.json"), "w"), indent=1)
