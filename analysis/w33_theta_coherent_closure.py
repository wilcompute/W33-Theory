A = np.array([[1 if a != b and w(pts[U[a]], pts[U[b]]) == 1 else 0 for b in range(n)] for a in range(n)])
col = np.where(np.eye(n, dtype=bool), 2, A)  # initial colours: diag, edge, non-edge
