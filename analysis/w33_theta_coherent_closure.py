edge_cls = [c for c, Bk in zip(classes, B) if (Bk * A).sum() > 0]
diag_cls = [c for c, Bk in zip(classes, B) if np.trace(Bk) > 0]
print("coherent closure rank:", len(classes), "| diagonal (vertex) classes:", len(diag_cls), [int(np.trace(B[classes.index(c)])) for c in diag_cls], "| edge classes:", len(edge_cls), flush=True)
x = cp.Variable(len(classes)); X = sum(x[i] * B[i] for i in range(len(classes)))
cons = [X >> 0, cp.trace(X) == 1] + [x[classes.index(c)] == 0 for c in edge_cls]
pr = cp.Problem(cp.Maximize(cp.sum(X)), cons); pr.solve(solver=cp.CLARABEL)
th = pr.value
mp = sp.nsimplify(th, [sp.sqrt(5)], tolerance=1e-7)
print("reduced theta:", th, " identified:", mp, flush=True)
