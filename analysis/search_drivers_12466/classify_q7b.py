"""12522, second stage: finish the star class that classify_q7.py could not enumerate in time.  Loop: find a 40-line hyperoval in the class (8 workers; this is search, not
enumeration), test it with cube_recognise, block its whole orbit under the stabiliser H of the star.  INFEASIBLE at the end means every 40-line hyperoval of this class is in a
recorded orbit.  H is generated by g = (generator of Stab(X), corrected by the radical element restoring the star); each is asserted to preserve X and the star.
usage: py -3 classify_q7b.py rep [secs_per_solve]"""
import itertools, json, sys, time
import numpy as np
from ortools.sat.python import cp_model
from star_cubes import build, orbits, star_action, _pow
from cube_recognise import recognise

rep = int(sys.argv[1]); tl = float(sys.argv[2]) if len(sys.argv) > 2 else 3600
q, W = 7, 40
B = build(q); digits, reps, counts = orbits(B); assert rep in set(reps.tolist())
F, lines, through, X = B["F"], B["lines"], B["through"], B["X"]; sets = [frozenset(L) for L in lines]; n = q + 1
star = [int(t) for t in digits[rep]]
I = ((1, 0), (0, 1)); Z = ((0, 0), (0, 0))
prim = next(c for c in F if c and len({_pow(B, c, k) for k in range(q - 1)}) == q - 1); neg = B["neg"]
raw = [B["on_lines"](B["mat4"](((prim, 0), (0, 1)), Z)), B["on_lines"](B["mat4"](((0, 1), (neg[1], 0)), Z)), B["on_lines"](B["mat4"](((1, 1), (0, 1)), Z)),
       B["on_lines"](lambda v: (v[0], v[1], B["mul"][prim][v[2]], B["mul"][prim][v[3]]))]
rad = [B["on_lines"](B["mat4"](I, ((a, b), (b, c)))) for a, b, c in itertools.product(F, repeat=3)]
starlines = [B["choices"][i][star[i]] for i in range(n)]; starset = set(starlines)
gens = []
for g in raw:
    img = [g[j] for j in starlines]
    r = [lp for lp in rad if {lp[j] for j in img} == starset]
    if not r: print("generator does not fix this star modulo the radical"); continue
    h = [r[0][g[j]] for j in range(len(lines))]; assert h[X] == X and {h[j] for j in starlines} == starset
    gens.append(h)
print(f"class {rep}: orbit {int(counts[list(reps).index(rep)])}, {len(gens)} stabiliser generators", flush=True)
fixed = {X} | starset
banned = {j for p in B["Xpts"] for j in through[p]} - fixed
md = cp_model.CpModel(); y = {j: (1 if j in fixed else 0 if j in banned else md.NewBoolVar(f"y{j}")) for j in range(len(lines))}
for p in range(len(B["pts"])):
    z = md.NewBoolVar(f"z{p}"); md.Add(sum(y[j] for j in through[p]) == 2 * z)
md.Add(sum(y.values()) == W)
res = dict(q=q, W=W, rep=rep, generators=len(gens), orbits=[]); t0 = time.time(); seen = set(); final = None
while True:
    sv = cp_model.CpSolver(); sv.parameters.max_time_in_seconds = tl; sv.parameters.num_workers = 8
    st = sv.Solve(md); final = sv.StatusName(st)
    if st not in (cp_model.OPTIMAL, cp_model.FEASIBLE): break
    S = frozenset(j for j in range(len(lines)) if (y[j] if isinstance(y[j], int) else sv.Value(y[j])))
    o = {S}; fr = [S]
    while fr:
        nx = []
        for T in fr:
            for h in gens:
                U = frozenset(h[j] for j in T)
                if U not in o: o.add(U); nx.append(U)
        fr = nx
    assert all(fixed <= T for T in o) and not (o & seen); seen |= o
    cube = bool(recognise(S, sets, q)["cube"])
    res["orbits"].append(dict(size=len(o), cube=cube))
    print(f"  orbit {len(res['orbits'])}: size {len(o)} cube={cube} total {len(seen)} {time.time() - t0:.0f}s", flush=True)
    for T in o:
        md.Add(sum(y[j] for j in T if not isinstance(y[j], int)) <= len([j for j in T if not isinstance(y[j], int)]) - 1)
res.update(final_status=final, total_sets=len(seen), seconds=round(time.time() - t0, 1))
print({k: v for k, v in res.items() if k != "orbits"}, res["orbits"], flush=True)
json.dump(res, open(f"classify_q7b_{rep}.json", "w"), indent=1)
