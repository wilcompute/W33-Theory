"""12483 addendum: the 216 minimum even line sets of W(3,3) form ONE orbit of PSp(4,3) (stabiliser order 25920/216 = 120).
Sp(4,3) is generated by the symplectic transvections x -> x + w(x,a) a; we act on points, hence on lines, hence on line sets, and
grow the orbit of one optimum by breadth-first search.  usage: py -3 orbit_q3.py"""
import itertools, json
from even_line_sets_gf import build
from pair_structure import enumerate_q3  # noqa: F401  (same build; the count 216 is from pair_structure.json)

q = 3
pts, lines, N = build(q)
pid = {p: i for i, p in enumerate(pts)}


def w(u, v):
    return (u[0] * v[2] + u[1] * v[3] - u[2] * v[0] - u[3] * v[1]) % q


def norm(v):
    f = next(x for x in v if x); s = pow(f, -1, q)
    return tuple(x * s % q for x in v)


gens = []
for a in pts:
    perm = [pid[norm(tuple((x[c] + w(x, a) * a[c]) % q for c in range(4)))] for x in pts]
    gens.append(perm)
lid = {frozenset(l): j for j, l in enumerate(lines)}
lgens = [[lid[frozenset(p[x] for x in l)] for l in lines] for p in gens]
assert all(sorted(g) == list(range(len(lines))) for g in lgens), "transvections must permute the lines"
res = json.load(open("pair_structure.json"))
start = None
import numpy as np
from scipy.optimize import milp, LinearConstraint, Bounds
n, m = N.shape
c = np.concatenate([np.ones(m), np.zeros(n)])
M = np.vstack([np.hstack([N, -2 * np.eye(n)]), np.concatenate([np.ones(m), np.zeros(n)])[None, :]])
r = milp(c, constraints=LinearConstraint(M, np.concatenate([np.zeros(n), [1]]), np.concatenate([np.zeros(n), [np.inf]])),
         integrality=np.ones(m + n), bounds=Bounds(np.zeros(m + n), np.concatenate([np.ones(m), np.full(n, 2)])))
start = frozenset(np.flatnonzero(np.round(r.x[:m])).tolist())
orbit = {start}; frontier = [start]
while frontier:
    nxt = []
    for S in frontier:
        for g in lgens:
            T = frozenset(g[j] for j in S)
            if T not in orbit:
                orbit.add(T); nxt.append(T)
    frontier = nxt
out = dict(orbit_size=len(orbit), enumerated=res["q3_enumeration"]["count"], one_orbit=len(orbit) == res["q3_enumeration"]["count"],
           stabiliser_order_in_PSp43=25920 // len(orbit))
print(json.dumps(out)); json.dump(out, open("orbit_q3.json", "w"))
