        MCGCheck("pants_g5_k", "pants curves g=5 = K", PANTS_CURVES_G5, K),
        MCGCheck("pants_flags", "pants flags", (PANTS_G2_IS_Q and PANTS_G3_IS_MULT_K2 and
                                                 PANTS_G5_IS_K), True),
