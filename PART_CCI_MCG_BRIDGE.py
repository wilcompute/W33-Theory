# ---------------------------------------------------------------------------
# W(3,3) atoms
# ---------------------------------------------------------------------------
Q: int = 3
LAM: int = 2
V: int = 40
K: int = 12
PHI3: int = Q**2 + Q + 1        # 13
PHI4: int = Q**2 + 1            # 10
PHI6: int = Q**2 - Q + 1        # 7
J_INV: int = 2 * LAM**2         # 8
EDGES: int = V * K // 2         # 240
EIG_MAX: int = 5
MULT_K2: int = K // 2           # 6
LEECH_DIM: int = 2 * K          # 24

# ---------------------------------------------------------------------------
# Mapping class group constants
# ---------------------------------------------------------------------------

# Genus labels (expressed via atoms)
GENUS_1: int = 1
GENUS_LAM: int = LAM             # 2
GENUS_Q: int = Q                 # 3
GENUS_HALF_K: int = K // 2      # 6

# H_1(Σ_g; ℤ) = ℤ^{2g} → symplectic space dimension
def homology_dim(g: int) -> int:
    return 2 * g

HOMOLOGY_DIM_G1: int = homology_dim(GENUS_1)    # 2 = LAM
HOMOLOGY_DIM_G2: int = homology_dim(GENUS_LAM)  # 4 = LAM²
HOMOLOGY_DIM_G3: int = homology_dim(GENUS_Q)    # 6 = MULT_K2

HOMOLOGY_G1_IS_LAM: bool = (HOMOLOGY_DIM_G1 == LAM)
HOMOLOGY_G3_IS_MULT_K2: bool = (HOMOLOGY_DIM_G3 == MULT_K2)

# Dehn-Lickorish-Humphries generators: 2g+1
def dlh_generators(g: int) -> int:
    return 2 * g + 1

DLH_G1: int = dlh_generators(GENUS_1)      # 3 = Q
DLH_G2: int = dlh_generators(GENUS_LAM)    # 5 = EIG_MAX
DLH_G3: int = dlh_generators(GENUS_Q)      # 7 = PHI6
DLH_G6: int = dlh_generators(GENUS_HALF_K) # 13 = PHI3

DLH_G1_IS_Q: bool = (DLH_G1 == Q)
DLH_G2_IS_EIG_MAX: bool = (DLH_G2 == EIG_MAX)
DLH_G3_IS_PHI6: bool = (DLH_G3 == PHI6)
DLH_G6_IS_PHI3: bool = (DLH_G6 == PHI3)

# SL(2,ℤ) ≅ MCG(Σ_1): generator orders
SL2Z_ORDER_S: int = LAM**2        # |S| = 4
SL2Z_ORDER_T: int = 0             # T = [[1,1],[0,1]] has infinite order
SL2Z_ORDER_ST: int = MULT_K2      # |ST| = 6 (ST has order 6)

SL2Z_S_IS_LAM_SQ: bool = (SL2Z_ORDER_S == LAM**2)
SL2Z_ST_IS_MULT_K2: bool = (SL2Z_ORDER_ST == MULT_K2)

# Teichmüller space dimension for genus g ≥ 2: real dim = 6g−6 = 2*(3g-3)
def teich_real_dim(g: int) -> int:
    if g == 0:
        return 0
    if g == 1:
        return LAM   # H, real dim 2 (here treated as moduli space ℳ_1)
    return 6 * g - 6

def teich_complex_dim(g: int) -> int:
    if g <= 1:
        return GENUS_1
    return 3 * g - 3

TEICH_DIM_G1: int = teich_real_dim(GENUS_1)       # 2 = LAM
TEICH_DIM_G2: int = teich_real_dim(GENUS_LAM)     # 6 = MULT_K2
TEICH_DIM_G3: int = teich_real_dim(GENUS_Q)       # 12 = K
TEICH_DIM_G5: int = teich_real_dim(EIG_MAX)       # 24 = LEECH_DIM

TEICH_G1_IS_LAM: bool = (TEICH_DIM_G1 == LAM)
TEICH_G2_IS_MULT_K2: bool = (TEICH_DIM_G2 == MULT_K2)
TEICH_G3_IS_K: bool = (TEICH_DIM_G3 == K)
TEICH_G5_IS_LEECH: bool = (TEICH_DIM_G5 == LEECH_DIM)

TEICH_COMPLEX_DIM_G2: int = teich_complex_dim(GENUS_LAM)  # 3 = Q
TEICH_COMPLEX_G2_IS_Q: bool = (TEICH_COMPLEX_DIM_G2 == Q)

# Symplectic group Sp(2g, ℤ) matrix dimensions
def sp_dim(g: int) -> int:
    return 2 * g

SP_DIM_G1: int = sp_dim(GENUS_1)      # 2 = LAM
SP_DIM_G3: int = sp_dim(GENUS_Q)      # 6 = MULT_K2
SP_DIM_G6: int = sp_dim(GENUS_HALF_K) # 12 = K

SP_DIM_G1_IS_LAM: bool = (SP_DIM_G1 == LAM)
SP_DIM_G3_IS_MULT_K2: bool = (SP_DIM_G3 == MULT_K2)
SP_DIM_G6_IS_K: bool = (SP_DIM_G6 == K)

# Euler characteristic of moduli space ℳ_g (Harer-Zagier):
# χ(ℳ_g) = ζ(1-2g) * (2g-2)! / (2^{2g-1} * ... ) — complex for general g
# For g=1: χ(ℳ_1) = ζ(-1) = -1/12 (related to ZETA_NEG1_DEN = K = 12)
# We record ζ(-1) = -1/K
EULER_CHAR_M1_DEN: int = K        # denominator = 12 = K ✓
EULER_CHAR_M1_NUM: int = -1
EULER_CHAR_M1: float = EULER_CHAR_M1_NUM / EULER_CHAR_M1_DEN  # -1/12

# Dehn surgery: for Seifert genus g surface bounding a knot K, 
# the Dehn twist along the knot contributes to MCG
# Number of distinct Dehn-twist boundary components for pants decompositions of Σ_g:
# 3g - 3 pairs of pants → 3g-3 curves
PANTS_CURVES_G1: int = 0   # no pants decomp for g=1
PANTS_CURVES_G2: int = teich_complex_dim(GENUS_LAM)   # 3 = Q
PANTS_CURVES_G3: int = teich_complex_dim(GENUS_Q)     # 6 = MULT_K2
PANTS_CURVES_G5: int = teich_complex_dim(EIG_MAX)     # 12 = K

PANTS_G2_IS_Q: bool = (PANTS_CURVES_G2 == Q)
PANTS_G3_IS_MULT_K2: bool = (PANTS_CURVES_G3 == MULT_K2)
PANTS_G5_IS_K: bool = (PANTS_CURVES_G5 == K)

# ---------------------------------------------------------------------------
# MCGCheck dataclass
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class MCGCheck:
    name: str
    description: str
    computed: Any
    expected: Any
    exact: bool = True

    @property
    def passes(self) -> bool:
        if self.exact:
            return self.computed == self.expected
        return abs(self.computed - self.expected) < 1e-10


# ---------------------------------------------------------------------------
# Check factories
# ---------------------------------------------------------------------------

def _make_atom_checks() -> List[MCGCheck]:
    return [
        MCGCheck("Q", "W(3,3) Q", Q, 3),
        MCGCheck("LAM", "W(3,3) LAM", LAM, 2),
        MCGCheck("K", "W(3,3) K", K, 12),
        MCGCheck("PHI3", "Q²+Q+1", PHI3, 13),
        MCGCheck("PHI4", "Q²+1", PHI4, 10),
        MCGCheck("PHI6", "Q²−Q+1", PHI6, 7),
        MCGCheck("J_INV", "2·LAM²", J_INV, 8),
        MCGCheck("EDGES", "V·K/2", EDGES, 240),
        MCGCheck("EIG_MAX", "max eigenvalue", EIG_MAX, 5),
    ]


