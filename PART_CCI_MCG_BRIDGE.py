# ---------------------------------------------------------------------------
# Audit function
# ---------------------------------------------------------------------------

def mcg_bridge_audit() -> Dict[str, Any]:
    categories = {
        "atom_checks": _make_atom_checks(),
        "homology_checks": _make_homology_checks(),
        "dlh_checks": _make_dlh_checks(),
        "sl2z_checks": _make_sl2z_checks(),
        "teich_checks": _make_teich_checks(),
        "structural_checks": _make_structural_checks(),
    }

    all_checks = [c for checks in categories.values() for c in checks]
    failed = [c.name for c in all_checks if not c.passes]
    passing = len(all_checks) - len(failed)

    return {
        "status": "PASS" if not failed else "FAIL",
        "all_checks_pass": not bool(failed),
        "check_count": len(all_checks),
        "checks_passing": passing,
        "failed_checks": failed,
        "category_counts": {k: len(v) for k, v in categories.items()},
        "teichmuller_dims": {
            "genus_1": TEICH_DIM_G1,
            "genus_2": TEICH_DIM_G2,
            "genus_3": TEICH_DIM_G3,
            "genus_5": TEICH_DIM_G5,
        },
        "dlh_generators": {
            "genus_1": DLH_G1,
            "genus_2": DLH_G2,
            "genus_3": DLH_G3,
            "genus_6": DLH_G6,
        },
        "w33_atoms": {
            "Q": Q, "LAM": LAM, "V": V, "K": K,
            "PHI3": PHI3, "PHI4": PHI4, "PHI6": PHI6,
            "J_INV": J_INV, "EDGES": EDGES, "EIG_MAX": EIG_MAX,
        },
        "theorem_cci": (
            "The real dimension of Teichmüller space T_g encodes W(3,3) atoms: "
            "T_2=MULT_K2=6, T_3=K=12, T_5=LEECH_DIM=24. "
            "DLH generator counts: 2g+1 gives Q(g=1), EIG_MAX(g=2), PHI6(g=3), PHI3(g=6). "
            "SL(2,ℤ) orders: |S|=LAM²=4, |ST|=MULT_K2=6. "
            "Pants curve counts: Q(g=2), MULT_K2(g=3), K(g=5)."
        ),
    }


def main() -> None:
    result = mcg_bridge_audit()
    out_path = os.path.join(os.path.dirname(__file__),
                            "PART_CCI_mcg_results.json")
    with open(out_path, "w") as fh:
        json.dump(result, fh, indent=2)

    n = result["check_count"]
    p = result["checks_passing"]
    status = result["status"]
    print(f"PART_CCI MCG Bridge: {status} ({p}/{n} checks pass)")
    if result["failed_checks"]:
        print(f"  FAILED: {result['failed_checks']}")


if __name__ == "__main__":
    main()
