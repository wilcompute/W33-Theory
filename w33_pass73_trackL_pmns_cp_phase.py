def jarlskog(theta_12, theta_13, theta_23, delta_cp_deg):
    """
    J = (1/8) sin(2*theta_12) sin(2*theta_23) sin(2*theta_13)^2 / sin(theta_13)
      = cos(theta_12) sin(theta_12) cos^2(theta_13) sin(theta_13)
        cos(theta_23) sin(theta_23) sin(delta_CP)
    Standard formula:
    J = sin(theta_12)cos(theta_12) sin(theta_23)cos(theta_23) sin^2(theta_13)
        * cos(theta_13) * sin(delta_CP)
    """
    t12 = np.radians(theta_12)
    t13 = np.radians(theta_13)
    t23 = np.radians(theta_23)
    d   = np.radians(delta_cp_deg)
    J = (np.sin(t12) * np.cos(t12) *
         np.sin(t23) * np.cos(t23) *
         np.sin(t13)**2 * np.cos(t13) *
         np.sin(d))
    return J


