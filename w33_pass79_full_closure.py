def gf3_rank(rows: list[list[int]], cols: int | None = None) -> int:
    if not rows:
        return 0
    mat = [[x % 3 for x in row] for row in rows if any(x % 3 for x in row)]
    if not mat:
        return 0
    ncols = cols if cols is not None else len(mat[0])
    rank = 0
    for col in range(ncols):
        pivot = next((r for r in range(rank, len(mat)) if mat[r][col] % 3), None)
        if pivot is None:
            continue
        mat[rank], mat[pivot] = mat[pivot], mat[rank]
        inv = pow(mat[rank][col] % 3, -1, 3)
        mat[rank] = [(x * inv) % 3 for x in mat[rank]]
        for r in range(len(mat)):
            if r != rank and mat[r][col] % 3:
                factor = mat[r][col] % 3
                mat[r] = [(mat[r][c] - factor * mat[rank][c]) % 3 for c in range(ncols)]
        rank += 1
        if rank == len(mat):
            break
    return rank


def in_rowspace(row: list[int], matrix: list[list[int]]) -> bool:
    cols = len(row)
    return gf3_rank(matrix, cols) == gf3_rank(matrix + [row], cols)


def symplectic(u: list[int], v: list[int], n: int) -> int:
    ux, uz = u[:n], u[n:]
    vx, vz = v[:n], v[n:]
    return (sum(ux[i] * vz[i] - uz[i] * vx[i] for i in range(n))) % 3


def sparse_row(row: list[int], n: int) -> list[dict[str, int]]:
    out = []
    for idx in range(n):
        x, z = row[idx] % 3, row[n + idx] % 3
        if x or z:
            out.append({"site": idx, "x": x, "z": z})
    return out


def cyclic_5_code_rows() -> list[list[int]]:
    """Cyclic qutrit perfect-code stabilizers generated by X Z Z^-1 X^-1 I."""
    n = 5
    rows = []
    for shift in range(4):
        x = [0] * n
        z = [0] * n
        pattern = [(0, 1, 0), (1, 0, 1), (2, 0, 2), (3, 2, 0)]
        for pos, xv, zv in pattern:
            site = (pos + shift) % n
            x[site] = xv
            z[site] = zv
        rows.append(x + z)
    return rows


def build_66_stabilizer() -> dict:
    n = 66
    rows: list[list[int]] = []
    base_rows = cyclic_5_code_rows()
    for block in range(8):
        offset = 5 * block
        for base in base_rows:
            row = [0] * (2 * n)
            for site in range(5):
                row[offset + site] = base[site]
                row[n + offset + site] = base[5 + site]
            rows.append(row)
    for site in range(40, 66):
        row = [0] * (2 * n)
        row[n + site] = 1
        rows.append(row)

    rank = gf3_rank(rows, 2 * n)
    commute = all(symplectic(a, b, n) == 0 for a, b in combinations(rows, 2))

    paulis = [(x, z) for x, z in product(range(3), repeat=2) if (x, z) != (0, 0)]
    checked = 0
    central_weight_le_2 = []
    logical_weight_le_2 = []
    for weight in [1, 2]:
        for sites in combinations(range(n), weight):
            for labels in product(paulis, repeat=weight):
                checked += 1
                err = [0] * (2 * n)
                for site, (x, z) in zip(sites, labels):
                    err[site] = x
                    err[n + site] = z
                if all(symplectic(err, h, n) == 0 for h in rows):
                    central_weight_le_2.append(sparse_row(err, n))
                    if not in_rowspace(err, rows):
                        logical_weight_le_2.append(sparse_row(err, n))
                        break
            if logical_weight_le_2:
                break
        if logical_weight_le_2:
            break

    logical = [0] * (2 * n)
    logical[1] = 1
    logical[n + 0] = 1
    logical[n + 2] = 1
    logical_weight = sum(1 for site in range(n) if logical[site] or logical[n + site])
    logical_commutes = all(symplectic(logical, h, n) == 0 for h in rows)
    logical_in_stabilizer = in_rowspace(logical, rows)

    return {
        "status": "valid_block_plus_ancilla_stabilizer_witness",
        "parameters": {
            "n": n,
            "rank_stabilizer": rank,
            "k_logical": n - rank,
            "distance": 3,
        },
        "construction": (
            "direct sum of eight cyclic qutrit [[5,1,3]]_3 perfect-code blocks "
            "plus 26 frozen single-site Z stabilizer ancillas"
        ),
        "canonical_geometric_code_claimed": False,
        "base_5_code_generator": "X Z Z^-1 X^-1 I, cyclic shifts 0..3",
        "base_5_code_rows": base_rows,
        "stabilizer_generator_count": len(rows),
        "stabilizer_matrix": rows,
        "stabilizer_generators_sparse": [sparse_row(row, n) for row in rows],
        "mutual_commutation": commute,
        "weight_1_2_errors_checked": checked,
        "centralizer_weight_1_2_count": len(central_weight_le_2),
        "nonstabilizer_logical_weight_1_2_count": len(logical_weight_le_2),
        "logical_weight_3_example_sparse": sparse_row(logical, n),
        "logical_weight_3_commutes": logical_commutes,
        "logical_weight_3_in_stabilizer": logical_in_stabilizer,
        "distance_verified": (
            rank == 58
            and n - rank == 8
            and commute
            and not logical_weight_le_2
            and logical_weight == 3
            and logical_commutes
            and not logical_in_stabilizer
        ),
        "boundary": (
            "This is an explicit finite [[66,8,3]]_3 stabilizer witness.  The "
            "still-open stronger target is a canonical geometric 66-site code whose "
            "generators are native to the K12/genus-6/toroidal carrier."
        ),
    }


