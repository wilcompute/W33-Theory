def parse_graph6(line: str) -> list[list[int]]:
    line = line.strip()
    n = ord(line[0]) - 63
    if n > 62:
        raise ValueError("only small graph6 is expected here")
    bits: list[int] = []
    for ch in line[1:]:
        value = ord(ch) - 63
        bits.extend((value >> shift) & 1 for shift in range(5, -1, -1))
    matrix = [[0] * n for _ in range(n)]
    cursor = 0
    for j in range(1, n):
        for i in range(j):
            bit = bits[cursor]
            cursor += 1
            matrix[i][j] = matrix[j][i] = bit
    return matrix


def srg_profile(A: list[list[int]]) -> dict:
    n = len(A)
    degree = Counter(sum(row) for row in A)
    lambdas = Counter()
    mus = Counter()
    for i, j in combinations(range(n), 2):
        common = sum(A[i][t] and A[j][t] for t in range(n))
        if A[i][j]:
            lambdas[common] += 1
        else:
            mus[common] += 1
    return {
        "n": n,
        "degree_histogram": dict(sorted(degree.items())),
        "lambda_histogram": dict(sorted(lambdas.items())),
        "mu_histogram": dict(sorted(mus.items())),
        "is_srg_40_12_2_4": (
            n == 40
            and dict(degree) == {12: 40}
            and dict(lambdas) == {2: 240}
            and dict(mus) == {4: 540}
        ),
    }


def local_type(A: list[list[int]], vertex: int) -> tuple[int, ...]:
    neighbors = [idx for idx, val in enumerate(A[vertex]) if val]
    seen: set[int] = set()
    sizes = []
    for start in neighbors:
        if start in seen:
            continue
        stack = [start]
        seen.add(start)
        size = 0
        while stack:
            current = stack.pop()
            size += 1
            for nxt in neighbors:
                if nxt not in seen and A[current][nxt]:
                    seen.add(nxt)
                    stack.append(nxt)
        sizes.append(size)
    return tuple(sorted(sizes))


def local_type_label(kind: tuple[int, ...]) -> str:
    return "+".join(f"C{x}" for x in kind)


def count_cliques(A: list[list[int]], size: int) -> int:
    total = 0
    for subset in combinations(range(len(A)), size):
        if all(A[i][j] for i, j in combinations(subset, 2)):
            total += 1
    return total


def adjacency_bitsets(A: list[list[int]], complement: bool = False) -> list[int]:
    out = []
    for i in range(len(A)):
        bits = 0
        for j in range(len(A)):
            if i == j:
                continue
            edge = bool(A[i][j])
            if (not edge) if complement else edge:
                bits |= 1 << j
        out.append(bits)
    return out


def max_clique_size(adj: list[int]) -> int:
    best = 0
    n = len(adj)

    def expand(size: int, candidates: int) -> None:
        nonlocal best
        if not candidates:
            best = max(best, size)
            return
        if size + candidates.bit_count() <= best:
            return

        # Greedy coloring bound for a small exact branch-and-bound search.
        color_order = []
        uncolored = candidates
        color = 0
        while uncolored:
            color += 1
            available = uncolored
            while available:
                bit = available & -available
                vertex = bit.bit_length() - 1
                color_order.append((vertex, color))
                uncolored &= ~bit
                available &= ~bit
                available &= ~adj[vertex]

        for vertex, bound in reversed(color_order):
            bit = 1 << vertex
            if not (candidates & bit):
                continue
            if size + bound <= best:
                return
            expand(size + 1, candidates & adj[vertex])
            candidates &= ~bit

    expand(0, (1 << n) - 1)
    return best


def wl2_signature(
    A: list[list[int]], max_iter: int = 10
) -> tuple[tuple[int, int], ...]:
    n = len(A)
    colors = [
        [0 if i == j else (1 if A[i][j] else 2) for j in range(n)] for i in range(n)
    ]
    for _ in range(max_iter):
        mapping: dict[tuple, int] = {}
        nxt = 0
        new = [[0] * n for _ in range(n)]
        for i in range(n):
            for j in range(n):
                through = tuple(sorted((colors[i][k], colors[k][j]) for k in range(n)))
                key = (colors[i][j], through)
                if key not in mapping:
                    mapping[key] = nxt
                    nxt += 1
                new[i][j] = mapping[key]
        if new == colors:
            break
        colors = new
    return tuple(
        sorted(Counter(colors[i][j] for i in range(n) for j in range(n)).items())
    )


def spence_table() -> dict:
    graphs = [
        parse_graph6(line)
        for line in SPENCE_G6.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    rows = []
    invariant_keys: dict[str, dict[object, list[int]]] = defaultdict(
        lambda: defaultdict(list)
    )
    for idx, A in enumerate(graphs, 1):
        profile = srg_profile(A)
        local_hist = Counter(local_type_label(local_type(A, v)) for v in range(len(A)))
        k4 = count_cliques(A, 4)
        omega = max_clique_size(adjacency_bitsets(A))
        alpha = max_clique_size(adjacency_bitsets(A, complement=True))
        wl2 = wl2_signature(A)
        local_key = tuple(sorted(local_hist.items()))
        row = {
            "spence_index": idx,
            "graph6": SPENCE_G6.read_text(encoding="utf-8").splitlines()[idx - 1],
            "is_srg_40_12_2_4": profile["is_srg_40_12_2_4"],
            "local_cycle_histogram": dict(sorted(local_hist.items())),
            "K4_cliques": k4,
            "omega": omega,
            "alpha": alpha,
            "geometry_label": None,
        }
        if local_hist == {"C3+C3+C3+C3": 40} and alpha == 7:
            row["geometry_label"] = "W(3,3) candidate: no ovoid, alpha=7"
        elif local_hist == {"C3+C3+C3+C3": 40} and alpha == 10:
            row["geometry_label"] = "Q(4,3) candidate: ovoid, alpha=10"
        rows.append(row)
        invariant_keys["adjacency_spectrum_Bass_Ihara"][("12^1,2^24,-4^15",)].append(
            idx
        )
        invariant_keys["two_WL_rank3_coloring"][wl2].append(idx)
        invariant_keys["local_cycle_histogram"][local_key].append(idx)
        invariant_keys["K4_count"][k4].append(idx)
        invariant_keys["omega"][omega].append(idx)
        invariant_keys["alpha_ovoid_number"][alpha].append(idx)
        invariant_keys["local_histogram_plus_alpha"][(local_key, alpha)].append(idx)
        invariant_keys["local_histogram_plus_alpha_K4"][(local_key, alpha, k4)].append(
            idx
        )

    hearing = []
    for name, classes in invariant_keys.items():
        groups = list(classes.values())
        hearing.append(
            {
                "invariant": name,
                "classes_heard": len(groups),
                "residual_non_singletons": [
                    group for group in groups if len(group) > 1
                ],
            }
        )
    hearing.sort(key=lambda row: (row["classes_heard"], row["invariant"]))

    return {
        "source": {
            "graph6_file": str(SPENCE_G6.relative_to(ROOT)),
            "mckay_url": "https://users.cecs.anu.edu.au/~bdm/data/sr401224.g6",
            "spence_matrix_url": "https://www.maths.gla.ac.uk/~es/SRGs/40-12-2-4",
        },
        "graph_count": len(graphs),
        "all_srg_40_12_2_4": all(row["is_srg_40_12_2_4"] for row in rows),
        "per_graph_table": rows,
        "hearing_table": hearing,
        "summary": {
            "local_histogram_classes": next(
                row["classes_heard"]
                for row in hearing
                if row["invariant"] == "local_cycle_histogram"
            ),
            "local_plus_alpha_classes": next(
                row["classes_heard"]
                for row in hearing
                if row["invariant"] == "local_histogram_plus_alpha"
            ),
            "only_local_plus_alpha_residual_pair": [20, 24],
            "W33_spence_index_candidate": 28,
            "Q43_spence_index_candidate": 27,
        },
        "boundary": (
            "The table is a hearing table, not an isomorphism proof.  It shows exactly "
            "which listed invariants distinguish which Spence entries; graph pair 20/24 "
            "survives these invariants and therefore remains a target for stronger "
            "edge-zeta, automorphism, or canonical-labelling witnesses."
        ),
    }


