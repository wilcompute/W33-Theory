def run_gap_certificate() -> dict:
    gap = shutil.which("gap") or "/usr/bin/gap"
    if not Path(gap).exists() and shutil.which(gap) is None:
        raise RuntimeError("GAP is required for Pass 79 but was not found")
    process = subprocess.run(
        [gap, "-q", str(GAP_SCRIPT)],
        cwd=ROOT,
        text=True,
        capture_output=True,
        check=True,
        timeout=60,
    )
    raw = process.stdout.replace("\\\n", "")
    parsed = {}
    for line in raw.splitlines():
        if "=" in line:
            key, value = line.strip().split("=", 1)
            parsed[key] = value

    required = {
        "point_group_order",
        "point_rank",
        "point_suborbit_sizes",
        "directed_edge_degree",
        "directed_edge_group_order",
        "directed_edge_rank",
        "directed_edge_constituents",
        "undirected_edge_degree",
        "undirected_edge_group_order",
        "undirected_edge_rank",
        "undirected_edge_constituents",
        "terwilliger_dimension",
        "terwilliger_center_dimension",
        "terwilliger_radical_dimension",
        "terwilliger_central_idempotents",
        "terwilliger_component_dimensions",
        "terwilliger_wedderburn_block_sizes",
    }
    missing = required - set(parsed)
    if missing:
        raise AssertionError(f"GAP output missing keys: {sorted(missing)}\n{raw}")

    def ints(key: str) -> list[int]:
        return [] if not parsed[key] else [int(x) for x in parsed[key].split(",")]

    def triples(key: str) -> list[dict[str, int]]:
        rows = []
        if parsed[key]:
            for chunk in parsed[key].split(","):
                idx, degree, mult = [int(x) for x in chunk.split(":")]
                rows.append(
                    {"character_index": idx, "degree": degree, "multiplicity": mult}
                )
        return rows

    directed = triples("directed_edge_constituents")
    undirected = triples("undirected_edge_constituents")
    component_dims = ints("terwilliger_component_dimensions")
    block_sizes = ints("terwilliger_wedderburn_block_sizes")

    return {
        "raw_gap_stdout": raw,
        "point_action": {
            "group": "PSp(4,3)",
            "order": int(parsed["point_group_order"]),
            "rank": int(parsed["point_rank"]),
            "suborbit_sizes": ints("point_suborbit_sizes"),
        },
        "directed_edge_action": {
            "degree": int(parsed["directed_edge_degree"]),
            "group_order": int(parsed["directed_edge_group_order"]),
            "rank": int(parsed["directed_edge_rank"]),
            "constituents": directed,
            "dimension_sum": sum(
                row["degree"] * row["multiplicity"] for row in directed
            ),
            "active_degree_multiset": [
                [row["degree"], row["multiplicity"]] for row in directed
            ],
        },
        "undirected_edge_action": {
            "degree": int(parsed["undirected_edge_degree"]),
            "group_order": int(parsed["undirected_edge_group_order"]),
            "rank": int(parsed["undirected_edge_rank"]),
            "constituents": undirected,
            "dimension_sum": sum(
                row["degree"] * row["multiplicity"] for row in undirected
            ),
            "active_degree_multiset": [
                [row["degree"], row["multiplicity"]] for row in undirected
            ],
        },
        "terwilliger_wedderburn": {
            "dimension": int(parsed["terwilliger_dimension"]),
            "center_dimension": int(parsed["terwilliger_center_dimension"]),
            "radical_dimension": int(parsed["terwilliger_radical_dimension"]),
            "central_idempotents": int(parsed["terwilliger_central_idempotents"]),
            "component_dimensions": component_dims,
            "wedderburn_block_sizes": block_sizes,
            "block_reading": "Q + Q + Q + M_2(Q) + M_3(Q)",
        },
    }


