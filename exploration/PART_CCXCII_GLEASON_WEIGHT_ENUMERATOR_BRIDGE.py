"""
Part CCXCII: Gleason's Theorem for Self-Dual Codes over GF(3) and the
Weight Enumerator Ring.

Gleason's theorem (1970) classifies weight enumerators of self-dual codes:

  Over GF(2): W in C[x, y]^{S3}, generated by x^2+y^2 and x^2*y^2*(x^2-y^2)^2
  Over GF(3): W in C[x, y]^{G}, where G is the Clifford group action.

For *Type I* self-dual codes over GF(3) (orthogonal self-dual, with all weights
divisible by 3):

The ring of invariants is generated by:
  g1 = x^4 + 8*y^4                 (degree 4)
  g2 = x^4*y^4*(x^4 - y^4)^4      (degree 16)  [actually degree 12 for Ternary]

For ternary self-dual codes (Type I over GF(3)), the standard generators are:
  phi1 = x^2 + 2*y^2                                 (weight enumerator of [2,1] repetition)
  phi2 = x^12 - 33*x^8*y^4 - 33*x^4*y^8 + y^12     (weight enumerator of ternary Golay [12,6])

A *ternary Type II* (also called "Type I with divisibility 3") code satisfies:
  - All codeword weights ≡ 0 (mod 3)
  - The weight enumerator is a polynomial in phi1 and phi2.

The ternary Golay code G12 is the primary example:
  - Length n = 12
  - Dimension k = 6
  - Min distance d = 6
  - Weight enumerator: W(x,y) = x^12 + 264*x^6*y^6 + 440*x^3*y^9 + ... 

NOTE: In this part we focus on the *invariant ring structure* and verify
explicit divisibility and symmetry conditions on the weight enumerator of
the ternary Hamming / simplex dual pair, not the Golay code itself.

All arithmetic is exact (integers / Fraction, no numpy).
"""

