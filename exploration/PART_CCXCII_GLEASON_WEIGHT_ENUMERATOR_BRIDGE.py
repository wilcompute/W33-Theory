MACWILLIAMS_DIVISOR_CORRECT = (MACWILLIAMS_DIVISOR == 81)

def macwilliams_eval(we_dual: dict, n: int, k: int, q: int) -> dict:
    """
    Apply MacWilliams transform to a weight enumerator (in dict form).
    we_dual: {weight: multiplicity} for the dual code.
    Returns we_primal: {weight: Fraction}.
    """
    size = q ** (n - k)   # = |C^perp| = divisor
    result = {}
    for w_target in range(n + 1):
        total = Fraction(0)
        for w_src, mult in we_dual.items():
            # Krawtchouk K_{w_target}(w_src; n, q):
            kraw = Fraction(0)
            for j in range(w_target + 1):
                kraw += ((-1) ** j) * Fraction((q-1) ** (w_target - j)) * \
                        comb(w_src, j) * comb(n - w_src, w_target - j)
            total += Fraction(mult) * kraw
        val = total / size
        if val != 0:
            result[w_target] = val
    return result


