# ─────────────────────────────────────────────────────────────────────────────
# Gleason-MacWilliams duality
#
# The MacWilliams transform pairs weight enumerators of dual codes:
#   W_{C^perp}(x,y) = (1/|C|) * W_C(x + (q-1)*y, x - y)
#
# For Ham(4,3) ↔ Sim(4,3):
#   W_Ham(x,y) obtained from W_Sim by MacWilliams (computed in Part CCXC).
# The Gleason framework says this pair lives in the Gleason ring.
