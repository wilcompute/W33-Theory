"""Exact triality line/rotation split of the live CP bivector shell.

The remaining open question after the family-complex-structure bridge was
whether CP on the bivector shell is purely the rotating triality plane
generated by the same family complex structure J.

The exact answer is more precise:

    not purely, but still on the same triality operator stack.

For each bivector triplet sector (the `3` and `3'` pieces of Lambda^2(4)),
the exact triality 3-cycle decomposes the real 3-space as

    3 = 1 ⊕ 2,

that is, one fixed line plus one rotating plane.

On the live CKM packet with

    sigma = (a+b)/2,
    delta = (a-b)/2,

the fixed-line and rotating-plane norms are exact:

    sector 3:
        ||fixed||^2 = 4 delta^2 / 3
        ||rot||^2   = 2 sigma^2 + 8 delta^2 / 3

    sector 3':
        ||fixed||^2 = 4 sigma^2 / 3
        ||rot||^2   = 2 sigma^2 / 3

So CP is not a separate mystery packet. It is the triality line/rotation split
of the same two family scalars sigma and delta, one exterior degree higher.
"""

from __future__ import annotations

import json
from math import sqrt
from pathlib import Path
import sys
from typing import Any

import numpy as np


ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
DEFAULT_OUTPUT_PATH = DATA_DIR / "w33_cp_triality_line_rotation_bridge_summary.json"

if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from exploration.w33_ckm_clifford_sector_separation_bridge import (
    _build_irrep_projectors,
    _permutation_matrix,
    _wedge2_rep,
    _wedge_coords,
)
from exploration.w33_tetrahedral_ckm_oscillator_bridge import _two_edge_vector
from exploration.w33_triality_phase_compression_bridge import _load_json


def build_summary() -> dict[str, Any]:
    _, wedge_projectors = _build_irrep_projectors()

    quarter_turn = _load_json("w33_quarter_turn_quark_sheet_bridge_summary.json")
    lift = _load_json("w33_two_sheet_ckm_lift_bridge_summary.json")
    a = float(quarter_turn["refined_q11_q21_quarter_turn_family"]["best_error"]["amplitude"])
    b = float(lift["second_layer_lift_edge"]["amplitude"])
    sigma = (a + b) / 2.0
    delta = (a - b) / 2.0

    live = _two_edge_vector(a, b)
    wedge_coords = _wedge_coords(np.outer(live, np.conjugate(live)).imag)

    cycle_perm = (0, 2, 3, 1)
    cycle_wedge = _wedge2_rep(_permutation_matrix(cycle_perm))

    sector_data: dict[str, dict[str, Any]] = {}
    for irrep_name in ("3", "3'"):
        projector = wedge_projectors[irrep_name]
        sector_vector = projector @ wedge_coords
        fixed_projector = (projector + projector @ cycle_wedge + projector @ (cycle_wedge @ cycle_wedge)) / 3.0
        fixed_vector = fixed_projector @ wedge_coords
        rotating_vector = sector_vector - fixed_vector
        sector_data[irrep_name] = {
            "total_norm": float(np.linalg.norm(sector_vector)),
            "fixed_line_norm": float(np.linalg.norm(fixed_vector)),
            "rotating_plane_norm": float(np.linalg.norm(rotating_vector)),
            "total_norm_squared": float(np.linalg.norm(sector_vector) ** 2),
            "fixed_line_norm_squared": float(np.linalg.norm(fixed_vector) ** 2),
            "rotating_plane_norm_squared": float(np.linalg.norm(rotating_vector) ** 2),
        }

    sector3_fixed_sq = 4.0 * delta * delta / 3.0
    sector3_rot_sq = 2.0 * sigma * sigma + 8.0 * delta * delta / 3.0
    sector3p_fixed_sq = 4.0 * sigma * sigma / 3.0
    sector3p_rot_sq = 2.0 * sigma * sigma / 3.0

    return {
        "live_packet_dictionary": {
            "a_z2": a,
            "b_z1": b,
            "sigma_half_sum": sigma,
            "delta_half_difference": delta,
        },
        "triality_line_rotation_split": sector_data,
        "exact_formula_packet": {
            "sector_3_fixed_sq": sector3_fixed_sq,
            "sector_3_rotating_sq": sector3_rot_sq,
            "sector_3prime_fixed_sq": sector3p_fixed_sq,
            "sector_3prime_rotating_sq": sector3p_rot_sq,
        },
        "cp_triality_line_rotation_theorem": {
            "each_bivector_triplet_splits_under_the_triality_cycle_as_fixed_line_plus_rotating_plane": True,
            "the_live_sector_3_fixed_line_norm_squared_is_exactly_4_delta_squared_over_3": bool(
                abs(sector_data["3"]["fixed_line_norm_squared"] - sector3_fixed_sq) < 1e-12
            ),
            "the_live_sector_3_rotating_plane_norm_squared_is_exactly_2_sigma_squared_plus_8_delta_squared_over_3": bool(
                abs(sector_data["3"]["rotating_plane_norm_squared"] - sector3_rot_sq) < 1e-12
            ),
            "the_live_sector_3prime_fixed_line_norm_squared_is_exactly_4_sigma_squared_over_3": bool(
                abs(sector_data["3'"]["fixed_line_norm_squared"] - sector3p_fixed_sq) < 1e-12
            ),
            "the_live_sector_3prime_rotating_plane_norm_squared_is_exactly_2_sigma_squared_over_3": bool(
                abs(sector_data["3'"]["rotating_plane_norm_squared"] - sector3p_rot_sq) < 1e-12
            ),
            "cp_is_therefore_the_triality_line_rotation_shadow_of_the_same_family_scalars_sigma_and_delta": True,
        },
        "interpretation": (
            "The CP shell is not purely the rotating triality plane, but it is still "
            "fully controlled by the same family scalars sigma and delta. Under the "
            "exact triality 3-cycle, each bivector triplet decomposes as a fixed line "
            "plus a rotating plane, and the live CP packet has exact line/rotation "
            "weights determined by sigma and delta. So CP is the exterior-degree-one "
            "higher shadow of the same family operator stack."
        ),
    }


def main() -> None:
    summary = build_summary()
    DEFAULT_OUTPUT_PATH.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print("=" * 72)
    print("W33 CP TRIALITY LINE-ROTATION BRIDGE")
    print("=" * 72)
    for key, value in summary["cp_triality_line_rotation_theorem"].items():
        status = "PASS" if value else "FAIL"
        print(f"  [{status}] {key}")


if __name__ == "__main__":
    main()
