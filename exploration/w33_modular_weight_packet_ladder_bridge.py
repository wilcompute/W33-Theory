"""Exact bridge from the modular weight semigroup to the W33 packet ladder.

The modular ring grammar

    M_*(SL(2,Z)) = C[E_4, E_6]

is generated by weights 4 and 6.  Earlier bridges already tied those two
weights to the W33 chart and centered-shell packets.  This bridge closes the
next layer:

    4   = chart count,
    6   = centered toroidal shell,
    8   = bosonic octet,
    10  = Phi_4 packet,
    12  = first collision weight = modular period = toroidal genus numerator,
    14  = dim(G_2),

and then checks that the later common affine/non-affine input grammar

    16, 20, 24, 36, 40

already sits inside the same modular semigroup with the exact modular
dimensions

    2, 2, 3, 4, 4.

So the modular side is not just classical background.  Its semigroup ladder is
already the old W33 packet dictionary.
"""

from __future__ import annotations

import json
from pathlib import Path
import sys
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
DEFAULT_OUTPUT_PATH = DATA_DIR / "w33_modular_weight_packet_ladder_bridge_summary.json"

if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
if str(ROOT / "exploration") not in sys.path:
    sys.path.insert(0, str(ROOT / "exploration"))

from w33_modular_dimension_formula import dim_M
from w33_modular_generator_packet_bridge import _list_monomials


def _load_json(name: str) -> dict[str, Any]:
    return json.loads((DATA_DIR / name).read_text(encoding="utf-8"))


LOW_WEIGHT_LABELS = {
    4: "chart_count",
    6: "centered_toroidal_shell",
    8: "bosonic_octet",
    10: "Phi_4_packet",
    12: "modular_period_and_toroidal_genus_numerator",
    14: "G2_dimension",
}


def build_summary() -> dict[str, Any]:
    mod12 = _load_json("w33_mod12_selector_closure_bridge_summary.json")
    heptad = _load_json("w33_toroidal_heptad_projector_bridge_summary.json")
    octet = _load_json("w33_subdominant_octet_bridge_summary.json")
    common = _load_json("w33_affine_nonaffine_common_grammar_bridge_summary.json")

    chart_count = int(mod12["mod12_selector_dictionary"]["mu"])
    centered_shell = int(heptad["dictionary"]["centered_shell_dimension"])
    bosonic_octet = int(octet["dirac_packet"]["subdominant_count"])
    phi4_packet = int(common["affine_nonaffine_common_grammar_dictionary"]["Phi4"])
    modular_period = int(mod12["mod12_selector_dictionary"]["modulus"])
    genus_numerator = int(heptad["dictionary"]["toroidal_genus_numerator"])
    g2_dimension = int(mod12["mod12_selector_dictionary"]["g2_dimension"])
    q = int(mod12["mod12_selector_dictionary"]["q"])
    lam = int(common["affine_nonaffine_common_grammar_dictionary"]["lambda"])

    low_weight_packet_dictionary = {
        4: chart_count,
        6: centered_shell,
        8: bosonic_octet,
        10: phi4_packet,
        12: modular_period,
        14: g2_dimension,
    }

    low_weight_monomials = {
        weight: {
            "label": LOW_WEIGHT_LABELS[weight],
            "weight": weight,
            "dim_M": dim_M(weight),
            "monomials": _list_monomials(weight),
        }
        for weight in sorted(LOW_WEIGHT_LABELS)
    }

    common_input_grammar = list(common["affine_nonaffine_common_grammar_dictionary"]["common_input_grammar"])
    common_input_rows = {
        weight: {
            "weight": weight,
            "dim_M": dim_M(weight),
            "monomials": _list_monomials(weight),
        }
        for weight in common_input_grammar
    }

    return {
        "modular_weight_packet_ladder_dictionary": {
            "chart_count": chart_count,
            "centered_toroidal_shell": centered_shell,
            "bosonic_octet": bosonic_octet,
            "Phi_4_packet": phi4_packet,
            "modular_period": modular_period,
            "toroidal_genus_numerator": genus_numerator,
            "G2_dimension": g2_dimension,
            "q": q,
            "lambda": lam,
            "common_input_grammar": common_input_grammar,
        },
        "low_weight_monomial_dictionary": low_weight_monomials,
        "common_input_monomial_dictionary": common_input_rows,
        "modular_weight_packet_ladder_theorem": {
            "weight_4_is_exactly_the_chart_count": chart_count == 4 and dim_M(4) == 1,
            "weight_6_is_exactly_the_centered_toroidal_shell": centered_shell == 6 and dim_M(6) == 1,
            "weight_8_is_exactly_the_bosonic_octet": bosonic_octet == 8 and dim_M(8) == 1,
            "weight_10_is_exactly_the_existing_Phi_4_packet": phi4_packet == 10 and dim_M(10) == 1,
            "weight_12_is_exactly_the_modular_period_and_toroidal_genus_numerator": (
                modular_period == genus_numerator == 12 and dim_M(12) == 2
            ),
            "weight_14_is_exactly_dim_G2": g2_dimension == 14 and dim_M(14) == 1,
            "the_first_modular_collision_is_exactly_q_times_4_equals_lambda_times_6": (
                q * 4 == lam * 6 == 12
                and _list_monomials(12) == [(3, 0), (0, 2)]
            ),
            "the_unique_low_weight_modular_ladder_4_6_8_10_14_plus_the_first_collision_12_is_the_old_W33_packet_ladder": (
                low_weight_packet_dictionary == {4: 4, 6: 6, 8: 8, 10: 10, 12: 12, 14: 14}
            ),
            "the_shared_affine_nonaffine_input_grammar_16_20_24_36_40_is_already_a_modular_subgrammar": (
                common_input_grammar == [16, 20, 24, 36, 40]
                and [dim_M(w) for w in common_input_grammar] == [2, 2, 3, 4, 4]
            ),
        },
        "interpretation": (
            "The modular semigroup generated by weights 4 and 6 already carries "
            "the old W33 packet ladder. The low unique weights 4, 6, 8, 10, 14 "
            "are exactly the chart, shell, octet, Phi_4, and G2 packets, while "
            "the first collision at weight 12 is exactly q*4 = lambda*6, i.e. "
            "the modular period and toroidal genus numerator. The later common "
            "grammar inputs 16, 20, 24, 36, 40 then sit inside the same modular "
            "semigroup with dimensions 2, 2, 3, 4, 4."
        ),
    }


def main() -> None:
    summary = build_summary()
    DEFAULT_OUTPUT_PATH.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print("=" * 72)
    print("W33 MODULAR WEIGHT PACKET LADDER BRIDGE")
    print("=" * 72)
    for key, value in summary["modular_weight_packet_ladder_theorem"].items():
        status = "PASS" if value else "FAIL"
        print(f"  [{status}] {key}")


if __name__ == "__main__":
    main()
