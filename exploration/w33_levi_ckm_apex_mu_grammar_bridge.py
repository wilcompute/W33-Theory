"""Exact apex-coordinate grammar for the Levi CKM unitarity triangle.

The standard CKM packet is already generated by the exact alphabet

    {q, mu, 5, 20, 40, 53, 43, k}.

This bridge closes the apex coordinates themselves. Since

    R_u = q^2 k / (5 * 53),
    cos^2(gamma) = q^5 / (q^5 + mu^4 * 5),
    sin^2(gamma) = mu^4 * 5 / (q^5 + mu^4 * 5),

the squared apex coordinates are exactly

    rho_bar^2 = q^9 k^2 / (5^2 * 53^2 * (q^5 + mu^4 * 5)),
    eta_bar^2 = q^4 k^2 mu^4 / (5 * 53^2 * (q^5 + mu^4 * 5)).

So the full apex packet uses the same finite alphabet, and its denominator is
the same phase denominator

    q^5 + mu^4 * 5 = 243 + 1280 = 1523.
"""

from __future__ import annotations

from fractions import Fraction
import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
DEFAULT_OUTPUT_PATH = DATA_DIR / "w33_levi_ckm_apex_mu_grammar_bridge_summary.json"


Q = 3
MU = 4
BOTT_FIVE = 5
TRIALITY_PLUS = 53
K = 12

RHO2 = Fraction(2834352, 106952675)
ETA2 = Fraction(2985984, 21390535)
COS2_GAMMA = Fraction(243, 1523)
SIN2_GAMMA = Fraction(1280, 1523)


def _fraction_report(value: Fraction) -> dict[str, Any]:
    return {"exact": str(value), "value": float(value)}


def build_summary() -> dict[str, Any]:
    phase_denominator = Q**5 + MU**4 * BOTT_FIVE
    rho2_from_grammar = Fraction(Q**9 * K * K, BOTT_FIVE**2 * TRIALITY_PLUS**2 * phase_denominator)
    eta2_from_grammar = Fraction(Q**4 * K * K * MU**4, BOTT_FIVE * TRIALITY_PLUS**2 * phase_denominator)
    tan2_from_apex = eta2_from_grammar / rho2_from_grammar

    return {
        "levi_ckm_apex_mu_grammar_dictionary": {
            "q": Q,
            "mu": MU,
            "bott_five": BOTT_FIVE,
            "triality_plus_53": TRIALITY_PLUS,
            "k": K,
            "phase_denominator_q5_plus_mu4_times_5": phase_denominator,
            "rho_bar_squared": _fraction_report(RHO2),
            "eta_bar_squared": _fraction_report(ETA2),
            "cos2_gamma": _fraction_report(COS2_GAMMA),
            "sin2_gamma": _fraction_report(SIN2_GAMMA),
            "eta2_over_rho2": _fraction_report(tan2_from_apex),
        },
        "levi_ckm_apex_mu_grammar_theorem": {
            "the_exact_phase_denominator_is_q5_plus_mu4_times_5_equals_1523": bool(
                phase_denominator == 1523
            ),
            "the_squared_real_apex_coordinate_is_exactly_q9_k2_over_25_53_squared_1523": bool(
                RHO2 == rho2_from_grammar
            ),
            "the_squared_imaginary_apex_coordinate_is_exactly_q4_k2_mu4_over_5_53_squared_1523": bool(
                ETA2 == eta2_from_grammar
            ),
            "the_apex_coordinate_ratio_eta2_over_rho2_is_exactly_mu4_5_over_q5": bool(
                tan2_from_apex == Fraction(MU**4 * BOTT_FIVE, Q**5)
            ),
            "the_apex_coordinates_and_the_gamma_phase_use_the_same_exact_phase_denominator": bool(
                COS2_GAMMA.denominator == phase_denominator
                and SIN2_GAMMA.denominator == phase_denominator
                and RHO2.denominator % phase_denominator == 0
                and ETA2.denominator % phase_denominator == 0
            ),
            "the_CKM_apex_packet_is_generated_by_the_same_exact_finite_alphabet_q_mu_5_53_k": bool(
                RHO2 == rho2_from_grammar
                and ETA2 == eta2_from_grammar
                and tan2_from_apex == Fraction(MU**4 * BOTT_FIVE, Q**5)
            ),
        },
        "interpretation": (
            "The CKM apex coordinates are not extra irrational decoration. "
            "Their squared packet is generated by the same q/mu/5/53/k alphabet "
            "as the rest of the standard CKM closure, with the shared phase "
            "denominator 1523 = q^5 + mu^4*5."
        ),
    }


def main() -> None:
    summary = build_summary()
    DEFAULT_OUTPUT_PATH.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print("=" * 72)
    print("W33 LEVI CKM APEX MU-GRAMMAR BRIDGE")
    print("=" * 72)
    for key, value in summary["levi_ckm_apex_mu_grammar_theorem"].items():
        status = "PASS" if value else "FAIL"
        print(f"  [{status}] {key}")


if __name__ == "__main__":
    main()
