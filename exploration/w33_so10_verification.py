def extend_basis(products, new_mat, tol=1e-8):
    """Check if new_mat is linearly independent of existing products"""
    M = np.column_stack([p.ravel() for p in products])
    v = new_mat.ravel()
    
    # Solve M @ c ≈ v
    c, res, _, _ = np.linalg.lstsq(M, v, rcond=None)
    reconstruction = M @ c
    error = norm(v - reconstruction) / max(norm(v), 1e-10)
    return error > tol

