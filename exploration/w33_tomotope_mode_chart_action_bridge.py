"""Faithful 12-point tomotope action on the Fourier-resolved tetrahedral packet.

The user supplied a degree-12 permutation model for the tomotope automorphism
group, generated by four involutions p0, p1, p2, p3.  The natural temptation is
to identify those 12 points with the 12 tomotope edges.  That is too naive.

Using the repo's actual 192-flag bundle, the stabilizer of one flag has order
96 but its induced action on the literal 12 tomotope edges has order only 12.
So the external degree-12 model is a different faithful permutation model of
Aut(T), not the raw edge action.

This bridge identifies the right local target for that faithful 12-point model:
the Fourier-resolved tetrahedral bridge packet

    12 = 3 local modes x 4 chart vertices.

In a suitable mode-major basis,

    A = {1,2,3,4}     radial block,
    B = {5,6,7,8}     first tangential block,
    C = {9,10,11,12}  second tangential block,

the generators become exact operations on (mode, chart):

    p1: swap radial <-> tangential-1 with chart flip lambda,
    p2: swap tangential-1 <-> tangential-2 with same chart,
    p0: swap tangential-1 <-> tangential-2 with chart flip lambda,
    p3: fix radial and apply chart flip kappa on both tangential blocks,

where

    lambda = (1 2)(3 4),
    kappa  = (1 4)(2 3).

So the faithful tomotope 12-point model is naturally the 3x4 Fourier packet,
not the raw source-major 4x3 bridge list.
"""

