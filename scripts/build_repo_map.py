"""Generate REPO_MAP.md: where everything lives, where new work goes, and how to search (2026-10-30).

    py -3 scripts/build_repo_map.py          # rewrite REPO_MAP.md from the tracked tree (counts are live; descriptions are below)

Descriptions are curated here; counts, the top-level inventory and the "undescribed" list are computed, so the map cannot silently rot:
a new top-level directory shows up under "Not yet described" until someone adds one line to DESCRIBE.
"""
import collections
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESCRIBE = {
    "analysis": "THE corpus. Pass write-ups (PASS*.md, BT*.md, YYYY-MM-DD_*.md), their producers (w33_pass*.py), manuscript inserts (*_insert.tex) and search drivers (search_drivers_NNNNN/).",
    "data": "Certificates: JSON emitted by producers (gitignored by default -- commit with `git add -f`). Query with scripts/cert_query.py.",
    "tests": "pytest regressions; tests/test_w33_passNNNNN_*.py re-run a producer and assert its certificate.",
    "papers": "Current paper projects (papers/forty_points: the Claude-track paper; appA_ledger.tex has one row per pass block).",
    "manuscripts": "Older manuscript sources and per-part TeX.",
    "docs": "Website (docs/index.html -- encyclopedic; grep it before claiming anything) and docs/pdf/ copies of built PDFs.",
    "scripts": "Tooling: search front door (find.py), guards/hooks (check_*.py), index builders, CI helpers.",
    "formal": "Lean 4 library (W33/**); built by lake in CI (`lake build --wfail`).",
    "exploration": "Earlier exploratory scripts (PART_* series); importable from tests.",
    "archive": "Retired material, history preserved by git mv. archive/root_<kind>/ = files moved out of the root by scripts/repo_hygiene.py.",
    "tools": "Vendored/auxiliary tools.",
    "bootstrap": "Chunk-encoded payloads from remote batches (verify with scripts/check_bootstrap_payloads.py).",
    "committed_artifacts": "Frozen artifacts referenced by older passes.",
    "pillars": "Pillar series (structured theory modules).",
    "bundles": "Delivered bundles (reports + certificates).",
    "legacy": "Legacy code kept for reproducibility.",
    "artifacts": "Generated artifacts kept for reference.",
    "rtl": "Hardware description (RTL) for the holonet machine.",
    "paper": "Earlier single-paper workspace.",
    "src": "Python package sources.",
    "w33": "Importable `w33` Python package.",
    "proofs": "Proof write-ups.",
    "lib": "Shared libraries.",
    "hardware": "Hardware specs and JSON configs.",
    "passes": "Early pass files (indexed by the results index).",
    ".github": "CI: workflows/ (~900; most are path-filtered per pass) plus the freeze bot.",
    ".continuity": "Continuity decision memory (managed by the continuity CLI; do not hand-edit).",
}


def main():
    files = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace").stdout.splitlines()
    top = collections.Counter(f.split("/")[0] for f in files if "/" in f)
    rootfiles = [f for f in files if "/" not in f]
    kinds = collections.Counter(Path(f).suffix.lower() or "(none)" for f in rootfiles)
    L = ["# Repository map", "",
         "Generated by `py -3 scripts/build_repo_map.py` -- counts are from the tracked tree at generation time.", "",
         "## Find before you write (the rediscovery protocol, made fast)", "",
         "| question | command |", "|---|---|",
         "| has this result / formula / integer / code parameter appeared anywhere? (live tree + commit subjects, oldest owner first) | `py -3 scripts/find.py \"<result>\"` (`-E` regex, `-i`, `--certs` for data/*.json, `--repos` for the other repositories) |",
         "| full first-commit dating across every repository | `py -3 scripts/check_prior_art_all_repos.py \"<regex>\"` |",
         "| which certificate asserts a value, under which key? | `py -3 scripts/cert_query.py` (DuckDB over data/**/*.json) |",
         "| result -> file inverted index (prose, witnesses, ledger) | `RESULTS_INDEX.md` (rebuild: `py -3 analysis/build_results_index.py`) |",
         "| JSON key names used by certificates | `KEY_VOCABULARY.md` |",
         "| [[n,k,d]] parameters in every repository | `CODE_PARAMETER_INDEX_ALL_REPOS.md` (`py -3 scripts/code_parameter_index_all_repos.py`) |",
         "| history without the formula-freeze bot | `git log --invert-grep --grep=\"Pass 398: freeze\"` |", "",
         "## Health checks", "",
         "| check | command |", "|---|---|",
         "| bootstrap payloads intact? | `py -3 scripts/check_bootstrap_payloads.py` |",
         "| every manuscript builds? | `py -3 scripts/compile_sweep.py` (undefined group macros: `py -3 scripts/fix_undefined_group_macros.py <file>.tex`) |",
         "| root clutter that can be archived safely | `py -3 scripts/repo_hygiene.py report` / `plan` / `apply` |",
         "| ownership-resolution selftest | `py -3 scripts/first_appearance.py --selftest` |", "",
         "## Where new work goes", "",
         "- A pass block: `analysis/PASS<a>_<b>_<TOPIC>.md` (write-up), `analysis/w33_pass<a>_to_<b>_<topic>.py` (producer -> `data/w33_pass<a>_to_<b>_<topic>.json`), "
         "`tests/test_w33_pass<a>_to_<b>.py`, drivers in `analysis/search_drivers_<n>/` (commit every JSON a producer reads; large raw outputs -> a manifest + regeneration command), "
         "and a ledger row in `papers/forty_points/appA_ledger.tex` or the shared manuscript tail.",
         "- Never at the repository root: new root files are invisible to tidy tooling and to several indices. Scratch belongs in the gitignored `/.research_*` or `/.sage_scratch/`.",
         "- Reserve pass numbers with an empty commit first (CLAUDE.md).", "",
         "## Top-level directories", "", "| directory | tracked files | what it is |", "|---|---:|---|"]
    for d, n in sorted(top.items(), key=lambda t: -t[1]):
        if d in DESCRIBE:
            L.append(f"| `{d}/` | {n} | {DESCRIBE[d]} |")
    und = [(d, n) for d, n in sorted(top.items(), key=lambda t: -t[1]) if d not in DESCRIBE]
    L += ["", f"## Root files ({len(rootfiles)})", "",
          "Root files that stay are importable Python modules, files other files reference by name, and the indexed corpus globs "
          "(PASS*.md, AUDIT*.md, BT*.md, PART*.md, *.tex). By type: " + ", ".join(f"{k} {v}" for k, v in kinds.most_common()) + ".", "",
          f"## Not yet described ({len(und)} directories -- add a line to DESCRIBE in scripts/build_repo_map.py)", "",
          ", ".join(f"`{d}/` ({n})" for d, n in und), ""]
    (ROOT / "REPO_MAP.md").write_text("\n".join(L), encoding="utf-8")
    print(f"REPO_MAP.md: {len(top)} directories ({len(top) - len(und)} described), {len(rootfiles)} root files")


if __name__ == "__main__":
    main()
