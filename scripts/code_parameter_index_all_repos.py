"""Cross-repository code-parameter index (Pass 12454).

Usage:  py -3 scripts/code_parameter_index_all_repos.py [--out CODE_PARAMETER_INDEX_ALL_REPOS.md] [--roots C:/Repos]

git-greps every primary repository (snapshot clones skipped, see check_prior_art_all_repos.py) for quantum-code parameters [[n,k,d]]
and [[n,k,d]]_q and writes an inverted index: parameter -> repositories, number of files, and the earliest first-added date among the
files carrying it (with that file).  This is the RESULT index of CLAUDE.md lifted from one repository to all of them: grep it for the
parameters of a code before calling the code new.
"""
import os
import re
import subprocess
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check_prior_art_all_repos import DEFAULT_ROOTS, SNAPSHOT_HINTS, first_added, repos_under

PAT = r'\[\[ *[0-9]+ *, *[0-9]+ *, *[0-9]+ *\]\](_[0-9]+)?'
RX = re.compile(r'\[\[ *(\d+) *, *(\d+) *, *(\d+) *\]\](?:_(\d+))?')


def main():
    args = sys.argv[1:]
    out = 'CODE_PARAMETER_INDEX_ALL_REPOS.md'
    roots = DEFAULT_ROOTS
    if '--out' in args:
        out = args[args.index('--out') + 1]
    if '--roots' in args:
        roots = args[args.index('--roots') + 1].split(',')
    hits = defaultdict(lambda: defaultdict(set))          # param -> repo -> files
    for root in roots:
        for repo in repos_under(root):
            name = os.path.basename(repo)
            if any(h in name for h in SNAPSHOT_HINTS):
                continue
            r = subprocess.run(['git', '-C', repo, 'grep', '-I', '-o', '-E', PAT, '--', '*.md', '*.py', '*.tex'],
                               capture_output=True, text=True, encoding='utf-8', errors='replace')
            for line in r.stdout.splitlines():
                path, _, m = line.partition(':')
                g = RX.search(m)
                if g:
                    n, k, d, qq = g.groups()
                    hits[(int(n), int(k), int(d), int(qq) if qq else 2)][repo].add(path)
            print(name, sum(1 for p in hits for _ in [p] if repo in hits[p]), 'parameters', flush=True)
    rows = []
    for p in sorted(hits):
        files = [(repo, f) for repo, fs in hits[p].items() for f in fs]
        best = None
        for repo, f in sorted(files)[:6]:                  # dating every file is slow; date a bounded sample, report it as such
            d = first_added(repo, os.path.join(repo, f))
            if d != 'untracked' and (best is None or d < best[0]):
                best = (d, os.path.basename(repo), f)
        rows.append((p, sorted({os.path.basename(r) for r in hits[p]}), len(files), best))
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write('# Code-parameter index, all repositories\n\nGenerated by `scripts/code_parameter_index_all_repos.py` (Pass 12454). '
                 'q = 2 unless a subscript was written. Earliest date is over a sample of at most six files per parameter.\n\n'
                 '| [[n,k,d]]_q | repositories | files | earliest dated file |\n|---|---|---|---|\n')
        for (n, k, d, q), reps, nf, best in rows:
            b = f'{best[0]} {best[1]}:{best[2]}' if best else '-'
            fh.write(f'| [[{n},{k},{d}]]_{q} | {", ".join(reps)} | {nf} | {b} |\n')
    print(len(rows), 'parameters written to', out)


if __name__ == '__main__':
    main()
