#!/usr/bin/env python3
"""Part DCXVII: tomotope/toroidal universality fixed-point bridge.

Outside-the-box synthesis layer:
    21 -> 42 -> 84 -> 168

This script proves that the full bridge chain is generated by one base shell (21)
under a binary ladder, while remaining compatible with:
  - Z2 swap symmetry,
  - Burnside quotient,
  - weighted closure,
  - linear/quadratic horizon duality.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DCXII_PATH = ROOT / "data" / "tomotope_toroidal_commutative_closure_bridge.json"
DCXIV_PATH = ROOT / "data" / "tomotope_toroidal_z2_orbit_quotient_bridge.json"
DCXVI_PATH = ROOT / "data" / "tomotope_toroidal_z2_horizon_invariance_bridge.json"
OUT_PATH = ROOT / "data" / "tomotope_toroidal_universality_fixed_point_bridge.json"


def _load_json_or_build(path: Path, module_name: str) -> dict[str, Any]:
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    module = __import__(module_name, fromlist=["build_bridge"])
    return module.build_bridge()


@dataclass(frozen=True)
class UniversalitySummary:
    base_shell: int
    oriented_shell: int
    quotient_shell: int
    weighted_shell: int
    linear_half_horizon: int
    linear_packet_horizon: int
    energy_half_horizon: int
    energy_packet_horizon: int
    all_identities_hold: bool


def build_bridge() -> dict[str, Any]:
    dcxii = _load_json_or_build(
        DCXII_PATH, "scripts.tomotope_toroidal_commutative_closure_bridge"
    )
    dcxiv = _load_json_or_build(
        DCXIV_PATH, "scripts.tomotope_toroidal_z2_orbit_quotient_bridge"
    )
    dcxvi = _load_json_or_build(
        DCXVI_PATH, "scripts.tomotope_toroidal_z2_horizon_invariance_bridge"
    )

    base = int(dcxii["summary"]["half_split_value"])  # 21
    oriented = int(dcxii["summary"]["transport_total"])  # 42
    weighted = int(dcxii["summary"]["weighted_total"])  # 168
    quotient = int(dcxiv["summary"]["weighted_orbit_count"])  # 84

    l_half = int(dcxvi["summary"]["forward_half_horizon"])  # 8
    l_packet = int(dcxvi["summary"]["forward_packet_horizon"])  # 14
    e_half = int(dcxvi["summary"]["energy_half_horizon"])  # 4
    e_packet = int(dcxvi["summary"]["energy_packet_horizon"])  # 7

    ladder = [base * (2**k) for k in range(4)]
    expected_ladder = [21, 42, 84, 168]

    normalized = {
        "base": base / base,
        "oriented": oriented / base,
        "quotient": quotient / base,
        "weighted": weighted / base,
    }

    identities = {
        "upstream_dcxii_ok": bool(dcxii["summary"]["all_identities_hold"]),
        "upstream_dcxiv_ok": bool(dcxiv["summary"]["all_identities_hold"]),
        "upstream_dcxvi_ok": bool(dcxvi["summary"]["all_identities_hold"]),
        "binary_ladder_exact": ladder == expected_ladder,
        "base_to_oriented_double": oriented == 2 * base,
        "oriented_to_quotient_double": quotient == 2 * oriented,
        "quotient_to_weighted_double": weighted == 2 * quotient,
        "weighted_equals_8_times_base": weighted == 8 * base,
        "z2_orbit_halving": quotient == weighted // 2,
        "normalized_is_power_of_two": normalized == {
            "base": 1.0,
            "oriented": 2.0,
            "quotient": 4.0,
            "weighted": 8.0,
        },
        "horizon_duality_half": l_half == 2 * e_half,
        "horizon_duality_packet": l_packet == 2 * e_packet,
        "horizon_pairs_exact": (l_half, l_packet, e_half, e_packet) == (8, 14, 4, 7),
    }

    summary = UniversalitySummary(
        base_shell=base,
        oriented_shell=oriented,
        quotient_shell=quotient,
        weighted_shell=weighted,
        linear_half_horizon=l_half,
        linear_packet_horizon=l_packet,
        energy_half_horizon=e_half,
        energy_packet_horizon=e_packet,
        all_identities_hold=all(identities.values()),
    )

    return {
        "summary": asdict(summary),
        "binary_ladder": expected_ladder,
        "normalized_ladder": normalized,
        "identities": identities,
        "notes": (
            "DCXVII universality certificate: all current tomotope/toroidal bridges "
            "close to a single fixed-point ladder 21*{1,2,4,8}, with swap quotient, "
            "weighted closure, and horizon duality commuting exactly."
        ),
    }


def write_bridge(path: Path = OUT_PATH) -> Path:
    payload = build_bridge()
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return path


def main() -> None:
    out = write_bridge()
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
