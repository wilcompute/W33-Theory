"""Regenerate the root-level PART_*_results.json files that tests read (2026-10-30).

Root *_results.json are gitignored (/*_results.json: "regenerated by the passes that own them"), so a fresh checkout -- and CI -- has
none of them, and every test that opens one fails at collection (9 of the 18 local collection errors on 2026-10-30).  Producers also
read each other's outputs, so this runs to a FIXED POINT: each pass runs, for every still-missing target, every script that names it,
until a pass creates nothing new.

    py -3 scripts/regenerate_root_results.py            # targets = PART_*_results.json named by tests/*.py and missing
    py -3 scripts/regenerate_root_results.py --collection   # only the files whose absence breaks test COLLECTION (CI)
    py -3 scripts/regenerate_root_results.py --list     # show targets and candidate producers only
"""
import os
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RX = re.compile(r"PART_[A-Za-z0-9_]+_results\.json")
TIMEOUT = 600
# root outputs opened at MODULE level by tests, so their absence aborts collection (local --collect-only, 2026-10-30)
COLLECTION_BREAKERS = ["PART_CCXV_grand_unification_results.json", "PART_CCXVI_susy_breaking_results.json",
                       "PART_CCXVII_string_landscape_results.json", "PART_MCLXIII_TEMPORAL_SELF_ENTANGLED_QUTRIT_results.json",
                       "PART_MCLXIX_COMMENSURATION_CLOCK_results.json", "PART_MCLXXVIII_SUPERBEAT_PRIME_HORIZON_results.json",
                       "PART_MCLXXXII_Q4_TOMOTOPE_REYE_DOUBLE_COVER_results.json",
                       "PART_MCXCII_REYE_K12_ORIENTABLE_HORIZON_COMPLETION_results.json"]


def git(*a):
    return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace").stdout


def main():
    names_in_tests = set()
    for t in (ROOT / "tests").glob("test_*.py"):
        names_in_tests |= set(RX.findall(t.read_text(encoding="utf-8", errors="ignore")))
    py = [p for p in git("ls-files", "*.py").splitlines() if not p.startswith("tests/")]
    mentions = {}
    for p in py:
        try:
            txt = (ROOT / p).read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        for n in set(RX.findall(txt)):
            mentions.setdefault(n, []).append(p)
    # a producer is a script that names the target and writes json (heuristic: 'json.dump' or 'write_text' in it)
    def producers(n):
        out = []
        for p in mentions.get(n, []):
            txt = (ROOT / p).read_text(encoding="utf-8", errors="ignore")
            if "json.dump" in txt or "write_text" in txt:
                out.append(p)
        # the script whose own name matches the target first
        key = n.replace("_results.json", "").lower().split("_", 2)[-1]
        return sorted(out, key=lambda p: (key not in p.lower(), len(p)))
    explicit = [a for a in sys.argv[1:] if a.endswith("_results.json")]
    if explicit or "--collection" in sys.argv:
        names_in_tests = set(explicit or COLLECTION_BREAKERS)
    targets = sorted(n for n in names_in_tests if not (ROOT / n).exists())
    if "--list" in sys.argv:
        for n in targets:
            print(n, "<-", producers(n)[:5])
        return 0
    env = dict(os.environ, PYTHONIOENCODING="utf-8", MPLBACKEND="Agg")
    tried = set(); made = []
    for rnd in range(15):
        missing = [n for n in targets if not (ROOT / n).exists()]
        if not missing:
            break
        # also chase dependencies: anything a candidate producer reads that is missing becomes a target
        new = 0
        for n in missing:
            for p in producers(n)[:6]:
                if (p, rnd) in tried or (ROOT / n).exists():
                    continue
                tried.add((p, rnd)); t0 = time.time()
                try:
                    subprocess.run([sys.executable, str(ROOT / p)], cwd=ROOT, env=env, capture_output=True, timeout=TIMEOUT)
                except subprocess.TimeoutExpired:
                    pass
                for m in RX.findall((ROOT / p).read_text(encoding="utf-8", errors="ignore")):
                    if m not in targets and not (ROOT / m).exists():
                        targets.append(m)
                if (ROOT / n).exists():
                    made.append(n); new += 1
                    print(f"round {rnd}: {n} <- {p} ({time.time() - t0:.0f}s)", flush=True)
        if new == 0 and rnd > 0:
            break
    still = [n for n in names_in_tests if not (ROOT / n).exists()]
    print(f"made {len(made)}; still missing {len(still)}: {sorted(still)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
